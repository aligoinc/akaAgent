CREATE OR REPLACE FUNCTION public.aka_agent_sync_copied_data_group_origins(
  p_source_membership_id bigint,
  p_target_membership_id bigint,
  p_force_source_primary boolean DEFAULT false
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_preferred_origin_id bigint;
BEGIN
  IF p_source_membership_id IS NULL
    OR p_target_membership_id IS NULL
    OR p_source_membership_id = p_target_membership_id
    OR NOT EXISTS (
      SELECT 1
      FROM public.auto_account_contact_group_members AS source_member
      JOIN public.auto_account_contact_group_members AS target_member
        ON target_member.id = p_target_membership_id
       AND target_member.contact_id = source_member.contact_id
      JOIN public.auto_account_contact_groups AS source_group
        ON source_group.id = source_member.group_id
       AND source_group.purpose = 'data_group'
      JOIN public.auto_account_contact_groups AS target_group
        ON target_group.id = target_member.group_id
       AND target_group.purpose = 'data_group'
       AND target_group.staff_id IS NOT DISTINCT FROM source_group.staff_id
       AND target_group.organization_id IS NOT DISTINCT FROM source_group.organization_id
      WHERE source_member.id = p_source_membership_id
        AND source_member.is_delete = false
        AND target_member.is_delete = false
    )
  THEN
    RAISE EXCEPTION 'invalid_data_group_origin_copy';
  END IF;

  -- ON CONFLICT DO NOTHING in the v186 move writer can meet a historical
  -- inactive identity. Reactivate every exact origin which is current on the
  -- source; this keeps provenance and primary selection in agreement.
  UPDATE public.auto_account_contact_group_member_origins AS target_origin
  SET is_current = true,
      updated_at = clock_timestamp()
  FROM public.auto_account_contact_group_member_origins AS source_origin
  WHERE source_origin.membership_id = p_source_membership_id
    AND source_origin.is_current = true
    AND target_origin.membership_id = p_target_membership_id
    AND target_origin.kind = source_origin.kind
    AND target_origin.dataset_id IS NOT DISTINCT FROM source_origin.dataset_id
    AND target_origin.batch_id IS NOT DISTINCT FROM source_origin.batch_id
    AND target_origin.source_account_id IS NOT DISTINCT FROM source_origin.source_account_id
    AND target_origin.automation_detail_id IS NOT DISTINCT FROM source_origin.automation_detail_id
    AND target_origin.source_name_snapshot IS NOT DISTINCT FROM source_origin.source_name_snapshot
    AND target_origin.relationship_kind IS NOT DISTINCT FROM source_origin.relationship_kind
    AND target_origin.is_current = false;

  SELECT target_origin.id
  INTO v_preferred_origin_id
  FROM public.auto_account_contact_group_members AS source_member
  JOIN public.auto_account_contact_group_member_origins AS source_origin
    ON source_origin.id = source_member.primary_origin_id
   AND source_origin.membership_id = source_member.id
   AND source_origin.is_current = true
  JOIN public.auto_account_contact_group_member_origins AS target_origin
    ON target_origin.membership_id = p_target_membership_id
   AND target_origin.kind = source_origin.kind
   AND target_origin.dataset_id IS NOT DISTINCT FROM source_origin.dataset_id
   AND target_origin.batch_id IS NOT DISTINCT FROM source_origin.batch_id
   AND target_origin.source_account_id IS NOT DISTINCT FROM source_origin.source_account_id
   AND target_origin.automation_detail_id IS NOT DISTINCT FROM source_origin.automation_detail_id
   AND target_origin.source_name_snapshot IS NOT DISTINCT FROM source_origin.source_name_snapshot
   AND target_origin.relationship_kind IS NOT DISTINCT FROM source_origin.relationship_kind
   AND target_origin.is_current = true
  WHERE source_member.id = p_source_membership_id
  ORDER BY target_origin.created_at, target_origin.id
  LIMIT 1;

  PERFORM public.aka_agent_sync_data_group_member_primary_origin(
    p_target_membership_id,
    v_preferred_origin_id,
    COALESCE(p_force_source_primary, false) AND v_preferred_origin_id IS NOT NULL
  );
END;
$$;

