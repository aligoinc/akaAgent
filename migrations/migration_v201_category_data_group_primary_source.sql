CREATE OR REPLACE FUNCTION public.aka_agent_data_group_source_code(
  p_origin_kind text
)
RETURNS text
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
SET search_path = pg_catalog, public
AS $$
  SELECT CASE lower(btrim(COALESCE(p_origin_kind, '')))
    WHEN 'manual' THEN 'upload'
    WHEN 'upload' THEN 'upload'
    WHEN 'scan' THEN 'scan'
    WHEN 'automation' THEN 'automation'
    ELSE NULL
  END;
$$;

CREATE OR REPLACE FUNCTION public.aka_agent_data_group_source_category_item_id(
  p_origin_kind text
)
RETURNS bigint
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  SELECT category_item.id
  FROM public.category_type AS category_type
  JOIN public.category_item AS category_item
    ON category_item.category_type_id = category_type.id
  WHERE category_type.namespace = 'common'
    AND category_type.code = 'data_source'
    AND category_type.managed_by = 'system'
    AND category_item.managed_by = 'system'
    AND category_item.code = public.aka_agent_data_group_source_code(p_origin_kind)
  ORDER BY category_item.id
  LIMIT 1;
$$;

