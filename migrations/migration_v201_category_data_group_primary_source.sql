CREATE TABLE IF NOT EXISTS public.category_type (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  namespace text NOT NULL DEFAULT 'common',
  code text NOT NULL,
  name text NOT NULL,
  managed_by text NOT NULL DEFAULT 'system',
  description text,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT category_type_namespace_check CHECK (
    namespace = lower(btrim(namespace))
    AND namespace ~ '^[a-z][a-z0-9_.-]{0,127}$'
  ),
  CONSTRAINT category_type_code_check CHECK (
    code = lower(btrim(code))
    AND code ~ '^[a-z][a-z0-9_.-]{0,127}$'
  ),
  CONSTRAINT category_type_name_check CHECK (
    length(btrim(name)) BETWEEN 1 AND 255
  ),
  CONSTRAINT category_type_managed_by_check CHECK (
    managed_by IN ('manual', 'sql_server_sync', 'system')
  ),
  CONSTRAINT uq_category_type_namespace_code UNIQUE (namespace, code)
);

CREATE TABLE IF NOT EXISTS public.category_item (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_type_id bigint NOT NULL
    REFERENCES public.category_type(id) ON DELETE RESTRICT,
  code text NOT NULL,
  name text NOT NULL,
  managed_by text NOT NULL DEFAULT 'system',
  description text,
  sort_order integer NOT NULL DEFAULT 0,
  color text,
  external_id text,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT category_item_code_check CHECK (
    code = lower(btrim(code))
    AND code ~ '^[a-z][a-z0-9_.-]{0,127}$'
  ),
  CONSTRAINT category_item_name_check CHECK (
    length(btrim(name)) BETWEEN 1 AND 255
  ),
  CONSTRAINT category_item_managed_by_check CHECK (
    managed_by IN ('manual', 'sql_server_sync', 'system')
  ),
  CONSTRAINT category_item_color_check CHECK (
    color IS NULL OR color ~ '^#[0-9A-Fa-f]{6}([0-9A-Fa-f]{2})?$'
  ),
  CONSTRAINT category_item_metadata_check CHECK (
    jsonb_typeof(metadata) = 'object'
  ),
  CONSTRAINT category_item_sort_order_check CHECK (sort_order >= 0),
  CONSTRAINT uq_category_item_type_code UNIQUE (category_type_id, code),
  CONSTRAINT uq_category_item_type_external_id UNIQUE (category_type_id, external_id)
);

