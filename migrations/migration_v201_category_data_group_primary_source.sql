CREATE OR REPLACE FUNCTION public.aka_agent_refresh_data_group_primary_from_origin()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
  -- A new/reactivated membership deliberately has no primary. Its first
  -- current mapped origin becomes the source of that activation. Existing
  -- memberships keep their non-NULL pointer here; retirement is repaired by
  -- the deferred trigger below using the transaction's final origin state.
  IF NEW.is_current
    AND NEW.source_category_item_id IS NOT NULL
    AND EXISTS (
      SELECT 1
      FROM public.auto_account_contact_group_members AS member
      WHERE member.id = NEW.membership_id
        AND member.primary_origin_id IS NULL
        AND member.is_delete = false
    )
  THEN
    PERFORM public.aka_agent_sync_data_group_member_primary_origin(
      NEW.membership_id,
      NEW.id
    );
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_aka_agent_refresh_data_group_primary_from_origin
  ON public.auto_account_contact_group_member_origins;
CREATE TRIGGER trg_aka_agent_refresh_data_group_primary_from_origin
AFTER INSERT OR UPDATE OF
  membership_id,
  kind,
  source_category_item_id,
  is_current
ON public.auto_account_contact_group_member_origins
FOR EACH ROW
EXECUTE FUNCTION public.aka_agent_refresh_data_group_primary_from_origin();

CREATE OR REPLACE FUNCTION public.aka_agent_repair_data_group_primary_from_origin()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_replacement_origin_id bigint;
BEGIN
  IF TG_OP = 'DELETE' THEN
    PERFORM public.aka_agent_sync_data_group_member_primary_origin(
      OLD.membership_id
    );
    RETURN OLD;
  END IF;

  IF OLD.membership_id IS DISTINCT FROM NEW.membership_id
    AND EXISTS (
      SELECT 1
      FROM public.auto_account_contact_group_members AS member
      WHERE member.id = OLD.membership_id
        AND member.primary_origin_id = NEW.id
    )
  THEN
    PERFORM public.aka_agent_sync_data_group_member_primary_origin(
      OLD.membership_id
    );
  END IF;

  IF (
      OLD.membership_id IS DISTINCT FROM NEW.membership_id
      OR (OLD.is_current AND NOT NEW.is_current)
      OR OLD.kind IS DISTINCT FROM NEW.kind
      OR OLD.source_category_item_id IS DISTINCT FROM NEW.source_category_item_id
    )
    AND EXISTS (
      SELECT 1
      FROM public.auto_account_contact_group_members AS member
      WHERE member.id = NEW.membership_id
        AND member.primary_origin_id = NEW.id
  )
  THEN
    -- Dataset refresh can replace an origin identity (for example after a
    -- dataset rename or relationship change). If the retired origin was the
    -- displayed primary, transfer that primary to the final current origin of
    -- the same dataset. A genuine removal has no such replacement and falls
    -- back to the oldest other current mapped origin.
    IF OLD.is_current
      AND NOT NEW.is_current
      AND OLD.dataset_id IS NOT NULL
    THEN
      SELECT origin.id
      INTO v_replacement_origin_id
      FROM public.auto_account_contact_group_member_origins AS origin
      JOIN public.category_item AS category_item
        ON category_item.id = origin.source_category_item_id
       AND category_item.is_active = true
       AND category_item.managed_by = 'system'
       AND category_item.code = public.aka_agent_data_group_source_code(origin.kind)
      JOIN public.category_type AS category_type
        ON category_type.id = category_item.category_type_id
       AND category_type.namespace = 'common'
       AND category_type.code = 'data_source'
       AND category_type.managed_by = 'system'
       AND category_type.is_active = true
      WHERE origin.membership_id = NEW.membership_id
        AND origin.dataset_id = OLD.dataset_id
        AND origin.is_current = true
      ORDER BY
        (origin.id = NEW.id) DESC,
        origin.updated_at DESC,
        origin.created_at DESC,
        origin.id DESC
      LIMIT 1;
    END IF;

    PERFORM public.aka_agent_sync_data_group_member_primary_origin(
      NEW.membership_id,
      v_replacement_origin_id,
      v_replacement_origin_id IS NOT NULL
    );
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_aka_agent_deferred_repair_data_group_primary_from_origin
  ON public.auto_account_contact_group_member_origins;
CREATE CONSTRAINT TRIGGER trg_aka_agent_deferred_repair_data_group_primary_from_origin
AFTER UPDATE OR DELETE
ON public.auto_account_contact_group_member_origins
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION public.aka_agent_repair_data_group_primary_from_origin();

CREATE OR REPLACE FUNCTION public.aka_agent_guard_data_group_member_primary_origin()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM public.auto_account_contact_groups AS contact_group
    WHERE contact_group.id = NEW.group_id
      AND contact_group.purpose = 'data_group'
  ) THEN
    NEW.primary_origin_id := NULL;
    RETURN NEW;
  END IF;

  IF NEW.is_delete THEN
    NEW.primary_origin_id := NULL;
    RETURN NEW;
  END IF;

  IF NEW.primary_origin_id IS NOT NULL AND NOT EXISTS (
    SELECT 1
    FROM public.auto_account_contact_group_member_origins AS origin
    JOIN public.category_item AS category_item
      ON category_item.id = origin.source_category_item_id
     AND category_item.is_active = true
     AND category_item.managed_by = 'system'
     AND category_item.code = public.aka_agent_data_group_source_code(origin.kind)
    JOIN public.category_type AS category_type
      ON category_type.id = category_item.category_type_id
     AND category_type.namespace = 'common'
     AND category_type.code = 'data_source'
     AND category_type.managed_by = 'system'
     AND category_type.is_active = true
    WHERE origin.id = NEW.primary_origin_id
      AND origin.membership_id = NEW.id
      AND origin.is_current = true
  ) THEN
    RAISE EXCEPTION 'invalid_data_group_member_primary_origin';
  END IF;

  RETURN NEW;
END;
$$;

