  p_dataset_ids bigint[] DEFAULT NULL,
  p_ids bigint[] DEFAULT NULL,
  p_exclude_ids bigint[] DEFAULT NULL,
  p_offset integer DEFAULT 0,
  p_limit integer DEFAULT 100
)
RETURNS TABLE (
  id bigint,
  group_id bigint,
  contact_id bigint,
  name text,
  uid text,
  url text,
  phone text,
  email text,
  info1 text,
  info2 text,
  info3 text,
  info4 text,
  info5 text,
