-- Shared category catalog and one stable displayed source per Data Group member.
--
-- Provenance remains additive: a membership may keep many current origins.  The
-- primary pointer is only the source displayed by list APIs.  Once selected it
-- remains stable while that exact origin is current and its shared category is
-- active.  A retired source falls back to the oldest remaining current mapped
-- origin, so a later duplicate observation never silently changes the label.

BEGIN;

