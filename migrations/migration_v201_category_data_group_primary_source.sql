    FROM public.auto_account_contact_group_members AS member
    JOIN public.auto_account_contact_groups AS contact_group
      ON contact_group.id = member.group_id
     AND contact_group.purpose = 'data_group'
    WHERE member.id = origin.membership_id
  );

-- Keep an already-valid sticky primary on rerun. Clear only inactive/invalid
-- pointers, then deterministically fill missing values old-first.
UPDATE public.auto_account_contact_group_members AS member
SET primary_origin_id = NULL
WHERE member.primary_origin_id IS NOT NULL
  AND (
    member.is_delete = true
    OR NOT EXISTS (
      SELECT 1
      FROM public.auto_account_contact_groups AS contact_group
      WHERE contact_group.id = member.group_id
        AND contact_group.purpose = 'data_group'
    )
    OR NOT EXISTS (
      SELECT 1
      FROM public.auto_account_contact_group_member_origins AS origin
      JOIN public.category_item AS category_item
        ON category_item.id = origin.source_category_item_id
       AND category_item.is_active = true
       AND category_item.managed_by = 'system'
       AND category_item.code = public.aka_agent_data_group_source_code(origin.kind)
      JOIN public.category_type AS category_type
        ON category_type.id = category_item.category_type_id
       AND category_type.namespace = 'common'
       AND category_type.code = 'data_source'
       AND category_type.managed_by = 'system'
       AND category_type.is_active = true
      WHERE origin.id = member.primary_origin_id
        AND origin.membership_id = member.id
        AND origin.is_current = true
    )
  );

WITH ranked_primary AS (
  SELECT
    origin.membership_id,
    origin.id,
    row_number() OVER (
      PARTITION BY origin.membership_id
      ORDER BY origin.created_at, origin.id
    ) AS source_rank
  FROM public.auto_account_contact_group_member_origins AS origin
  JOIN public.auto_account_contact_group_members AS member
    ON member.id = origin.membership_id
   AND member.is_delete = false
  JOIN public.auto_account_contact_groups AS contact_group
    ON contact_group.id = member.group_id
   AND contact_group.purpose = 'data_group'
  JOIN public.category_item AS category_item
    ON category_item.id = origin.source_category_item_id
   AND category_item.is_active = true
   AND category_item.managed_by = 'system'
   AND category_item.code = public.aka_agent_data_group_source_code(origin.kind)
  JOIN public.category_type AS category_type
    ON category_type.id = category_item.category_type_id
   AND category_type.namespace = 'common'
   AND category_type.code = 'data_source'
   AND category_type.managed_by = 'system'
   AND category_type.is_active = true
  WHERE origin.is_current = true
)
UPDATE public.auto_account_contact_group_members AS member
SET primary_origin_id = ranked_primary.id
FROM ranked_primary
WHERE ranked_primary.membership_id = member.id
  AND ranked_primary.source_rank = 1
  AND member.primary_origin_id IS NULL;

CREATE OR REPLACE FUNCTION public.aka_agent_sync_data_group_member_primary_origin(
  p_membership_id bigint,
  p_preferred_origin_id bigint DEFAULT NULL,
  p_force_preferred boolean DEFAULT false
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_member public.auto_account_contact_group_members%ROWTYPE;
  v_primary_origin_id bigint;
BEGIN
  SELECT member.*
  INTO v_member
  FROM public.auto_account_contact_group_members AS member
  JOIN public.auto_account_contact_groups AS contact_group
    ON contact_group.id = member.group_id
   AND contact_group.purpose = 'data_group'
  WHERE member.id = p_membership_id
  FOR UPDATE OF member;

  IF NOT FOUND THEN
    RETURN;
  END IF;

  IF v_member.is_delete THEN
    IF v_member.primary_origin_id IS NOT NULL THEN
      UPDATE public.auto_account_contact_group_members
      SET primary_origin_id = NULL
      WHERE id = v_member.id;
    END IF;
    RETURN;
  END IF;

  -- A valid current primary is sticky.  This is the key distinction between
  -- provenance (many current rows) and the one source displayed in the UI.
  IF NOT COALESCE(p_force_preferred, false)
    AND v_member.primary_origin_id IS NOT NULL
    AND EXISTS (
      SELECT 1
      FROM public.auto_account_contact_group_member_origins AS origin
      JOIN public.category_item AS category_item
        ON category_item.id = origin.source_category_item_id
       AND category_item.is_active = true
       AND category_item.managed_by = 'system'
       AND category_item.code = public.aka_agent_data_group_source_code(origin.kind)
      JOIN public.category_type AS category_type
        ON category_type.id = category_item.category_type_id
       AND category_type.namespace = 'common'
       AND category_type.code = 'data_source'
       AND category_type.managed_by = 'system'
       AND category_type.is_active = true
      WHERE origin.id = v_member.primary_origin_id
        AND origin.membership_id = v_member.id
        AND origin.is_current = true
    )
  THEN
    RETURN;
  END IF;

  IF p_preferred_origin_id IS NOT NULL THEN
    SELECT origin.id
    INTO v_primary_origin_id
    FROM public.auto_account_contact_group_member_origins AS origin
    JOIN public.category_item AS category_item
      ON category_item.id = origin.source_category_item_id
     AND category_item.is_active = true
     AND category_item.managed_by = 'system'
     AND category_item.code = public.aka_agent_data_group_source_code(origin.kind)
    JOIN public.category_type AS category_type
      ON category_type.id = category_item.category_type_id
     AND category_type.namespace = 'common'
     AND category_type.code = 'data_source'
     AND category_type.managed_by = 'system'
     AND category_type.is_active = true
    WHERE origin.id = p_preferred_origin_id
      AND origin.membership_id = v_member.id
      AND origin.is_current = true;
  END IF;

  IF v_primary_origin_id IS NULL THEN
    SELECT origin.id
    INTO v_primary_origin_id
    FROM public.auto_account_contact_group_member_origins AS origin
    JOIN public.category_item AS category_item
      ON category_item.id = origin.source_category_item_id
     AND category_item.is_active = true
     AND category_item.managed_by = 'system'
     AND category_item.code = public.aka_agent_data_group_source_code(origin.kind)
    JOIN public.category_type AS category_type
      ON category_type.id = category_item.category_type_id
     AND category_type.namespace = 'common'
     AND category_type.code = 'data_source'
     AND category_type.managed_by = 'system'
     AND category_type.is_active = true
    WHERE origin.membership_id = v_member.id
      AND origin.is_current = true
    ORDER BY origin.created_at, origin.id
    LIMIT 1;
  END IF;

  UPDATE public.auto_account_contact_group_members
  SET primary_origin_id = v_primary_origin_id
  WHERE id = v_member.id
    AND primary_origin_id IS DISTINCT FROM v_primary_origin_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.aka_agent_stamp_data_group_source_category()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM public.auto_account_contact_group_members AS member
    JOIN public.auto_account_contact_groups AS contact_group
      ON contact_group.id = member.group_id
     AND contact_group.purpose = 'data_group'
