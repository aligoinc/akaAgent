-- Persist named contact datasets for scan results and uploaded campaign data.
-- A contact can belong to many datasets, so membership is modeled separately
-- instead of storing a lossy, singular dataset_id on auto_account_contacts.

BEGIN;

CREATE TABLE IF NOT EXISTS public.auto_account_contacts_dataset (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  name text NOT NULL,
  link text,
  description text,
  source text NOT NULL,
  account_id bigint NOT NULL REFERENCES public.auto_accounts(id) ON DELETE CASCADE,
  flatform_type text NOT NULL,
  contact_type text NOT NULL,
  scan_type text NOT NULL,
  source_key text NOT NULL,
  last_scanned_at timestamptz,
  last_scan_status text,
  extra_data jsonb NOT NULL DEFAULT '{}'::jsonb,
  contact_count integer NOT NULL DEFAULT 0,
  is_delete boolean NOT NULL DEFAULT false,
  staff_id bigint NOT NULL REFERENCES public.org_staff(id) ON DELETE CASCADE,
  organization_id bigint NOT NULL REFERENCES public.org_organization(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT auto_account_contacts_dataset_pkey PRIMARY KEY (id),
  CONSTRAINT auto_account_contacts_dataset_source_check
    CHECK (source IN ('scan', 'upload')),
  CONSTRAINT auto_account_contacts_dataset_contact_type_check
    CHECK (contact_type IN (
      'person', 'group', 'page', 'page_inbox_customer', 'zalo_tag',
      'phone', 'email', 'campaign_input'
    )),
  CONSTRAINT auto_account_contacts_dataset_scan_type_check
    CHECK (scan_type IN (
      'facebook_group_members', 'facebook_profile_friends',
      'facebook_post_commenters', 'facebook_post_likes',
      'zalo_group_members', 'upload_data'
    )),
  CONSTRAINT auto_account_contacts_dataset_scan_status_check
    CHECK (last_scan_status IS NULL OR last_scan_status IN ('completed', 'partial', 'failed')),
  CONSTRAINT auto_account_contacts_dataset_contact_count_check
    CHECK (contact_count >= 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_account_contact_datasets_active_identity
  ON public.auto_account_contacts_dataset (
    staff_id, account_id, scan_type, contact_type, source_key
  )
  WHERE is_delete = false;

CREATE INDEX IF NOT EXISTS idx_account_contact_datasets_active_list
  ON public.auto_account_contacts_dataset (
    staff_id, account_id, created_at DESC, id DESC
  )
  WHERE is_delete = false;

CREATE INDEX IF NOT EXISTS idx_account_contact_datasets_active_type
  ON public.auto_account_contacts_dataset (
    staff_id, account_id, scan_type, contact_type, created_at DESC, id DESC
  )
  WHERE is_delete = false;

CREATE TABLE IF NOT EXISTS public.auto_account_contacts_dataset_members (
  dataset_id bigint NOT NULL
    REFERENCES public.auto_account_contacts_dataset(id) ON DELETE CASCADE,
  contact_id bigint NOT NULL
    REFERENCES public.auto_account_contacts(id) ON DELETE CASCADE,
  sort_order integer NOT NULL DEFAULT 0,
  is_current boolean NOT NULL DEFAULT true,
  first_seen_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT auto_account_contacts_dataset_members_pkey
    PRIMARY KEY (dataset_id, contact_id),
  CONSTRAINT auto_account_contacts_dataset_members_sort_order_check
    CHECK (sort_order >= 0)
);

CREATE INDEX IF NOT EXISTS idx_account_contact_dataset_members_order
  ON public.auto_account_contacts_dataset_members (dataset_id, sort_order, contact_id)
  WHERE is_current = true;

CREATE INDEX IF NOT EXISTS idx_account_contact_dataset_members_contact
  ON public.auto_account_contacts_dataset_members (contact_id, dataset_id);

COMMENT ON TABLE public.auto_account_contacts_dataset IS
  'Named snapshots of contacts collected by one scan target or one data upload.';
COMMENT ON TABLE public.auto_account_contacts_dataset_members IS
  'Many-to-many membership preserving current and historical appearances of canonical contacts.';
COMMENT ON COLUMN public.auto_account_contacts_dataset.source_key IS
  'Stable idempotency key for one logical scan source or one named upload per account.';
COMMENT ON COLUMN public.auto_account_contacts_dataset.source IS
  'Dataset origin: scan or upload.';
COMMENT ON COLUMN public.auto_account_contacts_dataset.scan_type IS
  'The scan action that produced the dataset, or upload_data for imported rows.';
COMMENT ON COLUMN public.auto_account_contacts_dataset.contact_count IS
  'Cached count of current dataset memberships, maintained transactionally by dataset RPCs.';

-- Dataset tables are intentionally RPC-only. The desktop uses a public Supabase
-- client, so tenant/account checks live inside the narrowly scoped functions below.
ALTER TABLE public.auto_account_contacts_dataset ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.auto_account_contacts_dataset_members ENABLE ROW LEVEL SECURITY;

REVOKE ALL PRIVILEGES ON TABLE public.auto_account_contacts_dataset
  FROM PUBLIC, anon, authenticated;
REVOKE ALL PRIVILEGES ON TABLE public.auto_account_contacts_dataset_members
  FROM PUBLIC, anon, authenticated;
REVOKE ALL PRIVILEGES ON SEQUENCE public.auto_account_contacts_dataset_id_seq
  FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.aka_agent_list_contact_datasets(
  p_staff_id bigint,
  p_organization_id bigint,
  p_account_id bigint,
  p_scan_type text DEFAULT NULL,
  p_contact_type text DEFAULT NULL,
  p_source text DEFAULT NULL,
  p_flatform_type text DEFAULT NULL
)
RETURNS TABLE (
  id bigint,
  name text,
  link text,
  description text,
  source text,
  account_id bigint,
  flatform_type text,
  contact_type text,
  scan_type text,
  source_key text,
  last_scanned_at timestamptz,
  last_scan_status text,
  extra_data jsonb,
  contact_count integer,
  is_delete boolean,
  staff_id bigint,
  organization_id bigint,
  created_at timestamptz,
  updated_at timestamptz
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO public
AS $$
  SELECT
    dataset.id,
    dataset.name,
    dataset.link,
    dataset.description,
    dataset.source,
    dataset.account_id,
    dataset.flatform_type,
    dataset.contact_type,
    dataset.scan_type,
    dataset.source_key,
    dataset.last_scanned_at,
    dataset.last_scan_status,
    dataset.extra_data,
    (
      SELECT count(*)::integer
      FROM public.auto_account_contacts_dataset_members AS current_member
      JOIN public.auto_account_contacts AS current_contact
        ON current_contact.id = current_member.contact_id
      WHERE current_member.dataset_id = dataset.id
        AND current_member.is_current = true
        AND current_contact.account_id = dataset.account_id
        AND current_contact.staff_id = dataset.staff_id
        AND current_contact.organization_id = dataset.organization_id
        AND current_contact.contact_type = dataset.contact_type
        AND COALESCE(current_contact.is_delete, false) = false
    ) AS contact_count,
    dataset.is_delete,
    dataset.staff_id,
    dataset.organization_id,
    dataset.created_at,
    dataset.updated_at
  FROM public.auto_account_contacts_dataset AS dataset
  JOIN public.auto_accounts AS account
    ON account.id = dataset.account_id
  WHERE dataset.staff_id = p_staff_id
    AND dataset.organization_id = p_organization_id
    AND dataset.account_id = p_account_id
    AND dataset.is_delete = false
    AND account.staff_id = p_staff_id
    AND account.organization_id = p_organization_id
    AND COALESCE(account.is_delete, false) = false
    AND (p_scan_type IS NULL OR dataset.scan_type = p_scan_type)
    AND (p_contact_type IS NULL OR dataset.contact_type = p_contact_type)
    AND (p_source IS NULL OR dataset.source = p_source)
    AND (p_flatform_type IS NULL OR dataset.flatform_type = p_flatform_type)
  ORDER BY dataset.updated_at DESC, dataset.id DESC;
$$;

CREATE OR REPLACE FUNCTION public.aka_agent_list_contact_dataset_member_ids(
  p_staff_id bigint,
  p_organization_id bigint,
  p_account_id bigint,
  p_dataset_id bigint,
  p_contact_type text DEFAULT NULL
)
RETURNS TABLE (contact_id bigint, sort_order integer)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO public
AS $$
  SELECT member.contact_id, member.sort_order
  FROM public.auto_account_contacts_dataset AS dataset
  JOIN public.auto_account_contacts_dataset_members AS member
    ON member.dataset_id = dataset.id
  JOIN public.auto_account_contacts AS contact
    ON contact.id = member.contact_id
  WHERE dataset.id = p_dataset_id
    AND dataset.staff_id = p_staff_id
    AND dataset.organization_id = p_organization_id
    AND dataset.account_id = p_account_id
    AND dataset.is_delete = false
    AND member.is_current = true
    AND (p_contact_type IS NULL OR dataset.contact_type = p_contact_type)
    AND contact.staff_id = p_staff_id
    AND contact.organization_id = p_organization_id
    AND contact.account_id = p_account_id
    AND contact.contact_type = dataset.contact_type
    AND COALESCE(contact.is_delete, false) = false
  ORDER BY member.sort_order ASC, member.contact_id ASC;
$$;

CREATE OR REPLACE FUNCTION public.aka_agent_finalize_contact_dataset(
  p_staff_id bigint,
  p_organization_id bigint,
  p_account_id bigint,
  p_scan_type text,
  p_contact_type text,
  p_source_key text,
  p_name text,
  p_link text DEFAULT NULL,
  p_description text DEFAULT NULL,
  p_status text DEFAULT 'completed',
  p_contact_uids text[] DEFAULT '{}'::text[],
  p_extra_data jsonb DEFAULT '{}'::jsonb
)
RETURNS SETOF public.auto_account_contacts_dataset
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO public
AS $$
DECLARE
  v_account public.auto_accounts%ROWTYPE;
  v_dataset public.auto_account_contacts_dataset%ROWTYPE;
  v_dataset_exists boolean := false;
  v_uid_count integer := 0;
  v_matching_count integer := 0;
BEGIN
  IF p_staff_id IS NULL OR p_staff_id <= 0
    OR p_organization_id IS NULL OR p_organization_id <= 0
    OR p_account_id IS NULL OR p_account_id <= 0 THEN
    RAISE EXCEPTION 'invalid_contact_dataset_identity';
  END IF;

  IF p_scan_type IS NULL OR p_scan_type NOT IN (
      'facebook_group_members', 'facebook_profile_friends',
      'facebook_post_commenters', 'facebook_post_likes', 'zalo_group_members'
    )
    OR p_contact_type IS NULL OR p_contact_type NOT IN (
      'person', 'group', 'page', 'page_inbox_customer', 'zalo_tag',
      'phone', 'email', 'campaign_input'
    )
    OR NULLIF(btrim(COALESCE(p_source_key, '')), '') IS NULL
    OR NULLIF(btrim(COALESCE(p_name, '')), '') IS NULL
    OR p_status IS NULL OR p_status NOT IN ('completed', 'partial', 'failed')
    OR jsonb_typeof(COALESCE(p_extra_data, '{}'::jsonb)) <> 'object' THEN
    RAISE EXCEPTION 'invalid_contact_dataset_payload';
  END IF;

  SELECT account.*
  INTO v_account
  FROM public.auto_accounts AS account
  WHERE account.id = p_account_id
    AND account.staff_id = p_staff_id
    AND account.organization_id = p_organization_id
    AND COALESCE(account.is_delete, false) = false
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'contact_dataset_account_not_found';
  END IF;

  IF (p_scan_type LIKE 'facebook_%' AND v_account.flatform_type <> 'facebook')
    OR (p_scan_type LIKE 'zalo_%' AND v_account.flatform_type <> 'zalo') THEN
    RAISE EXCEPTION 'contact_dataset_platform_mismatch';
  END IF;

  SELECT dataset.*
  INTO v_dataset
  FROM public.auto_account_contacts_dataset AS dataset
  WHERE dataset.staff_id = p_staff_id
    AND dataset.account_id = p_account_id
    AND dataset.scan_type = p_scan_type
    AND dataset.contact_type = p_contact_type
    AND dataset.source_key = btrim(p_source_key)
    AND dataset.is_delete = false
  FOR UPDATE;
  v_dataset_exists := FOUND;

  IF v_dataset_exists AND (
      v_dataset.staff_id <> p_staff_id
      OR v_dataset.organization_id <> p_organization_id
      OR v_dataset.source <> 'scan'
      OR v_dataset.scan_type <> p_scan_type
      OR v_dataset.contact_type <> p_contact_type
    ) THEN
    RAISE EXCEPTION 'contact_dataset_source_key_conflict';
  END IF;

  -- A failed attempt records the latest outcome on an existing dataset, but
  -- never creates a dataset or changes its membership snapshot.
  IF p_status = 'failed' THEN
    IF v_dataset_exists THEN
      UPDATE public.auto_account_contacts_dataset AS dataset
      SET name = btrim(p_name),
          link = NULLIF(btrim(COALESCE(p_link, '')), ''),
          description = NULLIF(btrim(COALESCE(p_description, '')), ''),
          last_scanned_at = now(),
          last_scan_status = 'failed',
          extra_data = COALESCE(dataset.extra_data, '{}'::jsonb)
            || COALESCE(p_extra_data, '{}'::jsonb),
          updated_at = now()
      WHERE dataset.id = v_dataset.id
      RETURNING dataset.* INTO v_dataset;
      RETURN NEXT v_dataset;
    END IF;
    RETURN;
  END IF;

  SELECT count(*)::integer
  INTO v_uid_count
  FROM (
    SELECT DISTINCT btrim(raw_uid) AS uid
    FROM unnest(COALESCE(p_contact_uids, '{}'::text[])) AS input_uid(raw_uid)
    WHERE NULLIF(btrim(raw_uid), '') IS NOT NULL
  ) AS unique_uid;

  -- Do not create a meaningless empty dataset. A completed empty snapshot
  -- clears current membership; a partial empty snapshot preserves it.
  IF v_uid_count = 0 AND NOT v_dataset_exists THEN
    RETURN;
  END IF;

  IF v_uid_count > 0 THEN
    SELECT count(*)::integer
    INTO v_matching_count
    FROM public.auto_account_contacts AS contact
    JOIN (
      SELECT DISTINCT btrim(raw_uid) AS uid
      FROM unnest(p_contact_uids) AS input_uid(raw_uid)
      WHERE NULLIF(btrim(raw_uid), '') IS NOT NULL
    ) AS requested
      ON requested.uid = contact.uid
    WHERE contact.account_id = p_account_id
      AND contact.staff_id = p_staff_id
      AND contact.organization_id = p_organization_id
      AND contact.contact_type = p_contact_type
      AND COALESCE(contact.is_delete, false) = false;

    IF v_matching_count <> v_uid_count THEN
      RAISE EXCEPTION 'contact_dataset_contacts_not_found';
    END IF;
  END IF;

  IF v_dataset_exists THEN
    UPDATE public.auto_account_contacts_dataset AS dataset
    SET name = btrim(p_name),
        link = NULLIF(btrim(COALESCE(p_link, '')), ''),
        description = NULLIF(btrim(COALESCE(p_description, '')), ''),
        flatform_type = v_account.flatform_type,
        last_scanned_at = now(),
        last_scan_status = p_status,
        extra_data = COALESCE(dataset.extra_data, '{}'::jsonb) || COALESCE(p_extra_data, '{}'::jsonb),
        is_delete = false,
        updated_at = now()
    WHERE dataset.id = v_dataset.id
    RETURNING dataset.* INTO v_dataset;
  ELSE
    INSERT INTO public.auto_account_contacts_dataset AS existing_dataset (
      name, link, description, source, account_id, flatform_type,
      contact_type, scan_type, source_key, last_scanned_at,
      last_scan_status, extra_data, contact_count, is_delete,
      staff_id, organization_id
    ) VALUES (
      btrim(p_name), NULLIF(btrim(COALESCE(p_link, '')), ''),
      NULLIF(btrim(COALESCE(p_description, '')), ''), 'scan',
      p_account_id, v_account.flatform_type, p_contact_type, p_scan_type,
      btrim(p_source_key), now(), p_status, COALESCE(p_extra_data, '{}'::jsonb),
      0, false, p_staff_id, p_organization_id
    )
    ON CONFLICT (staff_id, account_id, scan_type, contact_type, source_key)
      WHERE is_delete = false
    DO UPDATE
    SET name = EXCLUDED.name,
        link = EXCLUDED.link,
        description = EXCLUDED.description,
        flatform_type = EXCLUDED.flatform_type,
        last_scanned_at = EXCLUDED.last_scanned_at,
        last_scan_status = EXCLUDED.last_scan_status,
        extra_data = COALESCE(existing_dataset.extra_data, '{}'::jsonb)
          || EXCLUDED.extra_data,
        updated_at = now()
    RETURNING * INTO v_dataset;
  END IF;

  IF p_status = 'completed' THEN
    UPDATE public.auto_account_contacts_dataset_members AS member
    SET is_current = false,
        updated_at = now()
    WHERE member.dataset_id = v_dataset.id
      AND member.is_current = true;
  END IF;

  INSERT INTO public.auto_account_contacts_dataset_members (
    dataset_id, contact_id, sort_order, is_current,
    first_seen_at, last_seen_at, updated_at
  )
  SELECT
    v_dataset.id,
    contact.id,
    (MIN(input_uid.ordinality) - 1)::integer,
    true,
    now(),
    now(),
    now()
  FROM unnest(COALESCE(p_contact_uids, '{}'::text[]))
    WITH ORDINALITY AS input_uid(raw_uid, ordinality)
  JOIN public.auto_account_contacts AS contact
    ON contact.uid = btrim(input_uid.raw_uid)
   AND contact.account_id = p_account_id
   AND contact.staff_id = p_staff_id
   AND contact.organization_id = p_organization_id
   AND contact.contact_type = p_contact_type
   AND COALESCE(contact.is_delete, false) = false
  WHERE NULLIF(btrim(input_uid.raw_uid), '') IS NOT NULL
  GROUP BY contact.id
  ON CONFLICT (dataset_id, contact_id) DO UPDATE
  SET sort_order = EXCLUDED.sort_order,
      is_current = true,
      last_seen_at = now(),
      updated_at = now();

  UPDATE public.auto_account_contacts_dataset AS dataset
  SET contact_count = (
        SELECT count(*)::integer
        FROM public.auto_account_contacts_dataset_members AS member
        WHERE member.dataset_id = dataset.id
          AND member.is_current = true
      ),
      updated_at = now()
  WHERE dataset.id = v_dataset.id
  RETURNING dataset.* INTO v_dataset;

  RETURN NEXT v_dataset;
END;
$$;

CREATE OR REPLACE FUNCTION public.aka_agent_save_upload_contact_datasets(
  p_staff_id bigint,
  p_organization_id bigint,
  p_account_ids bigint[],
  p_name text,
  p_flatform_type text,
  p_contact_type text,
  p_action_id text,
  p_import_source text,
  p_source_link text,
  p_description text,
  p_source_key_prefix text,
  p_contacts jsonb,
  p_extra_data jsonb DEFAULT '{}'::jsonb
)
RETURNS SETOF public.auto_account_contacts_dataset
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO public
AS $$
DECLARE
  v_account_id bigint;
  v_account_count integer := 0;
  v_requested_account_count integer := 0;
  v_contact_count integer := 0;
  v_unique_contact_count integer := 0;
  v_dataset public.auto_account_contacts_dataset%ROWTYPE;
  v_source_key text;
  v_dataset_extra_data jsonb := '{}'::jsonb;
BEGIN
  IF p_staff_id IS NULL OR p_staff_id <= 0
    OR p_organization_id IS NULL OR p_organization_id <= 0
    OR COALESCE(array_length(p_account_ids, 1), 0) = 0
    OR NULLIF(btrim(COALESCE(p_name, '')), '') IS NULL
    OR p_flatform_type IS NULL OR p_flatform_type NOT IN ('facebook', 'zalo', 'email', 'sms')
    OR p_contact_type IS NULL OR p_contact_type NOT IN (
      'person', 'group', 'page', 'page_inbox_customer', 'zalo_tag',
      'phone', 'email', 'campaign_input'
    )
    OR NULLIF(btrim(COALESCE(p_action_id, '')), '') IS NULL
    OR (left(p_action_id, 9) = 'facebook_' AND p_flatform_type <> 'facebook')
    OR (left(p_action_id, 5) = 'zalo_' AND p_flatform_type <> 'zalo')
    OR (p_action_id = 'email_send' AND p_flatform_type <> 'email')
    OR (p_action_id = 'sms_send' AND p_flatform_type <> 'sms')
    OR p_import_source IS NULL OR p_import_source NOT IN ('textbox', 'image', 'sheet', 'excel')
    OR NULLIF(btrim(COALESCE(p_source_key_prefix, '')), '') IS NULL
    OR jsonb_typeof(COALESCE(p_contacts, '[]'::jsonb)) <> 'array'
    OR jsonb_typeof(COALESCE(p_extra_data, '{}'::jsonb)) <> 'object' THEN
    RAISE EXCEPTION 'invalid_upload_contact_dataset_payload';
  END IF;

  SELECT count(*)::integer
  INTO v_requested_account_count
  FROM (SELECT DISTINCT unnest(p_account_ids) AS account_id) AS requested;

  SELECT count(*)::integer
  INTO v_account_count
  FROM public.auto_accounts AS account
  JOIN (SELECT DISTINCT unnest(p_account_ids) AS account_id) AS requested
    ON requested.account_id = account.id
  WHERE account.staff_id = p_staff_id
    AND account.organization_id = p_organization_id
    AND account.flatform_type = p_flatform_type
    AND COALESCE(account.is_delete, false) = false;

  IF v_requested_account_count <> v_account_count THEN
    RAISE EXCEPTION 'upload_contact_dataset_account_not_found';
  END IF;

  v_contact_count := jsonb_array_length(p_contacts);
  IF v_contact_count = 0 THEN
    RAISE EXCEPTION 'invalid_upload_contact_dataset_size';
  END IF;

  SELECT count(DISTINCT btrim(item.value->>'uid'))::integer
  INTO v_unique_contact_count
  FROM jsonb_array_elements(p_contacts) AS item(value)
  WHERE NULLIF(btrim(item.value->>'uid'), '') IS NOT NULL
    AND NULLIF(btrim(item.value->>'name'), '') IS NOT NULL
    AND jsonb_typeof(COALESCE(item.value->'extraData', '{}'::jsonb)) = 'object';

  IF v_unique_contact_count <> v_contact_count THEN
    RAISE EXCEPTION 'invalid_upload_contact_dataset_contacts';
  END IF;

  v_dataset_extra_data := COALESCE(p_extra_data, '{}'::jsonb) || jsonb_build_object(
    'actionId', btrim(p_action_id),
    'importSource', p_import_source,
    'rowCount', v_contact_count,
    'accountCount', v_requested_account_count,
    'sourceLink', CASE
      WHEN p_import_source = 'sheet' THEN NULLIF(btrim(COALESCE(p_source_link, '')), '')
      ELSE NULL
    END
  );

  INSERT INTO public.auto_account_contacts AS existing_contact (
    account_id, contact_type, name, uid, url, extra_data, is_delete,
    staff_id, organization_id, updated_at
  )
  SELECT
    account_ref.account_id,
    p_contact_type,
    btrim(item.value->>'name'),
    btrim(item.value->>'uid'),
    NULLIF(btrim(item.value->>'url'), ''),
    COALESCE(item.value->'extraData', '{}'::jsonb),
    false,
    p_staff_id,
    p_organization_id,
    now()
  FROM (SELECT DISTINCT unnest(p_account_ids) AS account_id) AS account_ref
  CROSS JOIN jsonb_array_elements(p_contacts) AS item(value)
  ON CONFLICT (account_id, contact_type, uid) DO UPDATE
  SET name = CASE
        WHEN NULLIF(btrim(existing_contact.name), '') IS NULL
          OR existing_contact.name = existing_contact.uid
        THEN EXCLUDED.name
        ELSE existing_contact.name
      END,
      url = COALESCE(existing_contact.url, EXCLUDED.url),
      extra_data = COALESCE(existing_contact.extra_data, '{}'::jsonb)
        || COALESCE(EXCLUDED.extra_data, '{}'::jsonb),
      is_delete = false,
      staff_id = EXCLUDED.staff_id,
      organization_id = EXCLUDED.organization_id,
      updated_at = now();

  FOR v_account_id IN
    SELECT DISTINCT unnest(p_account_ids) AS account_id
    ORDER BY account_id
  LOOP
    v_source_key := btrim(p_source_key_prefix) || ':' || v_account_id::text;

    SELECT dataset.*
    INTO v_dataset
    FROM public.auto_account_contacts_dataset AS dataset
    WHERE dataset.staff_id = p_staff_id
      AND dataset.account_id = v_account_id
      AND dataset.scan_type = 'upload_data'
      AND dataset.contact_type = p_contact_type
      AND dataset.source_key = v_source_key
      AND dataset.is_delete = false
    FOR UPDATE;

    IF FOUND AND (
        v_dataset.staff_id <> p_staff_id
        OR v_dataset.organization_id <> p_organization_id
        OR v_dataset.source <> 'upload'
        OR v_dataset.scan_type <> 'upload_data'
        OR v_dataset.contact_type <> p_contact_type
      ) THEN
      RAISE EXCEPTION 'upload_contact_dataset_source_key_conflict';
    END IF;

    INSERT INTO public.auto_account_contacts_dataset AS existing_dataset (
      name, link, description, source, account_id, flatform_type,
      contact_type, scan_type, source_key, last_scanned_at,
      last_scan_status, extra_data, contact_count, is_delete,
      staff_id, organization_id
    ) VALUES (
      btrim(p_name), CASE
        WHEN p_import_source = 'sheet' THEN NULLIF(btrim(COALESCE(p_source_link, '')), '')
        ELSE NULL
      END,
      NULLIF(btrim(COALESCE(p_description, '')), ''), 'upload',
      v_account_id, p_flatform_type, p_contact_type, 'upload_data',
      v_source_key, now(), 'completed', v_dataset_extra_data,
      0, false, p_staff_id, p_organization_id
    )
    ON CONFLICT (staff_id, account_id, scan_type, contact_type, source_key)
      WHERE is_delete = false
    DO UPDATE
    SET name = EXCLUDED.name,
        link = EXCLUDED.link,
        description = EXCLUDED.description,
        flatform_type = EXCLUDED.flatform_type,
        last_scanned_at = now(),
        last_scan_status = 'completed',
        extra_data = COALESCE(existing_dataset.extra_data, '{}'::jsonb)
          || EXCLUDED.extra_data,
        is_delete = false,
        updated_at = now()
    RETURNING * INTO v_dataset;

    UPDATE public.auto_account_contacts_dataset_members AS member
    SET is_current = false,
        updated_at = now()
    WHERE member.dataset_id = v_dataset.id
      AND member.is_current = true;

    INSERT INTO public.auto_account_contacts_dataset_members (
      dataset_id, contact_id, sort_order, is_current,
      first_seen_at, last_seen_at, updated_at
    )
    SELECT
      v_dataset.id,
      contact.id,
      (item.ordinality - 1)::integer,
      true,
      now(),
      now(),
      now()
    FROM jsonb_array_elements(p_contacts)
      WITH ORDINALITY AS item(value, ordinality)
    JOIN public.auto_account_contacts AS contact
      ON contact.account_id = v_account_id
     AND contact.staff_id = p_staff_id
     AND contact.organization_id = p_organization_id
     AND contact.contact_type = p_contact_type
     AND contact.uid = btrim(item.value->>'uid')
     AND COALESCE(contact.is_delete, false) = false
    ON CONFLICT (dataset_id, contact_id) DO UPDATE
    SET sort_order = EXCLUDED.sort_order,
        is_current = true,
        last_seen_at = now(),
        updated_at = now();

    UPDATE public.auto_account_contacts_dataset AS dataset
    SET contact_count = (
          SELECT count(*)::integer
          FROM public.auto_account_contacts_dataset_members AS member
          WHERE member.dataset_id = dataset.id
            AND member.is_current = true
        ),
        updated_at = now()
    WHERE dataset.id = v_dataset.id;
  END LOOP;

  RETURN QUERY
  SELECT dataset.*
  FROM unnest(p_account_ids) WITH ORDINALITY AS requested(account_id, position)
  JOIN public.auto_account_contacts_dataset AS dataset
    ON dataset.account_id = requested.account_id
   AND dataset.staff_id = p_staff_id
   AND dataset.scan_type = 'upload_data'
   AND dataset.contact_type = p_contact_type
   AND dataset.source_key = btrim(p_source_key_prefix) || ':' || requested.account_id::text
   AND dataset.is_delete = false
  WHERE dataset.staff_id = p_staff_id
    AND dataset.organization_id = p_organization_id
  ORDER BY requested.position;
END;
$$;

