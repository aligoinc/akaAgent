const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),os=require('node:os')
const {build}=require('esbuild'),{_electron}=require('playwright')
async function main(){
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'web-enrichment-ui-'));let app
 try{
  await build({entryPoints:[path.join(__dirname,'web-enrichment-ui-smoke.tsx')],outdir:dir,bundle:true,platform:'browser',format:'iife',jsx:'automatic',target:'chrome120',define:{'process.env.NODE_ENV':'"development"'},loader:{'.woff2':'file','.woff':'file'}})
  fs.writeFileSync(path.join(dir,'index.html'),'<html><link rel="stylesheet" href="web-enrichment-ui-smoke.css"><div id="root"></div><script src="web-enrichment-ui-smoke.js"></script></html>')
  fs.writeFileSync(path.join(dir,'main.cjs'),`const{app,BrowserWindow}=require('electron');app.setPath('userData',${JSON.stringify(path.join(dir,'profile'))});app.whenReady().then(()=>{const w=new BrowserWindow({show:false,width:1100,height:900,webPreferences:{sandbox:true,contextIsolation:true,nodeIntegration:false}});w.webContents.session.webRequest.onBeforeRequest((d,cb)=>cb({cancel:/^https?:/.test(d.url)}));w.loadFile(${JSON.stringify(path.join(dir,'index.html'))})})`)
  const env={...process.env};delete env.ELECTRON_RUN_AS_NODE
  app=await _electron.launch({executablePath:require('electron'),args:[path.join(dir,'main.cjs')],env})
  const page=await app.firstWindow();page.setDefaultTimeout(10000)
  await page.getByText('Làm giàu lịch sử Web',{exact:true}).click()
  const toggle=page.getByLabel('Bật làm giàu lịch sử Web'),save=page.getByRole('button',{name:'Lưu cài đặt',exact:true})
  await page.getByLabel('Mô tả lĩnh vực khách hàng').waitFor()
  assert.equal(await toggle.isChecked(),false);assert.equal(await page.locator('#web-industry').inputValue(),'')
  assert.equal(await page.locator('#web-minutes').inputValue(),'30')
  assert.deepEqual(await page.locator('.times>span').allTextContents(),[],'a new configuration must not contain a pre-created slot')
  assert.equal(await page.locator('#web-time').inputValue(),'12:00','prefill only the time input until the user clicks Add time')
  const expectedStop=await page.evaluate(()=>new Date(Date.now()+(7*24+7)*60*60*1000).toISOString().slice(0,10))
  assert.equal(await page.locator('#web-stop').inputValue(),expectedStop)
  const out=path.resolve(process.env.WEB_ENRICHMENT_UI_OUTPUT_DIR||path.join(__dirname,'../docs/audits/web-enrichment-v398'));fs.mkdirSync(out,{recursive:true})
  await page.locator('#web-time').locator('..').locator('..').screenshot({path:path.join(out,'modal-time-default.png')})
  // Real Chromium composition: an IME confirmation must not create a partial chip.
  const cdp=await page.context().newCDPSession(page)
  const assertNoImplicitSave=async()=>{
   assert.equal(await page.evaluate(()=>window.webUi.state.saved.length),0,'IME Enter must not save the settings')
   assert.equal(await page.getByRole('dialog').count(),1,'IME Enter must keep the modal open')
  }
  const pressLegacyImeEnter=async()=>{
   // Unlike DOM dispatchEvent, this can trigger the browser's implicit form submission.
   await cdp.send('Input.dispatchKeyEvent',{type:'keyDown',key:'Enter',code:'Enter',windowsVirtualKeyCode:229,nativeVirtualKeyCode:229,text:'\r',unmodifiedText:'\r'})
   await cdp.send('Input.dispatchKeyEvent',{type:'keyUp',key:'Enter',code:'Enter',windowsVirtualKeyCode:229,nativeVirtualKeyCode:229})
  }
  for(const [label,word] of [['Từ khóa Google','bóng đá'],['Sở thích ngoài công việc','nhiếp ảnh']]){
   const input=page.getByLabel(label,{exact:true}),chips=input.locator('..').locator(':scope > span')
   for(const key of ['Enter',',']){
    await input.focus()
    await cdp.send('Input.imeSetComposition',{text:word.slice(0,-1),selectionStart:word.length-1,selectionEnd:word.length-1})
    if(key==='Enter'){
     await input.press('Enter');await assertNoImplicitSave()
     assert.equal(await input.inputValue(),word.slice(0,-1),'keep the draft while the IME is updating it')
    }
    await input.dispatchEvent('keydown',{key,isComposing:true})
    assert.equal(await chips.count(),0,'do not tokenize an unfinished IME value')
    await input.dispatchEvent('keydown',{key,keyCode:229,isComposing:false})
    assert.equal(await chips.count(),0,'keep the legacy IME key code guard')
    await cdp.send('Input.insertText',{text:word})
    assert.equal(await input.inputValue(),word)
    if(key==='Enter'){
     await pressLegacyImeEnter();await assertNoImplicitSave()
     assert.equal(await input.inputValue(),word)
     assert.equal(await chips.count(),0,'legacy IME Enter must not tokenize the draft')
    }
    await input.press(key)
    assert.deepEqual(await chips.allTextContents(),[word],'commit one complete phrase')
    await input.dispatchEvent('keydown',{key:'Backspace',isComposing:true})
    await input.dispatchEvent('keydown',{key:'Backspace',keyCode:229,isComposing:false})
    assert.deepEqual(await chips.allTextContents(),[word],'IME backspace must not delete the previous chip')
    await input.press('Backspace');assert.equal(await chips.count(),0)
   }
   // Ordinary spaces and blur still preserve the whole phrase.
   await input.fill(word);await page.locator('#web-industry').focus()
   assert.deepEqual(await chips.allTextContents(),[word])
   await input.locator('..').getByRole('button',{name:`Xóa ${word}`,exact:true}).click()
  }
  const urlInput=page.locator('#web-url'),urls=page.locator('.website-url')
  await urlInput.focus()
  const partialUrl='bongda.example',completeUrl='bongda.example.vn'
  await cdp.send('Input.imeSetComposition',{text:partialUrl,selectionStart:partialUrl.length,selectionEnd:partialUrl.length})
  await urlInput.press('Enter');await assertNoImplicitSave()
  assert.equal(await urlInput.inputValue(),partialUrl)
  for(const ime of [{isComposing:true},{isComposing:false,keyCode:229}]){
   await urlInput.dispatchEvent('keydown',{key:'Enter',...ime})
   assert.equal(await urls.count(),0,'do not add an unfinished URL')
   assert.equal(await urlInput.inputValue(),partialUrl,'keep the URL draft during composition')
  }
  await cdp.send('Input.insertText',{text:completeUrl})
  await pressLegacyImeEnter();await assertNoImplicitSave()
  assert.equal(await urls.count(),0)
  assert.equal(await urlInput.inputValue(),completeUrl)
  await urlInput.press('Enter')
  assert.deepEqual(await urls.allTextContents(),[`https://${completeUrl}/`],'add the complete URL exactly once')
  assert.equal(await urlInput.inputValue(),'')
  assert.equal(await page.evaluate(()=>window.webUi.state.saved.length),0,'adding a URL must not submit the settings')
  await page.getByRole('button',{name:'Xóa website 1',exact:true}).click()
  await cdp.detach()
  await toggle.check();await save.click();await page.getByRole('alert').getByText('Vui lòng mô tả lĩnh vực khách hàng.').waitFor()
  await page.locator('#web-industry').fill('Thiết kế nội thất và tư vấn không gian sống.')
  const keywords=page.getByLabel('Từ khóa Google');await keywords.fill('nội thất, phòng khách, NỘI THẤT');await keywords.press('Enter')
  await save.click();await page.getByRole('alert').getByText('Cần ít nhất 3 từ khóa khác nhau.').waitFor()
  await keywords.fill('bàn ghế');await keywords.press('Enter')
  assert.equal(await page.locator('.web-enrichment-chips').first().locator('span').count(),3)
  for(const domain of ['one','two']){await page.locator('#web-url').fill(`${domain}.example`);await page.getByRole('button',{name:'Thêm web',exact:true}).click()}
  await save.click();await page.getByRole('alert').getByText('Cần đúng 3 website khác nhau.').waitFor()
  await page.locator('#web-url').fill('three.example');await page.getByRole('button',{name:'Thêm web',exact:true}).click()
  assert.equal(await page.getByRole('button',{name:'Thêm web',exact:true}).isDisabled(),true)
  assert.equal(await page.locator('.website-url').first().innerText(),'https://one.example/')
  await save.click();await page.getByRole('alert').getByText('Cần ít nhất một khung giờ HH:mm hợp lệ.').waitFor()
  assert.deepEqual(await page.locator('.times>span').allTextContents(),[],'saving must not implicitly add the time input')
  await page.getByRole('button',{name:'Thêm giờ',exact:true}).click()
  assert.deepEqual(await page.locator('.times>span').allTextContents(),['12:00'],'create the default slot only after clicking Add time')
  assert.equal(await page.locator('#web-time').inputValue(),'12:00','keep the default input after adding a slot')
  await page.locator('#web-time').fill('12:00');await page.getByRole('button',{name:'Thêm giờ',exact:true}).click()
  assert.deepEqual(await page.locator('.times>span').allTextContents(),['12:00'],'adding the default time again must not duplicate it')
  await page.getByRole('button',{name:'45 phút',exact:true}).click()
  await page.getByRole('button',{name:'Xóa giờ 12:00',exact:true}).click()
  for(const time of ['09:00','08:30','08:00','08:30']){await page.locator('#web-time').fill(time);await page.getByRole('button',{name:'Thêm giờ',exact:true}).click()}
  assert.deepEqual(await page.locator('.times>span').allTextContents(),['08:00','08:30','09:00'])
  assert.equal(await page.locator('#web-time').inputValue(),'12:00','return to the default input after adding a custom time')
  await page.getByText(/Các phiên có thể trùng nhau/).waitFor();assert.equal(await save.isEnabled(),true)
  await page.evaluate(()=>{window.webUi.state.failSave=true});await save.click();await page.getByRole('alert').getByText(/Cấu hình đã thay đổi/).waitFor()
  assert.equal(await page.locator('#web-minutes').inputValue(),'45');assert.equal(await page.locator('.website-url').count(),3)
  await page.locator('#web-stop').fill('2030-02-01')
  await page.evaluate(()=>{window.webUi.state.failSave=false});await save.focus();await save.press('Enter');await page.getByRole('dialog').waitFor({state:'detached'})
  assert.equal(await page.evaluate(()=>window.webUi.state.saved.length),1)
  await page.evaluate(()=>window.webUi.show());await page.locator('#web-industry').waitFor()
  assert.equal(await page.locator('#web-stop').inputValue(),'2030-02-01')
  assert.equal(await page.locator('#web-time').inputValue(),'12:00','reopen with the default time ready to add')
  assert.deepEqual(await page.locator('.times>span').allTextContents(),['08:00','08:30','09:00'])
  await page.screenshot({path:path.join(out,'modal-desktop.png')})
  await page.locator('.web-enrichment-body').evaluate(el=>{el.scrollTop=el.scrollHeight});await page.screenshot({path:path.join(out,'modal-schedule.png')})
  await page.setViewportSize({width:390,height:740});await page.screenshot({path:path.join(out,'modal-mobile.png')})
  assert.ok(await page.getByRole('dialog').evaluate(el=>el.getBoundingClientRect().right<=innerWidth))
  await toggle.uncheck();await page.locator('#web-industry').fill('');await save.click();await page.getByRole('dialog').waitFor({state:'detached'})
  assert.equal(await page.evaluate(()=>window.webUi.state.saved.at(-1).enabled),false)
  await page.evaluate(()=>{window.webUi.state.failLoad=true;window.webUi.show()});await page.getByRole('alert').waitFor()
  await page.evaluate(()=>{window.webUi.state.failLoad=false});await page.getByRole('button',{name:'Tải lại cài đặt'}).click();await page.locator('#web-minutes').waitFor()
  assert.equal(await page.locator('#web-time').inputValue(),'12:00')
  await page.getByRole('button',{name:'Hủy',exact:true}).click()
  await page.evaluate(()=>{window.webUi.state.settings.config.slots=[];window.webUi.show()});await page.locator('#web-time').waitFor()
  assert.equal(await page.locator('#web-time').inputValue(),'12:00')
  assert.deepEqual(await page.locator('.times>span').allTextContents(),[],'the input default must not add a slot to an existing empty draft')
  await save.click();await page.getByRole('dialog').waitFor({state:'detached'})
  assert.deepEqual(await page.evaluate(()=>window.webUi.state.saved.at(-1).config.slots),[])
  assert.deepEqual(await page.evaluate(()=>window.webUi.state.errors),[])
  console.log('PASS UI: native/legacy IME Enter cannot submit keywords/hobbies/URL, ordinary Enter adds once, Save button Enter, IME comma/Backspace, whole phrases on blur, menu, defaults, validation, chips, URLs, sorted slots, nonblocking overlap, CAS draft, disable, retry, 390px, screenshots')
 }finally{if(app)await app.close();fs.rmSync(dir,{recursive:true,force:true})}
}
main().catch(e=>{console.error(e);process.exitCode=1})
