#!/usr/bin/env bash
# Thử V481 (org_staff.web_campaign_form_version dạng text + khóa web.campaign_form) trên PostgreSQL 16 cục bộ, không chạm production.
# Fixture dựng org_staff/auto_system_settings tối thiểu như akachat (id settings là identity, sequence auto_system_settings_id_seq),
# chạy preflight (sequence thấp bị chặn), apply, kiểm cột/CHECK/khóa, giá trị hợp lệ/sai, khóa bận (lock_timeout), chạy lại bị từ chối,
# CHECK viết sai bị postflight chặn, rồi hai bước rollback và apply lại.
# Dùng: bash scripts/test-v481-web-campaign-form-version.sh   (PGBIN mặc định /usr/lib/postgresql/16/bin)
set -euo pipefail
PGBIN=${PGBIN:-/usr/lib/postgresql/16/bin}
ROOT=$(cd "$(dirname "$0")/.." && pwd)
MIGRATION="$ROOT/migrations/migration_v481_web_campaign_form_version.sql"
ROLLBACK="$ROOT/migrations/rollback_v481_web_campaign_form_version.sql"
WORK=$(mktemp -d "${TMPDIR:-/tmp}/v481.XXXXXX")
as_pg() { if [ "$(id -u)" = 0 ]; then runuser -u postgres -- "$@"; else "$@"; fi; }
[ "$(id -u)" = 0 ] && chown postgres "$WORK" && chmod 755 "$WORK"
cleanup() { as_pg "$PGBIN/pg_ctl" -D "$WORK/data" -m immediate stop >/dev/null 2>&1 || true; rm -rf "$WORK"; }
trap cleanup EXIT
as_pg "$PGBIN/initdb" -D "$WORK/data" -A trust -U postgres -E UTF8 --locale=C >/dev/null
as_pg "$PGBIN/pg_ctl" -D "$WORK/data" -o "-k $WORK -c listen_addresses=''" -l "$WORK/log" -w start >/dev/null
PSQL=("$PGBIN/psql" -h "$WORK" -U postgres -d postgres -v ON_ERROR_STOP=1 -qAt)
q() { as_pg "${PSQL[@]}" -c "$1"; }
run_file() { as_pg "${PSQL[@]}" -f "$1"; }
pass=0
ok() { pass=$((pass + 1)); echo "ok $pass - $1"; }
fail() { echo "FAIL - $1" >&2; exit 1; }
expect_error() { # $1 mô tả, $2 chuỗi lỗi phải có, phần còn lại: lệnh
  local label=$1 needle=$2; shift 2
  local out
  if out=$("$@" 2>&1); then fail "$label: lệnh chạy được nhưng lẽ ra phải lỗi"; fi
  grep -q -- "$needle" <<<"$out" || fail "$label: lỗi không chứa '$needle': $out"
}
copy_sql() { cp "$1" "$WORK/$2"; [ "$(id -u)" = 0 ] && chown postgres "$WORK/$2"; echo "$WORK/$2"; }

as_pg "${PSQL[@]}" <<'SQL'
CREATE TABLE public.org_staff (
  id bigint PRIMARY KEY, organization_id bigint NOT NULL, name text, username text,
  is_active boolean NOT NULL DEFAULT true, deleted_at timestamptz);
INSERT INTO public.org_staff (id, organization_id, name, username) SELECT g, 1 + g % 7, 'NV ' || g, 'nv' || g FROM generate_series(1, 2000) g;
CREATE TABLE public.auto_system_settings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, key text NOT NULL UNIQUE, value text, description text,
  is_secret boolean NOT NULL DEFAULT false, is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now());
-- id ghi tay như production (max 100) mà sequence chưa theo: preflight phải chặn.
INSERT INTO public.auto_system_settings (key, value) VALUES ('seed', 'x');
INSERT INTO public.auto_system_settings (id, key, value) SELECT g, 'k' || g, 'v' FROM generate_series(2, 99) g;
INSERT INTO public.auto_system_settings (id, key, value) VALUES (100, 'web.campaign_agent', '{"audience":"all"}');
SQL

expect_error "preflight chặn khi sequence thấp hơn max(id)" "sequence auto_system_settings_id_seq" run_file "$MIGRATION"
[ "$(q "SELECT count(*) FROM pg_attribute WHERE attrelid='public.org_staff'::regclass AND attname='web_campaign_form_version'")" = 0 ] \
  || fail "preflight lỗi mà cột đã được thêm"
ok "preflight chặn sequence thấp, không đổi gì"

q "SELECT setval('public.auto_system_settings_id_seq', 100)" >/dev/null

# Khóa bận: một phiên đang đọc org_staff giữ khóa 6 giây → ALTER chờ tối đa 3 giây rồi bỏ, không đổi gì.
as_pg "${PSQL[@]}" -c "BEGIN; SELECT count(*) FROM public.org_staff; SELECT pg_sleep(6); COMMIT;" >/dev/null &
holder=$!
sleep 1
start=$(date +%s)
expect_error "lock_timeout khi org_staff đang bị đọc" "lock timeout" run_file "$MIGRATION"
elapsed=$(( $(date +%s) - start ))
wait "$holder"
[ "$elapsed" -le 5 ] || fail "migration chờ khóa $elapsed giây (lẽ ra ~3 giây)"
[ "$(q "SELECT count(*) FROM public.auto_system_settings WHERE key='web.campaign_form'")" = 0 ] || fail "lock timeout mà khóa đã được ghi"
ok "lock_timeout 3 giây khi org_staff bận ($elapsed giây), không đổi gì"

run_file "$MIGRATION" >/dev/null
ok "apply V481"

[ "$(q "SELECT format_type(atttypid, atttypmod) || '|' || attnotnull || '|' || atthasdef FROM pg_attribute WHERE attrelid='public.org_staff'::regclass AND attname='web_campaign_form_version'")" = "text|false|false" ] \
  || fail "cột không phải text NULL không DEFAULT"
ok "cột text, cho NULL, không DEFAULT"
q "SELECT col_description('public.org_staff'::regclass, (SELECT attnum FROM pg_attribute WHERE attrelid='public.org_staff'::regclass AND attname='web_campaign_form_version'))" | grep -q "'1,2'" \
  || fail "thiếu COMMENT mô tả dạng '1,2'"
ok "COMMENT cột mô tả dạng danh sách"
[ "$(q "SELECT count(*) FROM public.org_staff WHERE web_campaign_form_version IS NOT NULL")" = 0 ] || fail "có nhân viên mang giá trị sau apply"
ok "mọi nhân viên NULL (vẫn form 1)"
[ "$(q "SELECT id || '|' || value || '|' || is_active || '|' || is_secret FROM public.auto_system_settings WHERE key='web.campaign_form'")" = '101|{"defaultVersion":1}|true|false' ] \
  || fail "khóa web.campaign_form sai"
ok "khóa web.campaign_form = {\"defaultVersion\":1}, id theo sequence"

for value in "1" "2" "1,2" "2,1" " 1 , 2 " "2,2" "" "   "; do
  q "UPDATE public.org_staff SET web_campaign_form_version = \$\$${value}\$\$ WHERE id = 7" >/dev/null || fail "chặn nhầm giá trị hợp lệ '$value'"
done
ok "nhận 1, 2, 1,2, 2,1, có khoảng trắng, trùng số, rỗng"
q "UPDATE public.org_staff SET web_campaign_form_version = 2 WHERE id = 8" >/dev/null
[ "$(q "SELECT web_campaign_form_version FROM public.org_staff WHERE id = 8")" = 2 ] || fail "gán số 2 không thành '2'"
ok "gán số 2 (không nháy) lưu thành '2'"
for value in "0" "3" "12" "1,3" "1;2" "1 2" "1," ",2" "a" "1,2,1,2,1,2,1,2,1,2,1"; do
  expect_error "chặn '$value'" "org_staff_web_campaign_form_version_check" q "UPDATE public.org_staff SET web_campaign_form_version = \$\$${value}\$\$ WHERE id = 9"
done
[ "$(q "SELECT coalesce(web_campaign_form_version, 'null') FROM public.org_staff WHERE id = 9")" = null ] || fail "giá trị sai vẫn được ghi"
ok "chặn 0, 3, 12, 1,3, 1;2, '1 2', dấu phẩy thừa, chữ, quá 20 ký tự"

expect_error "chạy lại bị từ chối" "đã apply" run_file "$MIGRATION"
ok "chạy lại bị từ chối"

# CHECK viết sai (nhận cả 3): postflight phải dừng và rollback cả migration.
q "BEGIN; SET LOCAL lock_timeout='3s'; ALTER TABLE public.org_staff DROP COLUMN web_campaign_form_version; DELETE FROM public.auto_system_settings WHERE key='web.campaign_form'; COMMIT;" >/dev/null
broken=$(copy_sql "$MIGRATION" broken.sql)
sed -i 's/\[12\]\[\[:space:\]\]\*(/[123][[:space:]]*(/' "$broken"
grep -q '\[123\]' "$broken" || fail "không dựng được bản CHECK sai"
expect_error "postflight bắt CHECK sai" "CHECK sai" run_file "$broken"
[ "$(q "SELECT count(*) FROM pg_attribute WHERE attrelid='public.org_staff'::regclass AND attname='web_campaign_form_version' AND NOT attisdropped")" = 0 ] \
  || fail "postflight lỗi mà cột vẫn còn"
ok "postflight chặn CHECK sai, rollback trọn"

run_file "$MIGRATION" >/dev/null
q "UPDATE public.org_staff SET web_campaign_form_version = '1,2' WHERE id IN (1, 2); UPDATE public.org_staff SET web_campaign_form_version = '2' WHERE id = 3" >/dev/null
q "UPDATE public.auto_system_settings SET value = '{\"defaultVersion\":\"1,2\"}' WHERE key = 'web.campaign_form'" >/dev/null
run_file "$ROLLBACK" >/dev/null
[ "$(q "SELECT count(*) FROM public.org_staff WHERE web_campaign_form_version IS NOT NULL")" = 0 ] || fail "rollback bước 1 còn nhân viên mang giá trị"
[ "$(q "SELECT value FROM public.auto_system_settings WHERE key='web.campaign_form'")" = '{"defaultVersion":1,"followCampaignForm":false}' ] || fail "rollback bước 1 không đặt lại mặc định"
[ "$(q "SELECT count(*) FROM pg_attribute WHERE attrelid='public.org_staff'::regclass AND attname='web_campaign_form_version' AND NOT attisdropped")" = 1 ] \
  || fail "rollback bước 1 đổi schema"
ok "rollback bước 1: mọi người về form 1 (cả khi sửa chiến dịch đã ghi Form 2), giữ schema"

step2=$(copy_sql "$ROLLBACK" rollback_step2.sql)
sed -n '/^-- BEGIN;/,/^-- COMMIT;/p' "$ROLLBACK" | sed 's/^-- //' > "$step2"
grep -q "DROP COLUMN" "$step2" || fail "không lấy được bước 2 của rollback"
run_file "$step2" >/dev/null
[ "$(q "SELECT count(*) FROM pg_attribute WHERE attrelid='public.org_staff'::regclass AND attname='web_campaign_form_version' AND NOT attisdropped")" = 0 ] \
  && [ "$(q "SELECT count(*) FROM public.auto_system_settings WHERE key='web.campaign_form'")" = 0 ] || fail "rollback bước 2 chưa gỡ hết"
ok "rollback bước 2: gỡ cột và khóa"

run_file "$MIGRATION" >/dev/null
[ "$(q "SELECT value FROM public.auto_system_settings WHERE key='web.campaign_form'")" = '{"defaultVersion":1}' ] || fail "apply lại sau gỡ không đúng"
ok "apply lại sau khi gỡ hẳn"

echo "V481: $pass/$pass ca đạt"
