const assert = require('node:assert/strict')
const { mkdtempSync, writeFileSync, rmSync } = require('node:fs')
const { join, resolve } = require('node:path')
const { tmpdir } = require('node:os')
const { build } = require('esbuild')
const { _electron } = require('playwright')

async function main() {
  const root = resolve(__dirname, '..')
  const directory = mkdtempSync(join(tmpdir(), 'akaagent-auxiliary-skip-ui-'))
  let app
  try {
    await build({ entryPoints: [join(__dirname, 'zalo-auxiliary-skip-ui-smoke.tsx')], outdir: directory,
      bundle: true, platform: 'browser', format: 'iife', jsx: 'automatic', target: 'chrome120',
      define: { 'process.env.NODE_ENV': '"development"' }, loader: { '.png': 'dataurl', '.svg': 'dataurl' }, logLevel: 'warning' })
    writeFileSync(join(directory, 'index.html'), '<!doctype html><html lang="vi"><meta charset="utf-8"><link rel="stylesheet" href="zalo-auxiliary-skip-ui-smoke.css"><body><div id="root"></div><script src="zalo-auxiliary-skip-ui-smoke.js"></script></body></html>')
    writeFileSync(join(directory, 'main.cjs'), `const { app, BrowserWindow } = require('electron'); app.whenReady().then(() => {
      const win = new BrowserWindow({ show: false, width: 1550, height: 1100, webPreferences: { sandbox: true, contextIsolation: true, nodeIntegration: false } });
      win.webContents.session.webRequest.onBeforeRequest((details, callback) => callback({ cancel: /^https?:/.test(details.url) }));
      win.loadFile(${JSON.stringify(join(directory, 'index.html'))});
    });`)
    const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE
    app = await _electron.launch({ executablePath: require('electron'), args: [join(directory, 'main.cjs')], cwd: root, env })
    const page = await app.firstWindow()
    page.setDefaultTimeout(15000)
    await page.waitForFunction(() => !!window.settingsSmoke)
    const form = page.locator('.campaign-full-modal')
    const tagGroup = form.getByRole('group', { name: 'Không gắn tag trong trường hợp', exact: true })
    const aliasGroup = form.getByRole('group', { name: 'Không đổi tên trong trường hợp', exact: true })
    for (const action of ['zalo_message_phone', 'zalo_message_friend', 'zalo_message_group_member', 'zalo_message_group_realtime', 'zalo_message_remarketing_customer', 'zalo_message_friend_recommendation']) {
      await page.evaluate(action => window.settingsSmoke.open('new', action), action)
      await form.getByLabel('Kiêm gắn tag Zalo', { exact: true }).check()
      await form.getByLabel('Kiêm đổi tên', { exact: true }).check()
      assert(!(await tagGroup.getByLabel('Đã là bạn bè', { exact: true }).isChecked()))
      assert(!(await tagGroup.getByLabel('Đã có tag', { exact: true }).isChecked()))
      assert(!(await aliasGroup.getByLabel('Đã là bạn bè', { exact: true }).isChecked()))
    }
    for (const mode of ['edit', 'clone', 'draft']) {
      await page.evaluate(mode => window.settingsSmoke.open(mode), mode)
      await tagGroup.getByLabel('VIP', { exact: true }).waitFor()
      assert(await tagGroup.getByLabel('Đã là bạn bè', { exact: true }).isChecked())
      assert(await tagGroup.getByLabel('VIP', { exact: true }).isChecked())
      assert(await tagGroup.getByLabel('Khách cũ Zalo', { exact: true }).isChecked())
      assert(await aliasGroup.getByLabel('Đã là bạn bè', { exact: true }).isChecked())
      if (mode === 'edit') continue
      await form.getByRole('button', { name: 'Lưu nháp', exact: true }).click()
      await page.waitForFunction(() => window.settingsSmoke.state.calls.some(call => call.method === 'saveCampaignDraft'))
      const savedValues = await page.evaluate(() => window.settingsSmoke.state.calls.find(call => call.method === 'saveCampaignDraft').args[0].payload.values)
      const saved = savedValues.formData
      assert.deepEqual(savedValues.zaloTagSettingsByAccountId['11'].zaloTagSkipTagIds, ['8', '9'])
      assert.equal(saved.zaloTagSkipIfFriend, true); assert.equal(saved.zaloAliasSkipIfFriend, true)
      assert.equal(saved.zaloTagSkipIfHasSelectedTags, true)
    }
    await page.evaluate(() => window.settingsSmoke.open('edit'))
    await tagGroup.getByLabel('VIP', { exact: true }).waitFor()
    await page.evaluate(() => { window.settingsSmoke.state.failZaloLabels = true })
    await form.getByRole('button', { name: 'Tải tag', exact: true }).first().click()
    await tagGroup.getByRole('alert').filter({ hasText: 'offline' }).waitFor()
    assert(await tagGroup.getByLabel('VIP', { exact: true }).isChecked())
    await page.evaluate(() => { window.settingsSmoke.state.failZaloLabels = false })
    await tagGroup.getByLabel('VIP', { exact: true }).uncheck()
    await tagGroup.getByLabel('Khách cũ Zalo', { exact: true }).uncheck()
    await form.getByRole('button', { name: 'Lưu chiến dịch', exact: true }).click()
    await page.waitForFunction(() => window.settingsSmoke.state.alerts.some(alert => alert.message.includes('ít nhất một tag')))
    assert.equal(await page.evaluate(() => window.settingsSmoke.state.calls.filter(call => call.method === 'updateCampaign').length), 0)
    await tagGroup.getByLabel('VIP', { exact: true }).check()
    await form.getByRole('button', { name: 'Lưu chiến dịch', exact: true }).click()
    await page.waitForFunction(() => window.settingsSmoke.state.calls.some(call => call.method === 'updateCampaign'))
    const saved = await page.evaluate(() => window.settingsSmoke.state.calls.find(call => call.method === 'updateCampaign').args[1].extraSettings)
    assert.deepEqual(saved.zaloTagSkipTagIds, ['8'])
    assert.deepEqual(Object.keys(saved.zaloTagSettingsByAccountId), ['11'])
    assert.deepEqual(saved.zaloTagSettingsByAccountId['11'].zaloTagSkipTagIds, ['8'])
    assert.equal(saved.zaloTagSkipIfFriend, true); assert.equal(saved.zaloAliasSkipIfFriend, true)
    assert.equal(saved.zaloTagSkipIfHasSelectedTags, true)

    await form.waitFor({ state: 'detached' })
    await page.evaluate(() => window.settingsSmoke.open('draft'))
    await tagGroup.getByLabel('VIP', { exact: true }).waitFor()
    await form.getByText(/^Zalo 11 —/).first().click()
    const oldAccount = form.locator('.account-select-account-row').filter({ hasText: 'Zalo 11' }).locator('input')
    if (await oldAccount.getAttribute('type') === 'checkbox') await oldAccount.uncheck()
    await form.locator('.account-select-account-row').filter({ hasText: 'Zalo 12' }).locator('input').check()
    await page.getByText('Không gắn tag trong trường hợp', { exact: true }).click()
    await tagGroup.getByLabel('VIP', { exact: true }).waitFor()
    assert(!(await tagGroup.getByLabel('VIP', { exact: true }).isChecked()))
    assert(!(await tagGroup.getByLabel('Khách cũ Zalo', { exact: true }).isChecked()))
    await page.screenshot({ path: '/tmp/akaagent-zalo-auxiliary-skip-ui.png' })
    await form.getByLabel('Gửi dạng chia sẻ tin nhắn, gửi nhanh cho 50 người mỗi lần (không áp dụng cá nhân hoá nội dung tin nhắn)', { exact: true }).check()
    assert.equal(await tagGroup.count(), 0)
    assert.equal(await aliasGroup.count(), 0)


    // Multiple primaries: same tag names deliberately have different IDs per account.
    await page.evaluate(() => window.settingsSmoke.open('draft', 'zalo_message_friend_recommendation'))
    await tagGroup.getByLabel('VIP', { exact: true }).waitFor()
    await form.getByText(/^Zalo 11 —/).first().click()
    await form.locator('.account-select-account-row').filter({ hasText: 'Zalo 12' }).locator('input').check()
    await page.getByText('Không gắn tag trong trường hợp', { exact: true }).click()
    await form.getByRole('button', { name: 'Tạo chiến dịch', exact: true }).click()
    await page.waitForFunction(() => window.settingsSmoke.state.alerts.some(alert => alert.message.includes('tag Zalo cần gắn cho tài khoản Zalo 12')))
    assert.equal(await page.evaluate(() => window.settingsSmoke.state.calls.filter(call => call.method === 'createCampaign').length), 0)
    const accountPicker = tagGroup.getByLabel('Tài khoản cấu hình tag', { exact: true })
    await accountPicker.selectOption('12')
    await tagGroup.getByLabel('Tag cần gắn', { exact: true }).selectOption('17')
    await form.getByRole('button', { name: 'Tạo chiến dịch', exact: true }).click()
    await page.waitForFunction(() => window.settingsSmoke.state.alerts.some(alert => alert.message.includes('ít nhất một tag') && alert.message.includes('Zalo 12')))
    await tagGroup.getByLabel('VIP', { exact: true }).check()
    await accountPicker.selectOption('11')
    assert.equal(await tagGroup.getByLabel('Tag cần gắn', { exact: true }).inputValue(), '7')
    assert(await tagGroup.getByLabel('VIP', { exact: true }).isChecked())
    await form.getByRole('button', { name: 'Lưu nháp', exact: true }).click()
    await page.waitForFunction(() => window.settingsSmoke.state.calls.some(call => call.method === 'saveCampaignDraft'))
    const multipleDraft = await page.evaluate(() => window.settingsSmoke.state.calls.find(call => call.method === 'saveCampaignDraft').args[0])
    assert.deepEqual(multipleDraft.payload.values.zaloTagSettingsByAccountId['12'].zaloTagSkipTagIds, ['18'])
    await page.evaluate(draft => window.settingsSmoke.open('draft', 'zalo_message_friend_recommendation', { savedDraft: draft }), multipleDraft)
    await accountPicker.selectOption('12')
    assert.equal(await tagGroup.getByLabel('Tag cần gắn', { exact: true }).inputValue(), '17')
    assert(await tagGroup.getByLabel('VIP', { exact: true }).isChecked())
    await form.getByRole('button', { name: 'Tạo chiến dịch', exact: true }).click()
    await page.waitForFunction(() => window.settingsSmoke.state.calls.filter(call => call.method === 'createCampaign').length === 2)
    const created = await page.evaluate(() => window.settingsSmoke.state.calls.filter(call => call.method === 'createCampaign').map(call => call.args[0]))
    assert.deepEqual(created.map(item => [item.accountId, item.extraSettings.zaloTagId, item.extraSettings.zaloTagSkipTagIds]), [[11, '7', ['8', '9']], [12, '17', ['18']]])
    assert.deepEqual(created.map(item => Object.keys(item.extraSettings.zaloTagSettingsByAccountId)), [['11'], ['12']])
    await form.waitFor({ state: 'detached' })

    // Secondary account: require its own configuration and preserve it on edit/clone.
    await page.evaluate(() => window.settingsSmoke.open('edit', 'zalo_message_friend', { campaign: { secondaryAccountId: 12 } }))
    await tagGroup.getByLabel('VIP', { exact: true }).waitFor()
    await form.getByRole('button', { name: 'Lưu chiến dịch', exact: true }).click()
    await page.waitForFunction(() => window.settingsSmoke.state.alerts.some(alert => alert.message.includes('tag Zalo cần gắn cho tài khoản Zalo 12')))
    await accountPicker.selectOption('12')
    await tagGroup.getByLabel('Tag cần gắn', { exact: true }).selectOption('17')
    await tagGroup.getByLabel('VIP', { exact: true }).check()
    await form.getByRole('button', { name: 'Lưu chiến dịch', exact: true }).click()
    await page.waitForFunction(() => window.settingsSmoke.state.calls.some(call => call.method === 'updateCampaign'))
    const fallbackCampaign = await page.evaluate(() => window.settingsSmoke.state.calls.find(call => call.method === 'updateCampaign').args[1])
    assert.deepEqual(Object.keys(fallbackCampaign.extraSettings.zaloTagSettingsByAccountId), ['11', '12'])
    assert.deepEqual(fallbackCampaign.extraSettings.zaloTagSettingsByAccountId['12'].zaloTagSkipTagIds, ['18'])
    await form.waitFor({ state: 'detached' })
    for (const mode of ['edit', 'clone']) {
      await page.evaluate(({mode, campaign}) => window.settingsSmoke.open(mode, 'zalo_message_friend', { campaign }), {mode, campaign: fallbackCampaign})
      await accountPicker.selectOption('12')
      assert.equal(await tagGroup.getByLabel('Tag cần gắn', { exact: true }).inputValue(), '17')
      assert(await tagGroup.getByLabel('VIP', { exact: true }).isChecked())
    }
    // Late read from B must not populate A's picker or change either saved setting.
    await accountPicker.selectOption('11')
    await page.evaluate(() => { window.settingsSmoke.state.holdLabels = 12 })
    await accountPicker.selectOption('12')
    await page.waitForFunction(() => window.settingsSmoke.state.pendingLabels.length === 1)
    await accountPicker.selectOption('11')
    await page.evaluate(() => { window.settingsSmoke.state.pendingLabels.splice(0).forEach(resolve => resolve()); window.settingsSmoke.state.holdLabels = null })
    await tagGroup.getByLabel('Tag cần gắn', { exact: true }).waitFor()
    assert.equal(await tagGroup.getByLabel('Tag cần gắn', { exact: true }).inputValue(), '7')
    assert.equal(await tagGroup.getByLabel('Tag cần gắn', { exact: true }).locator('option[value="17"]').count(), 0)
    // A successful empty catalog refresh also keeps the saved selections visible.
    await page.evaluate(() => { window.settingsSmoke.state.emptyLabels = true })
    await tagGroup.getByRole('button', { name: 'Tải tag', exact: true }).first().click()
    assert.equal(await tagGroup.getByLabel('Tag cần gắn', { exact: true }).inputValue(), '7')
    assert(await tagGroup.getByLabel('VIP', { exact: true }).isChecked())
    await page.evaluate(() => { window.settingsSmoke.state.emptyLabels = false })
    // Removing/replacing the secondary account clears its selection, without moving tags to C.
    const secondary = form.locator('select').filter({ has: page.locator('option', { hasText: '-- Không sử dụng tài khoản phụ --' }) })
    await secondary.selectOption('13')
    await accountPicker.selectOption('13')
    await tagGroup.getByLabel('Tag cần gắn', { exact: true }).selectOption('27')
    assert(!(await tagGroup.getByLabel('VIP', { exact: true }).isChecked()))
    await tagGroup.getByLabel('VIP', { exact: true }).check()
    await tagGroup.scrollIntoViewIfNeeded()
    await page.screenshot({ path: '/tmp/akaagent-zalo-account-tags-ui.png' })
    await form.getByRole('button', { name: 'Lưu nháp', exact: true }).click()
    await page.waitForFunction(() => window.settingsSmoke.state.calls.some(call => call.method === 'saveCampaignDraft'))
    const replaced = await page.evaluate(() => window.settingsSmoke.state.calls.find(call => call.method === 'saveCampaignDraft').args[0].payload.values.zaloTagSettingsByAccountId)
    assert.deepEqual(Object.keys(replaced), ['11', '13'])
    assert.deepEqual(replaced['13'].zaloTagSkipTagIds, ['28'])
    assert.deepEqual(await page.evaluate(() => window.settingsSmoke.state.errors), [])

    // Capture the actual shared form layout in both themes and at a narrow width.
    await page.evaluate(() => window.settingsSmoke.open('edit'))
    const auxiliary = form.locator('.zalo-auxiliary-actions').filter({ has: page.getByLabel('Kiêm gắn tag Zalo', { exact: true }) })
    await tagGroup.getByLabel('VIP', { exact: true }).waitFor()
    assert.equal(await tagGroup.getByRole('button', { name: 'Tải tag', exact: true }).count(), 1)
    await form.getByLabel('Kiêm gắn tag akaBiz', { exact: true }).check()
    await form.locator('.akabiz-tag-card').getByLabel('Khách cũ', { exact: true }).check()
    await page.mouse.move(0, 0)
    await form.locator('.akabiz-tag-card').screenshot({ path: '/tmp/akaagent-akabiz-tag-card.png', animations: 'disabled' })
    await auxiliary.screenshot({ path: '/tmp/akaagent-zalo-auxiliary-redesign-wide.png', animations: 'disabled' })
    await page.evaluate(() => document.body.classList.add('theme-light'))
    await auxiliary.screenshot({ path: '/tmp/akaagent-zalo-auxiliary-redesign-light.png', animations: 'disabled' })
    await page.evaluate(() => document.body.classList.remove('theme-light'))
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1550, 1450))
    await auxiliary.evaluate(element => { element.style.width = '360px'; element.style.maxWidth = '100%' })
    await auxiliary.screenshot({ path: '/tmp/akaagent-zalo-auxiliary-redesign-narrow.png', animations: 'disabled' })
    assert(await auxiliary.evaluate(element => element.scrollWidth <= element.clientWidth), 'Auxiliary settings must not overflow in a narrow panel')
    console.log('PASS UI: legacy/all forms, account-specific bulk save, secondary validation/edit/clone, draft restore, account replacement, late catalog isolation and Share')
  } catch (error) {
    if (app) {
      const page = await app.firstWindow()
      console.error(await page.evaluate(() => ({ alerts: window.settingsSmoke.state.alerts,
        errors: window.settingsSmoke.state.errors, calls: window.settingsSmoke.state.calls.slice(-10),
        buttons: [...document.querySelectorAll('.modal-footer button')].map(button => button.textContent) })))
    }
    throw error
  } finally {
    await app?.close()
    rmSync(directory, { recursive: true, force: true })
  }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
