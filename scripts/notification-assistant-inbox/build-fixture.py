#!/usr/bin/env python3
"""Dựng nền Trợ lý aka cho bài kiểm V624 từ bản đọc chỉ-đọc của production.

Vào: tệp JSON do câu đọc ở đầu tệp này trả về (bảng ai_*, mọi hàm aka_agent_ai_* / aka_agent_control_ai_*, nhóm và agent).
Ra:  scripts/notification-assistant-inbox/fixture_assistant.sql (nạp sau nền thông báo của pgenv.sh + V621 + V622).

Câu đọc (chạy trong `begin read only`, thêm `repeat('x', 140000) as pad` để kết quả lưu ra tệp):
  bảng: cột (format_type, NOT NULL, DEFAULT, identity), ràng buộc, chỉ mục, trigger của ai_assistant_state, ai_attachment,
  ai_image_request, ai_message, ai_message_context, ai_message_thread, ai_model, ai_project, ai_project_group, ai_schedule;
  hàm: pg_get_functiondef của mọi hàm public/private tên ^aka_agent_(ai_|control_ai_) + aka_agent_notification_refresh_channel_state;
  dòng: ai_project_group, ai_project (không có ai_model: bảng đó giữ khóa API).
Dùng: python3 scripts/notification-assistant-inbox/build-fixture.py <tệp JSON>
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'scripts' / 'notification-assistant-inbox' / 'fixture_assistant.sql'

dump = json.loads(Path(sys.argv[1]).read_text(encoding='utf-8'))
tables = {t['t']: t for t in dump['tables']}
present = set(tables)


def lit(v) -> str:
    if v is None:
        return 'NULL'
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, (dict, list)):
        v = json.dumps(v, ensure_ascii=False)
    return "'" + str(v).replace("'", "''") + "'"


out: list[str] = [
    '-- Sinh bằng scripts/notification-assistant-inbox/build-fixture.py từ bản đọc production 22/11/2026. Không sửa tay.',
    "SET check_function_bodies = off;",
]
for name, t in tables.items():
    cols = []
    for c in t['cols']:
        s = f'  {c["n"]} {c["type"]}'
        if c['ident'] == 'a':
            s += ' GENERATED ALWAYS AS IDENTITY'
        elif c['ident'] == 'd':
            s += ' GENERATED BY DEFAULT AS IDENTITY'
        elif c['def'] is not None:
            s += f' DEFAULT {c["def"]}'
        if c['nn']:
            s += ' NOT NULL'
        cols.append(s)
    out.append(f'CREATE TABLE public.{name} (\n' + ',\n'.join(cols) + '\n);')

for f in dump['fns']:
    out.append(f['def'].rstrip('\n') + ';')

# Khóa chính / duy nhất / kiểm tra của mọi bảng trước, khóa ngoại sau (khóa ngoại cần khóa chính của bảng đích).
for kinds in (('p', 'u', 'c'), ('f',)):
    for name, t in tables.items():
        for c in sorted(t['cons'] or [], key=lambda c: (c['type'], c['n'])):
            if c['type'] not in kinds:
                continue
            if c['type'] == 'f':
                target = c['def'].split('REFERENCES ')[1].split('(')[0].strip().split('.')[-1]
                if target not in present:
                    continue
            out.append(f'ALTER TABLE public.{name} ADD CONSTRAINT {c["n"]} {c["def"]};')
for name, t in tables.items():
    for i in t['idx'] or []:
        out.append(i + ';')
    for g in t['trg'] or []:
        out.append(g + ';')


def rows(table: str, items: list[dict]) -> None:
    cols = [c['n'] for c in tables[table]['cols']]
    ident = any(c['ident'] == 'a' for c in tables[table]['cols'])
    for r in items:
        names = [c for c in cols if c in r]
        values = []
        for c in names:
            v = r[c]
            values.append(lit(v))
        override = ' OVERRIDING SYSTEM VALUE' if ident else ''
        out.append(f'INSERT INTO public.{table} ({", ".join(names)}){override} VALUES ({", ".join(values)});')


rows('ai_project_group', dump['groups'])
# Các khóa model / form / loại chiến dịch không có ở nền thử: để trống.
projects = [{k: (None if k in ('model_id', 'fallback_model_id', 'form_config_id', 'campaign_action_id') else v) for k, v in p.items()}
            for p in dump['projects']]
rows('ai_project', projects)
OUT.write_text('\n'.join(out) + '\n', encoding='utf-8')
print(f'{OUT.relative_to(ROOT)}: {len(dump["fns"])} hàm, {len(tables)} bảng, {OUT.stat().st_size} byte')
