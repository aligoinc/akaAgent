#!/usr/bin/env bash
# Thử V674 ("Đặt ngày kết thúc" dừng chiến dịch đúng ngày) trên PostgreSQL 16 cục bộ, không chạm production.
# Fixture: bảng tối thiểu + NGUYÊN VĂN 4 hàm production đọc 27/11/2026 (scripts/fixtures/campaign-schedule-end/live-20261127.json),
# các hàm phụ chúng gọi là bản thay không làm gì.
# Kiểm: p1 / p2 / p3 apply, chiến dịch chưa bật cột chạy đúng như trước (so từng ca với bản production), chiến dịch bật cột dừng đúng
# ngày ở cả hai hàm kết thúc, không bị mở lại, job quét, tạo / sửa từ Web, apply lại bị từ chối, bản gỡ trả đúng md5 cũ.
# Dùng: bash scripts/test-v674-campaign-schedule-end.sh   (PGBIN mặc định /usr/lib/postgresql/16/bin)
set -euo pipefail
PGBIN=${PGBIN:-/usr/lib/postgresql/16/bin}
ROOT=$(cd "$(dirname "$0")/.." && pwd)
MIG="$ROOT/migrations"
BASE=v674_campaign_schedule_end_strict
FIXTURE="$ROOT/scripts/fixtures/campaign-schedule-end/live-20261127.json"
WORK=$(mktemp -d "${TMPDIR:-/tmp}/v674.XXXXXX")
as_pg() { if [ "$(id -u)" = 0 ]; then runuser -u postgres -- "$@"; else "$@"; fi; }
[ "$(id -u)" = 0 ] && chown postgres "$WORK"
chmod 755 "$WORK"
cleanup() { as_pg "$PGBIN/pg_ctl" -D "$WORK/data" -m immediate stop >/dev/null 2>&1 || true; rm -rf "$WORK"; }
trap cleanup EXIT
as_pg "$PGBIN/initdb" -D "$WORK/data" -A trust -U postgres -E UTF8 --locale=C >/dev/null
as_pg "$PGBIN/pg_ctl" -D "$WORK/data" -o "-k $WORK -c listen_addresses=''" -l "$WORK/log" -w start >/dev/null
psql_db() { as_pg "$PGBIN/psql" -h "$WORK" -U postgres -d fixture -v ON_ERROR_STOP=1 -qAt "$@"; }
q() { psql_db -c "$1"; }
run_file() { psql_db -f "$1" 2>&1; }
pass=0
ok() { pass=$((pass + 1)); echo "ok $pass - $1"; }
fail() { echo "FAIL - $1" >&2; exit 1; }
expect() { [ "$2" = "$3" ] && ok "$1" || fail "$1 (mong đợi '$3', nhận '$2')"; }
refuse() { local name=$1 pattern=$2 out; shift 2; if out=$("$@" 2>&1); then fail "$name (không bị từ chối)"; fi
  case "$out" in *"$pattern"*) ok "$name" ;; *) fail "$name (thông báo khác: $out)" ;; esac; }

as_pg "$PGBIN/psql" -h "$WORK" -U postgres -d postgres -v ON_ERROR_STOP=1 -q <<'SQL'
