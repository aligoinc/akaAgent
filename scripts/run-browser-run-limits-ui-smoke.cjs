const assert = require('node:assert/strict')
const { mkdtempSync, writeFileSync, rmSync } = require('node:fs')
const { join, resolve } = require('node:path')
const { tmpdir } = require('node:os')
const { build } = require('esbuild')
const { _electron } = require('playwright')
async function main() {
  const dir = mkdtempSync(join(tmpdir(), 'aka-browser-limits-ui-'))
  let app
  try {
    await build({ entryPoints: [join(__dirname, 'browser-run-limits-ui-smoke.tsx')], outdir: dir, bundle: true, platform: 'browser', format: 'iife', jsx: 'automatic', target: 'chrome120', define: { 'process.env.NODE_ENV': '"development"' }, logLevel: 'warning' })
    writeFileSync(join(dir, 'index.html'), '<!doctype html><html lang="vi"><meta charset="utf-8"><link rel="stylesheet" href="browser-run-limits-ui-smoke.css"><body><div id="root"></div><script src="browser-run-limits-ui-smoke.js"></script></body></html>')
    writeFileSync(join(dir, 'main.cjs'), `const {app,BrowserWindow}=require('electron');app.whenReady().then(()=>{const win=new BrowserWindow({show:false,width:1280,height:920,webPreferences:{sandbox:true,contextIsolation:true,nodeIntegration:false}});win.webContents.session.webRequest.onBeforeRequest((d,c)=>c({cancel:/^https?:/.test(d.url)}));win.loadFile(${JSON.stringify(join(dir, 'index.html'))});});`)
    const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE
    app = await _electron.launch({ executablePath: require('electron'), args: [join(dir, 'main.cjs')], cwd: resolve(__dirname, '..'), env })
    const page = await app.firstWindow(); page.setDefaultTimeout(10000)
    await page.waitForFunction(() => !!window.limitsSmoke)
    assert.equal(await page.evaluate(() => window.limitsSmoke.state.reads), 0, 'lazy settings read')
    const menu = page.getByRole('button', { name: 'Giới hạn tài khoản chạy', exact: true })
    const card = page.locator('.browser-run-limits-settings')
    const zalo = card.getByLabel('Giới hạn số Zalo (trình duyệt) cùng chạy một lúc', { exact: true })
    const facebook = card.getByLabel('Giới hạn số Facebook cùng chạy một lúc', { exact: true })
    const save = card.getByRole('button', { name: 'Lưu', exact: true })
    await menu.click(); await save.waitFor(); await zalo.waitFor({ state: 'visible' })
    await page.waitForFunction(() => !document.querySelector('.browser-run-limits-settings fieldset').disabled)
    assert.equal(await zalo.inputValue(), ''); assert.equal(await facebook.inputValue(), '')
    for (const bad of ['0', '-1', '1.5', 'abc']) {
      await facebook.fill(bad); await save.click(); assert.match(await card.getByRole('alert').innerText(), /số nguyên dương/)
    }
    assert.equal(await page.evaluate(() => window.limitsSmoke.state.saves.length), 0)
    await zalo.fill('2'); await facebook.fill('3'); await save.click()
    await card.getByText('Đã lưu giới hạn tài khoản chạy.', { exact: true }).waitFor()
    assert.deepEqual(await page.evaluate(() => window.limitsSmoke.state.saves.at(-1)), { zaloWebMax: 2, facebookMax: 3, revision: 0 })
    await facebook.fill(''); await save.click()
    await page.waitForFunction(() => window.limitsSmoke.state.settings.facebookMax === null)
    await page.evaluate(() => { window.limitsSmoke.state.conflict = true })
    await facebook.fill('7'); await save.click(); assert.match(await card.getByRole('alert').innerText(), /máy khác/)
    assert.equal(await facebook.inputValue(), '7'); assert(await save.isDisabled())
    await page.evaluate(() => { window.limitsSmoke.state.conflict = false })
    await card.getByRole('button', { name: 'Tải lại cấu hình' }).click()
    await page.waitForFunction(() => !document.querySelector('.browser-run-limits-settings fieldset').disabled)
    assert.equal(await facebook.inputValue(), '')
    await page.evaluate(() => { window.limitsSmoke.state.failSave = true })
    await facebook.fill('9'); await save.click(); assert.match(await card.getByRole('alert').innerText(), /Chưa xác nhận/)
    assert.equal(await facebook.inputValue(), '9')
    await page.evaluate(() => { window.limitsSmoke.state.failSave = false; window.limitsSmoke.state.deferSave = true })
    await save.click(); assert(await page.getByTitle('Đóng', { exact: true }).isDisabled())
    await page.evaluate(() => { window.limitsSmoke.state.settings = { zaloWebMax: 5, facebookMax: 6, revision: 0 }; window.limitsSmoke.switchUser() })
    await page.waitForFunction(() => document.querySelector('#browser-run-limits-facebook').value === '6')
    await page.evaluate(() => { window.limitsSmoke.resolve(); window.limitsSmoke.state.deferSave = false })
    assert.equal(await facebook.inputValue(), '6', 'late save cannot overwrite new staff')
    assert.equal(await card.getByText('Đã lưu giới hạn tài khoản chạy.', { exact: true }).count(), 0)
    for (const theme of ['dark', 'light']) {
      await page.evaluate(theme => document.body.classList.toggle('theme-light', theme === 'light'), theme)
      for (const width of [1280, 780]) {
        await app.evaluate(({BrowserWindow}, width) => BrowserWindow.getAllWindows()[0].setSize(width, 920), width)
        await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
        assert(await card.evaluate(el => el.scrollWidth <= el.clientWidth + 1), 'no horizontal overflow')
        await page.screenshot({ path: `/tmp/aka-browser-run-limits-${theme}-${width}.png` })
      }
    }
    await page.evaluate(() => { window.limitsSmoke.state.failGet = true; window.limitsSmoke.open() })
    await menu.click(); await card.getByRole('alert').waitFor(); assert(await save.isDisabled())
    await page.evaluate(() => { window.limitsSmoke.state.failGet = false })
    await card.getByRole('button', { name: 'Thử lại' }).click()
    await page.waitForFunction(() => !document.querySelector('.browser-run-limits-settings fieldset').disabled)
    assert.equal(await facebook.inputValue(), '6')
    assert.deepEqual(await page.evaluate(() => window.limitsSmoke.state.errors), [])
    console.log('PASS real settings modal: lazy load, unlimited/validation/save, CAS drafts, network retry, busy close guard, late response after auth change, light/dark 1280/780px')
  } finally { if (app) await app.close(); rmSync(dir, { recursive: true, force: true }) }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
