// Thẻ "Không gửi cho" (V654) trên Chromium của Playwright với IPC giả: thêm chiến dịch đã gửi, Nhóm data, danh sách của Zalo khác,
// tạo nhóm điều kiện 2 Zalo, dùng chung cho mọi Zalo gửi rồi đặt riêng, Zalo gửi mới nhận cùng lựa chọn.
//   node scripts/run-send-exclusion-card-ui-smoke.cjs        (SX_UI_SHOTS=<thư mục> để chụp màn hình)
const assert = require('node:assert/strict')
const {mkdtempSync, writeFileSync, rmSync, mkdirSync} = require('node:fs')
const {join} = require('node:path')
const {tmpdir} = require('node:os')
const {build} = require('esbuild')
const {chromium} = require('playwright')
async function main() {
  const dir = mkdtempSync(join(tmpdir(), 'akaagent-sx-card-ui-'))
  const shots = process.env.SX_UI_SHOTS || ''
  if (shots) mkdirSync(shots, {recursive: true})
  await build({entryPoints: [join(__dirname, 'send-exclusion-card-ui-smoke.tsx')], outdir: dir, bundle: true, platform: 'browser', format: 'iife',
    jsx: 'automatic', target: 'chrome120', define: {'process.env.NODE_ENV': '"development"'},
    loader: {'.png': 'dataurl', '.svg': 'dataurl', '.woff2': 'dataurl', '.woff': 'dataurl', '.ttf': 'dataurl'}, logLevel: 'warning'})
  writeFileSync(join(dir, 'index.html'), '<!doctype html><html lang="vi"><meta charset="utf-8"><link rel="stylesheet" href="send-exclusion-card-ui-smoke.css"><body class="theme-light"><div id="root"></div><script src="send-exclusion-card-ui-smoke.js"></script></body></html>')
  const {existsSync} = require('node:fs')
  const executablePath = process.env.SX_UI_CHROMIUM || (existsSync('/opt/pw-browsers/chromium') ? '/opt/pw-browsers/chromium' : '')
  const browser = await chromium.launch(executablePath ? {executablePath, args: ['--no-sandbox']} : {})
  let passed = 0
  const ok = name => { passed++; console.log('PASS', name) }
  try {
    const context = await browser.newContext({viewport: {width: 1100, height: 1000}, locale: 'vi-VN'})
    await context.route(/^https?:/, route => route.abort())
    const page = await context.newPage(); page.setDefaultTimeout(10000)
    const errors = []; page.on('pageerror', e => errors.push(e.message))
    await page.goto('file://' + join(dir, 'index.html'))
    const value = () => page.evaluate(() => window.cardSmoke.value)
    const card = page.getByRole('region', {name: 'Không gửi cho'})
    await card.getByText('Khách đã từ chối nhận tin', {exact: true}).waitFor()
    assert.ok(await card.getByText('Chưa có loại trừ nào').isVisible())
    ok('thẻ trống: chỉ có dòng khách đã từ chối nhận tin')

    // Chiến dịch đã gửi: chọn 2, dùng chung cho cả 2 Zalo gửi.
    await card.getByRole('button', {name: 'Thêm loại trừ'}).click()
    await page.getByRole('menuitem', {name: /Khách đã được gửi tin ở chiến dịch/}).click()
    let dialog = page.getByRole('dialog')
    await dialog.getByText('Khuyến mãi tháng 10').waitFor()
    await dialog.getByRole('checkbox', {name: /Khuyến mãi tháng 10/}).check()
    await dialog.getByRole('checkbox', {name: /Chăm sóc khách VIP/}).check()
    assert.match(await dialog.locator('.exclusion-footnote').innerText(), /Đã chọn 2 · 3\.610/)
    await dialog.getByRole('button', {name: 'Đang chạy', exact: true}).click()
    assert.equal(await dialog.locator('.sx-pick').count(), 1)
    if (shots) await page.screenshot({path: join(shots, 'campaign-picker.png')})
    await dialog.getByRole('button', {name: 'Xong'}).click()
    await dialog.waitFor({state: 'hidden'})
    let v = await value()
    assert.deepEqual(v['100'], {groupId: null, blocklistIds: [], dataGroupIds: [], sentCampaignIds: [801, 802]})
    assert.deepEqual(v['101'], v['100'])
    // V657: dòng xem trước dùng đúng lựa chọn đang có (đếm theo nguồn, chưa xác định tính riêng).
    await card.locator('.sx-preview').getByText(/240 data sẽ không được gửi/).waitFor({timeout: 5000})
    assert.match(await card.locator('.sx-preview').innerText(), /Xem trước: Trong 500 data: 240 data sẽ không được gửi \(120 do chiến dịch “Khuyến mãi tháng 10”, 120 do chiến dịch “Chăm sóc khách VIP”\)\. 7 data chưa xác định được, sẽ kiểm khi chạy\./)
    assert.match(await card.textContent(), /Khuyến mãi tháng 10 · 3\.200 khách/)
    ok('chiến dịch đã gửi: chọn nhiều, lọc theo trạng thái, áp cho mọi Zalo gửi')

    // Nhóm data.
    await card.getByRole('button', {name: 'Thêm loại trừ'}).click()
    await page.getByRole('menuitem', {name: /Khách có trong Nhóm data/}).click()
    dialog = page.getByRole('dialog')
    await dialog.getByRole('searchbox', {name: 'Tìm theo tên'}).fill('nội bộ')
    await dialog.getByRole('checkbox', {name: /Nhân viên nội bộ/}).check()
    await dialog.getByRole('button', {name: 'Xong'}).click()
    v = await value()
    assert.deepEqual(v['101'].dataGroupIds, [12])
    assert.match(await card.textContent(), /Nhân viên nội bộ · 35 data/)
    ok('Nhóm data: tìm theo tên, chọn')

    // Danh sách của Zalo khác.
    await card.getByRole('button', {name: 'Thêm loại trừ'}).click()
    await page.getByRole('menuitem', {name: /danh sách bạn bè\/Zalo ID/}).click()
    dialog = page.getByRole('dialog')
    await dialog.getByRole('checkbox', {name: /Khách cũ/}).check()
    await dialog.getByRole('button', {name: 'Xong'}).click()
    assert.deepEqual((await value())['100'].blocklistIds, [9])
    ok('danh sách bạn bè/Zalo ID của Zalo khác chọn được')

    // Nhóm điều kiện 2 Zalo.
    await card.getByRole('button', {name: 'Thêm loại trừ'}).click()
    await page.getByRole('menuitem', {name: /Khách theo điều kiện ở Zalo/}).click()
    dialog = page.getByRole('dialog')
    assert.ok(await dialog.getByRole('button', {name: 'Lưu và dùng'}).isDisabled())
    await dialog.getByLabel('Tên nhóm').fill('Khách đã chăm sóc')
    await dialog.getByRole('checkbox', {name: /Zalo Shop/}).check()
    const first = dialog.getByRole('region', {name: 'Điều kiện ở Zalo Minh Thư'})
    await first.getByRole('button', {name: 'Thêm điều kiện'}).click()
    await first.getByRole('menuitem', {name: 'Trạng thái bạn bè'}).click()
    await first.getByRole('button', {name: 'Thêm điều kiện'}).click()
    await first.getByRole('menuitem', {name: 'Tag Zalo'}).click()
    await first.getByRole('button', {name: 'Chọn tag'}).click()
    await first.getByRole('checkbox', {name: 'Đã mua'}).check()
    await first.getByLabel('Cách kết hợp ở Zalo Minh Thư').selectOption('or')
    const second = dialog.getByRole('region', {name: 'Điều kiện ở Zalo Shop'})
    await second.getByRole('button', {name: /Chép điều kiện từ Zalo Minh Thư/}).click()
    assert.match(await dialog.locator('.sx-summary').innerText(), /là bạn bè hoặc có tag Zalo Đã mua ở Zalo Minh Thư[\s\S]*hoặc là bạn bè hoặc có tag Zalo Đã mua ở Zalo Shop/)
    assert.equal(await dialog.getByText('hoặc', {exact: true}).count(), 1)
    if (shots) await page.screenshot({path: join(shots, 'group-editor.png')})
    await page.evaluate(() => { window.cardSmoke.delay = 150 })
    await dialog.getByRole('button', {name: 'Lưu và dùng'}).dblclick()
    await dialog.waitFor({state: 'hidden'})
    const saves = await page.evaluate(() => window.cardSmoke.saves)
    assert.equal(saves.length, 1)
    assert.deepEqual(saves[0].blocks.map(b => b.accountId), [100, 101])
    assert.equal(saves[0].blocks[1].rules.find(r => r.fieldId === 2).value[0], '21', 'tag chép theo tên sang Zalo Shop')
    assert.equal((await value())['101'].groupId, 60)
    assert.match(await card.textContent(), /Khớp nhóm điều kiện “Khách đã chăm sóc”[\s\S]*Zalo Shop: là bạn bè hoặc có tag Zalo Đã mua/)
    ok('nhóm điều kiện 2 Zalo: câu tóm tắt, chép điều kiện theo tên tag, lưu một lần')
    if (shots) await page.screenshot({path: join(shots, 'card-filled.png')})

    // Đặt riêng cho từng Zalo gửi.
    await card.getByRole('button', {name: 'Đặt riêng cho từng Zalo gửi của chiến dịch'}).click()
    await card.getByLabel('Zalo gửi').selectOption('101')
    await card.getByRole('button', {name: 'Bỏ loại trừ theo Nhóm data'}).click()
    v = await value()
    assert.deepEqual(v['101'].dataGroupIds, [], 'V666: bỏ chọn ghi mảng rỗng (trigger lưu giữ khoá thiếu của client cũ)')
    assert.deepEqual(v['100'].dataGroupIds, [12])
    ok('đặt riêng: bỏ Nhóm data chỉ ở một Zalo gửi')
    await card.getByRole('button', {name: 'Dùng chung cho mọi Zalo gửi'}).click()
    v = await value()
    assert.deepEqual(v['100'], v['101'])
    ok('quay lại dùng chung: chép lựa chọn của Zalo đang xem cho mọi Zalo')

    // Zalo gửi mới thêm vào chiến dịch nhận cùng lựa chọn.
    await page.evaluate(() => window.cardSmoke.setAccounts([{id: 100, name: 'Zalo Minh Thư'}, {id: 101, name: 'Zalo Shop'}, {id: 102, name: 'Zalo Mới'}]))
    await page.waitForFunction(() => !!window.cardSmoke.value['102'])
    v = await value()
    assert.deepEqual(v['102'], v['100'])
    ok('Zalo gửi mới nhận cùng lựa chọn')

    // V666: Zalo mới thêm vào ĐẦU danh sách (trước: chép lựa chọn rỗng của Zalo đứng đầu sang mọi Zalo).
    const shared = (await value())['100']
    await page.evaluate(() => window.cardSmoke.setAccounts([{id: 103, name: 'Zalo Đầu'}, {id: 100, name: 'Zalo Minh Thư'}, {id: 101, name: 'Zalo Shop'}]))
    await page.waitForFunction(() => !!window.cardSmoke.value['103'])
    v = await value()
    assert.deepEqual(v['103'], shared); assert.deepEqual(v['100'], shared); assert.deepEqual(v['101'], shared)
    // Đổi hẳn sang một Zalo khác (chỉ còn 1 Zalo): lựa chọn đi theo.
    await page.evaluate(() => window.cardSmoke.setAccounts([{id: 104, name: 'Zalo Thay'}]))
    await page.waitForFunction(() => !!window.cardSmoke.value['104'])
    assert.deepEqual((await value())['104'], shared)
    ok('dùng chung: Zalo mới đứng đầu / đổi hẳn Zalo khác vẫn giữ lựa chọn')

    // V666: yêu cầu "chờ chọn danh sách" chỉ gỡ khi chọn danh sách cho đúng Zalo đang chờ.
    await page.evaluate(() => { window.cardSmoke.setAccounts([{id: 100, name: 'Zalo Minh Thư'}, {id: 101, name: 'Zalo Shop'}]); window.cardSmoke.setValue({}) })
    await card.getByRole('button', {name: 'Đặt riêng cho từng Zalo gửi của chiến dịch'}).waitFor()
    await card.getByRole('button', {name: 'Đặt riêng cho từng Zalo gửi của chiến dịch'}).click()
    await page.evaluate(() => window.cardSmoke.setPending(100))
    await card.getByLabel('Zalo gửi').selectOption('101')
    await card.getByRole('button', {name: 'Thêm loại trừ'}).click()
    await page.getByRole('menuitem', {name: /danh sách bạn bè\/Zalo ID/}).click()
    dialog = page.getByRole('dialog')
    await dialog.getByRole('checkbox', {name: /Khách cũ/}).check()
    await dialog.getByRole('button', {name: 'Xong'}).click()
    assert.equal(await page.evaluate(() => window.cardSmoke.resolved), 0, 'chọn danh sách cho Zalo Shop không gỡ yêu cầu của Zalo Minh Thư')
    await card.getByLabel('Zalo gửi').selectOption('100')
    assert.ok(await card.getByRole('button', {name: 'Bỏ yêu cầu loại trừ danh sách'}).isVisible())
    await card.getByRole('button', {name: 'Thêm loại trừ'}).click()
    await page.getByRole('menuitem', {name: /danh sách bạn bè\/Zalo ID/}).click()
    dialog = page.getByRole('dialog')
    await dialog.getByRole('checkbox', {name: /VIP/}).check()
    await dialog.getByRole('button', {name: 'Xong'}).click()
    assert.equal(await page.evaluate(() => window.cardSmoke.resolved), 1)
    await card.getByRole('button', {name: 'Dùng chung cho mọi Zalo gửi'}).click()
    await page.evaluate(() => window.cardSmoke.setPending(101))
    await card.getByRole('button', {name: 'Bỏ yêu cầu loại trừ danh sách'}).waitFor()
    ok('chờ chọn danh sách: chỉ gỡ đúng Zalo; dùng chung thì cảnh báo cả khi Zalo chờ không đứng đầu')

    // V666: lưu nhóm gặp 409: đóng trình sửa, tải lại trang nhóm, báo.
    const pageCalls = await page.evaluate(() => window.cardSmoke.calls.filter(c => c === 'page').length)
    await page.evaluate(() => { window.cardSmoke.conflict = true; window.cardSmoke.delay = 0 })
    await card.getByRole('button', {name: 'Sửa'}).first().waitFor().catch(() => {})
    await card.getByRole('button', {name: 'Thêm loại trừ'}).click()
    await page.getByRole('menuitem', {name: /Khách theo điều kiện ở Zalo/}).click()
    dialog = page.getByRole('dialog')
    const create = dialog.getByRole('button', {name: 'Tạo nhóm mới'})
    if (await create.count()) await create.click()
    dialog = page.getByRole('dialog')
    await dialog.getByLabel('Tên nhóm').fill('Nhóm trùng')
    const block = dialog.getByRole('region', {name: /Điều kiện ở Zalo/}).first()
    await block.getByRole('button', {name: 'Thêm điều kiện'}).click()
    await block.getByRole('menuitem', {name: 'Trạng thái bạn bè'}).click()
    await dialog.getByRole('button', {name: 'Lưu và dùng'}).click()
    await card.getByText('Nhóm có thể đã được tạo ở lần lưu trước nên đã tải lại danh sách nhóm. Hãy kiểm tra trước khi tạo lại.').waitFor()
    assert.equal(await page.getByRole('dialog').count(), 0)
    assert.ok(await page.evaluate(n => window.cardSmoke.calls.filter(c => c === 'page').length > n, pageCalls))
    await page.evaluate(() => { window.cardSmoke.conflict = false })
    // Mở lại một hộp thoại thì câu 409 tắt (trước: câu còn mãi tới khi đóng form).
    await card.getByRole('button', {name: 'Thêm loại trừ'}).click()
    await page.getByRole('menuitem', {name: /Khách theo điều kiện ở Zalo/}).click()
    await page.getByRole('dialog').first().waitFor()
    await card.getByText('Nhóm có thể đã được tạo ở lần lưu trước').waitFor({state: 'detached', timeout: 3000})
    await page.keyboard.press('Escape')
    const closeBtn = page.getByRole('dialog').getByRole('button', {name: /Đóng|Huỷ|Hủy/}).first()
    if (await page.getByRole('dialog').count() && await closeBtn.count()) await closeBtn.click()
    ok('409 khi lưu nhóm: đóng trình sửa, tải lại danh sách nhóm, báo; mở lại hộp thoại thì câu báo tắt')

    // V666: số "đã gửi" chưa đếm kịp / quá 1.000.
    await card.getByRole('button', {name: 'Thêm loại trừ'}).click()
    await page.getByRole('menuitem', {name: /Khách đã được gửi tin ở chiến dịch/}).click()
    dialog = page.getByRole('dialog')
    await dialog.getByText('Tri ân năm cũ').waitFor()
    assert.match(await dialog.textContent(), /Chưa đếm được số khách đã gửi/)
    assert.match(await dialog.textContent(), /Đã gửi 100\.000\+ khách/)
    await dialog.getByRole('button', {name: 'Tạm dừng', exact: true}).click()
    await page.waitForFunction(() => window.cardSmoke.calls.some(c => Array.isArray(c) && c[0] === 'lists' && c[1].status === 'tạm dừng'))
    await dialog.getByRole('button', {name: 'Hủy'}).click()
    ok('chiến dịch đã gửi: số chưa đếm được / 100.000+, lọc trạng thái gửi xuống DB')

    // Hẹp.
    await page.setViewportSize({width: 390, height: 844})
    assert.ok(await card.evaluate(el => el.scrollWidth <= el.clientWidth))
    if (shots) await page.screenshot({path: join(shots, 'card-narrow.png'), fullPage: true})
    ok('màn hẹp không tràn ngang')
    assert.deepEqual(errors, [])
  } finally { await browser.close(); rmSync(dir, {recursive: true, force: true}) }
  console.log(`${passed} nhóm đạt`)
}
main().catch(error => { console.error(error); process.exit(1) })
