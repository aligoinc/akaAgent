const assert = require('node:assert/strict')
const { mkdirSync } = require('node:fs'), { resolve } = require('node:path')
module.exports = async function checkLimitsUi(page) {
  const form = page.locator('.campaign-full-modal')
  const section = page.locator('.stepper-section').filter({ has: page.locator('.stepper-section-title').filter({ hasText: /^Giới hạn hành động$/ }) })
  const trigger = page.getByRole('button', { name: 'Điền giới hạn bằng AI', exact: true })
  const scheduleTrigger = page.getByRole('button', { name: 'Điền lịch bằng AI', exact: true })
  const panel = page.getByRole('dialog', { name: 'Điền giới hạn bằng AI', exact: true })
  const input = panel.getByLabel('Mô tả giới hạn muốn đặt')
  const requests = () => page.evaluate(() => window.scheduleSmoke.state.requests.length)
  const saveCount = () => page.evaluate(() => window.scheduleSmoke.state.calls.filter(call => /^(createCampaign|updateCampaign|saveCampaignDraft)$/.test(call.method)).length)
  const resolveAi = result => page.evaluate(result => window.scheduleSmoke.resolve(result), result)
  const generate = async text => {
    await trigger.click(); await input.fill(text); await input.press('Enter')
    await page.waitForFunction(() => document.querySelector('.stepper-layout')?.inert)
  }
  const expand = async () => {
    await trigger.scrollIntoViewIfNeeded()
    if (!await section.locator('.stepper-section-body').count()) await section.locator('.stepper-section-header').click()
  }
  await expand()
  await scheduleTrigger.hover()
  await page.getByRole('dialog', { name: 'Điền lịch bằng AI', exact: true }).waitFor()
  const before = await requests()
  await trigger.hover(); await panel.waitFor()
  assert.equal(await page.getByRole('dialog', { name: 'Điền lịch bằng AI', exact: true }).count(), 0, 'only one AI popover is open')
  assert.equal(await requests(), before, 'hover does not call AI')
  await input.fill(' '); await input.press('Enter'); assert.equal(await requests(), before)
  await input.fill('Mỗi ngày 20 bài'); await input.press('End'); await input.press('Shift+Enter'); await input.press('x')
  assert.equal(await input.inputValue(), 'Mỗi ngày 20 bài\nx', 'Shift+Enter inserts a newline')
  assert.equal(await requests(), before, 'Shift+Enter must not submit')
  await input.fill('giới hạn ngày 20')
  await input.dispatchEvent('keydown', { key: 'Enter', code: 'Enter', isComposing: true }); assert.equal(await requests(), before)
  const savesBefore = await saveCount()
  await generate('mỗi ngày 20 bài, trong nửa giờ 6 bài')
  assert(await scheduleTrigger.isDisabled()); assert(await input.isDisabled())
  assert(await form.getByRole('button', { name: 'Lưu chiến dịch', exact: true }).isDisabled())
  const request = await page.evaluate(() => window.scheduleSmoke.state.requests.at(-1))
  assert.deepEqual(request.limits.actions.map(item => item.actionCode), ['fb_post_my_profile'])
  await resolveAi({ ok: true, patch: { actions: [{ actionCode: 'fb_post_my_profile', dailyLimit: 20, rateLimitCount: 6, rateLimitMinutes: 30 }] } })
  await panel.waitFor({ state: 'detached' })
  assert.equal(await section.locator('#action-limit-day-fb_post_my_profile').inputValue(), '20')
  assert.equal(await section.locator('#action-limit-hour-fb_post_my_profile').inputValue(), '6')
  assert.equal(await section.locator('#action-limit-minute-fb_post_my_profile').inputValue(), '30')
  assert(await section.locator('#action-limit-minute-fb_post_my_profile').isVisible())
  assert.equal(await saveCount(), savesBefore, 'AI must not save')
  await generate('mỗi ngày 20 bài, trong nửa giờ 6 bài')
  await resolveAi({ ok: true, patch: { actions: [] } })
  await panel.waitFor({ state: 'detached' })
  assert(await form.getByRole('button', { name: 'Lưu chiến dịch', exact: true }).isEnabled())
  assert.equal(await section.locator('#action-limit-day-fb_post_my_profile').inputValue(), '20')
  assert.equal(await section.locator('#action-limit-hour-fb_post_my_profile').inputValue(), '6')
  assert.equal(await section.locator('#action-limit-minute-fb_post_my_profile').inputValue(), '30')
  assert.equal(await saveCount(), savesBefore, 'repeating a satisfied request must not save')
  await generate('giới hạn chưa rõ')
  await resolveAi({ ok: false, code: 'unclear', message: 'Bạn muốn đặt bao nhiêu bài trong ngày?' })
  await panel.getByRole('alert').waitFor(); assert.equal(await input.inputValue(), 'giới hạn chưa rõ')
  assert(await input.isEnabled()); assert(await form.getByRole('button', { name: 'Lưu chiến dịch', exact: true }).isEnabled())
  assert.equal(await section.locator('#action-limit-day-fb_post_my_profile').inputValue(), '20')
  for (const mode of ['cancel', 'timeout', 'error']) {
    await generate(mode)
    if (mode === 'cancel') await panel.getByRole('button', { name: 'Hủy yêu cầu' }).click()
    else if (mode === 'timeout') await page.evaluate(() => window.scheduleSmoke.expire())
    else await page.evaluate(() => window.scheduleSmoke.reject())
    if (mode !== 'error') await resolveAi({ ok: true, patch: { actions: [{ actionCode: 'fb_post_my_profile', dailyLimit: 1 }] } })
    assert(await input.isEnabled()); assert.equal(await section.locator('#action-limit-day-fb_post_my_profile').inputValue(), '20')
  }
  await generate('đóng form khi chờ')
  await form.getByRole('button', { name: 'Đóng', exact: true }).click(); await form.waitFor({ state: 'detached' })
  await resolveAi({ ok: true, patch: { actions: [{ actionCode: 'fb_post_my_profile', dailyLimit: 1 }] } })

  // New form/draft must preserve an explicit AI minute override instead of inheriting account defaults.
  await page.evaluate(() => window.scheduleSmoke.openNew()); await trigger.waitFor(); await expand()
  await generate('đặt giới hạn ngày 20 và 6 bài mỗi 30 phút')
  await resolveAi({ ok: true, patch: { actions: [{ actionCode: 'fb_post_my_profile', dailyLimit: 20, rateLimitCount: 6, rateLimitMinutes: 30 }] } })
  await panel.waitFor({ state: 'detached' })
  await form.getByRole('button', { name: 'Lưu nháp', exact: true }).click(); await form.waitFor({ state: 'detached' })
  const draft = await page.evaluate(() => window.scheduleSmoke.state.lastSavedDraft)
  assert.equal(draft.payload.values.editedRateLimitMinuteActions.fb_post_my_profile, true)
  assert.equal(draft.payload.values.formData.actionLimitsByCode.fb_post_my_profile.rateLimitMinutes, 30)
  await page.evaluate(draft => window.scheduleSmoke.openDraft(draft), draft); await trigger.waitFor(); await expand()
  assert.equal(await section.locator('#action-limit-hour-fb_post_my_profile').inputValue(), '6')
  await form.getByRole('button', { name: 'Tạo chiến dịch', exact: true }).click()
  await form.waitFor({ state: 'detached' })
  const saved = await page.evaluate(() => window.scheduleSmoke.state.calls.filter(call => call.method === 'createCampaign').at(-1).args[0])
  assert.equal(saved.extraSettings.actionLimits.byActionCode.fb_post_my_profile.rateLimitMinutes, 30)
  assert.equal(saved.extraSettings.actionLimits.byActionCode.fb_post_my_profile.rateLimitCount, 6)

  const groupCampaign = { id: 601, actionId: 'facebook_group_post', name: 'Giới hạn kiểm thử', accountId: 11,
    schedule: '2035-01-01T01:00:00Z', scheduleType: 'daily', content: 'Nội dung kiểm thử', status: 'tạm dừng',
    extraSettings: { enableComment: true, commentContent: 'Comment kiểm thử', actionLimits: { sleepBetweenActions: 30,
      byActionCode: { fb_post_group: { dailyLimit: 20, rateLimitCount: 6, rateLimitMinutes: 65 },
        fb_comment: { dailyLimit: 18, rateLimitCount: 4, rateLimitMinutes: 65 } } } } }
  await page.evaluate(value => window.scheduleSmoke.openCampaign(value), groupCampaign); await trigger.waitFor(); await expand()
  await generate('nghỉ 90 giây, tiếp tục khi một hành động hết hạn mức')
  const groupRequest = await page.evaluate(() => window.scheduleSmoke.state.requests.at(-1))
  assert.deepEqual(groupRequest.limits.actions.map(item => item.actionCode), ['fb_post_group'], 'comment limits in another section are excluded')
  await resolveAi({ ok: true, patch: { actions: [], sleepBetweenActions: 90, continueWhenActionLimitReached: true } })
  await panel.waitFor({ state: 'detached' })
  assert.equal(await section.getByText('Thời gian nghỉ giữa 2 lần gửi', { exact: true }).locator('..').locator('input').inputValue(), '90')
  assert(await section.getByRole('checkbox', { name: 'Chiến dịch sẽ tiếp tục chạy khi 1 trong các hành động đạt giới hạn' }).isChecked())
  assert.equal(await page.locator('#action-limit-day-fb_comment').inputValue(), '18')
  const countBeforeAuth = await requests()
  await generate('chờ đổi phiên'); await page.evaluate(() => window.scheduleSmoke.switchUser())
  await resolveAi({ ok: true, patch: { actions: [], sleepBetweenActions: 5 } })
  assert.equal(await requests(), countBeforeAuth + 1)
  assert.equal(await section.getByText('Thời gian nghỉ giữa 2 lần gửi', { exact: true }).locator('..').locator('input').inputValue(), '90')
  await panel.getByRole('button', { name: 'Đóng nhập giới hạn AI' }).click()

  await page.evaluate(value => window.scheduleSmoke.openCampaign(value), { ...groupCampaign, actionId: 'facebook_comment_seeding',
    extraSettings: { postsPerTarget: 3, enablePostLike: false, actionLimits: { sleepBetweenActions: 30,
      byActionCode: { fb_comment: { dailyLimit: 20, rateLimitCount: 6, rateLimitMinutes: 65 } } } } })
  await trigger.waitFor(); await expand(); await generate('mỗi nhóm comment 5 bài')
  await resolveAi({ ok: true, patch: { actions: [], postsPerTarget: 5 } }); await panel.waitFor({ state: 'detached' })
  assert.equal(await section.getByText('Số bài cần comment trên mỗi group/page/profile', { exact: true }).locator('..').locator('input').inputValue(), '5')
  await trigger.click(); await input.fill('Mỗi ngày 50 comment, mỗi nửa giờ 5 comment, nghỉ một phút giữa hai lần.')
  const shots = resolve(__dirname, '../docs/audits/campaign-limits-ai-v402'); mkdirSync(shots, { recursive: true })
  for (const theme of ['dark', 'light']) {
    await page.evaluate(theme => document.body.classList.toggle('theme-light', theme === 'light'), theme)
    await panel.screenshot({ path: resolve(shots, `${theme}.png`) })
  }
  console.log('PASS limits real form: exclusive popover, Enter/IME/hover, full lock/unlock, scoped fields, cancel/error/timeout/close/auth, no autosave, draft→actual Save preserves minute override, group-post exclusions, comment posts-per-target')
}
