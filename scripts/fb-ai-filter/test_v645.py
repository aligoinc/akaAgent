#!/usr/bin/env python3
"""Chạy V644 rồi V645 (trả mã ngoài bộ lọc về như cũ) và bản gỡ V645 trên PostgreSQL cục bộ (bảng tối thiểu theo cấu trúc production 24/11).
Chạy: PGBIN=/usr/lib/postgresql/16/bin python3 scripts/fb-ai-filter/test_v645.py"""
import json, os, shutil, subprocess, tempfile
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
PGBIN = os.environ.get('PGBIN', '/usr/lib/postgresql/16/bin')
MIG = open(os.path.join(ROOT, 'migrations/migration_v644_ai_haiku_luna_switch.sql'), encoding='utf-8').read()
RB = open(os.path.join(ROOT, 'migrations/rollback_v644_ai_haiku_luna_switch.sql'), encoding='utf-8').read()
HAIKU = ['app_ai_generate_campaign_name', 'app_campaign_import_image_to_data', 'campaign_error_screenshot_diagnosis', 'fb_newsfeed_check_comment',
         'fb_newsfeed_check_like', 'fb_prepare_seeding_iterations_ai_filter_v2', 'fb_extract_data_from_group_posts_ai_filter_v2',
         'fb_collect_group_comments_ai_filter_v2', 'fb_extract_data_from_search_posts_ai_filter_v2', 'fb_collect_search_post_comments_ai_filter_v2']
LUNA = ['app_ai_rewrite_content', 'app_ai_write_multi_other_content', 'fb_comment_at_position_rewrite', 'fb_comment_current_post_rewrite',
        'fb_page_post_api_rewrite', 'fb_post_current_identity_ui_rewrite', 'fb_post_reels_rewrite', 'fb_send_message_rewrite',
        'fb_send_page_inbox_message_rewrite', 'fb_share_post_rewrite', 'fb_type_post_content_rewrite', 'fb_rewrite_source_content_ai']
PROMPT = {c: (1 if c in LUNA[:1] + LUNA[2:11] else 2 if c == 'app_ai_write_multi_other_content' else 3 if c in ('fb_newsfeed_check_comment', 'fb_newsfeed_check_like', 'fb_rewrite_source_content_ai') else 6) for c in HAIKU + LUNA}
base = tempfile.mkdtemp(prefix='v644-', dir='/var/tmp'); os.chmod(base, 0o777)
data = os.path.join(base, 'data'); as_pg = ['runuser', '-u', 'postgres', '--'] if os.geteuid() == 0 else []
env = {**os.environ, 'LC_ALL': 'C'}; passed = 0
def run(cmd, **kw): return subprocess.run(as_pg + cmd, env=env, capture_output=True, text=True, **kw)
def psql(sql, ok=True):
    r = run([f'{PGBIN}/psql', '-h', base, '-p', '5644', '-d', 'postgres', '-v', 'ON_ERROR_STOP=1', '-At', '-q'], input=sql)
    if ok and r.returncode: raise SystemExit('psql lỗi: ' + r.stderr[-1500:])
    return r
def check(name, cond):
    global passed
    if not cond: raise SystemExit('FAIL ' + name)
    passed += 1; print('ok -', name)
def snap():
    return psql("""select json_build_object('using', (select json_object_agg(code, json_build_object('m', model_id, 'o', request_options, 'p', prompt_id)) from public.ai_using),
      'p', (select json_object_agg(code, json_build_object('md5', md5(prompt_user), 'active', is_active)) from public.ai_prompt), 'set', (select count(*) from public.auto_system_settings where is_active),
      'models', (select json_agg(json_build_object('code', code, 'model', model, 'ep', endpoint, 'active', is_active, 'key', api_key, 'body', default_body) order by id) from public.ai_model where id > 40))""").stdout.strip()
try:
    assert run([f'{PGBIN}/initdb', '-D', data, '-U', 'postgres', '-A', 'trust']).returncode == 0
    assert run([f'{PGBIN}/pg_ctl', '-D', data, '-l', os.path.join(base, 'pg.log'), '-o', f'-k {base} -p 5644 -c listen_addresses=', '-w', 'start']).returncode == 0
    rows = ',\n'.join(f"('{c}', {2 if c.endswith('_v2') else 1}, {PROMPT[c]}, " + ("'{\"text\":{\"verbosity\":\"low\"},\"reasoning\":{\"effort\":\"minimal\"},\"max_output_tokens\":128}'" if c == 'app_ai_generate_campaign_name' else "'{}'") + ")" for c in HAIKU + LUNA)
    psql(f"""create schema supabase_migrations; create table supabase_migrations.schema_migrations (version text, name text, statements text[]);
create table public.ai_model (id bigint generated by default as identity primary key, code text unique, model text, endpoint text, provider text,
  is_active boolean default true, is_system boolean default false, default_body jsonb, organization_id bigint, api_key text);
insert into public.ai_model (id, code, model, endpoint, provider, api_key) values (1,'nano','gpt-5-nano','https://api.openai.com/v1/responses','openai','k-openai'),
 (2,'deepseek_default','deepseek-flash','https://api.deepseek.com/chat/completions','deepseek','k-ds'),
 (16,'openai_luna','gpt-6-luna','https://api.openai.com/v1/responses','openai','k-openai'),
 (24,'app_campaign_content_haiku_5_5','claude-haiku-5-5','https://api.anthropic.com/v1/messages','claude','k-claude'),
 (40,'fb_ai_content_filter_haiku_5_5','claude-haiku-5-5','https://api.anthropic.com/v1/messages','claude','k-claude');
select setval(pg_get_serial_sequence('public.ai_model','id'), 40);
create table public.ai_prompt (id bigint generated always as identity primary key, code text not null unique, name text not null, prompt_system text,
  prompt_user text not null default '', is_system boolean not null default false, is_active boolean not null default true);
insert into public.ai_prompt (id, code, name, prompt_system, prompt_user, is_system) overriding system value values
 (1, 'akabiz_rewrite_content', 'r', null, E'Viết lại nội dung dưới đây, chỉ trả về kết quả và không giải thích gì thêm:\\r\\n[content]', true),
 (2, 'akabiz_write_multi_other_content', 'm', null, E'Tạo ra [count] phiên bản nội dung khác nhau cho nội dung dưới đây, mỗi nội dung phân tách nhau bởi dấu "|", vui lòng chỉ trả lời và không giải thích gì thêm. Nội dung là:\\r\\n\\r\\n[content]', true),
 (3, 'q', 'q', null, '[question]', true), (6, 'f', 'f', 's', 'u', true);
select setval(pg_get_serial_sequence('public.ai_prompt','id'), 75);
create table public.ai_using (id bigint generated by default as identity primary key, code text, model_id bigint, prompt_id bigint, request_options jsonb);
insert into public.ai_using (code, model_id, prompt_id, request_options) values {rows};
create table public.auto_system_settings (id bigint generated by default as identity primary key, key text unique, value text, description text, is_secret boolean, is_active boolean);""")
    before = json.loads(snap())
    psql(MIG)
    after644 = json.loads(snap())
    V645 = open(os.path.join(ROOT, 'migrations/migration_v645_ai_revert_non_filter_models.sql'), encoding='utf-8').read()
    RB645 = open(os.path.join(ROOT, 'migrations/rollback_v645_ai_revert_non_filter_models.sql'), encoding='utf-8').read()
    psql("update public.ai_using set model_id = 1 where code = 'fb_send_message_rewrite';")
    r = psql(V645, ok=False)
    check('V645: trạng thái khác sau V644 thì dừng, không ghi gì', r.returncode != 0 and 'fb_send_message_rewrite=' in r.stderr
          and psql("select count(*) from public.ai_prompt where code = 'akabiz_rewrite_content_luna'").stdout.strip() == '0')
    psql("update public.ai_using set model_id = (select id from public.ai_model where code = 'openai_luna_chat') where code = 'fb_send_message_rewrite';")
    psql(V645)
    s = json.loads(snap())
    hid = psql("select id from public.ai_model where code = 'anthropic_haiku_5_5_chat_compat'").stdout.strip()
    lid = psql("select id from public.ai_model where code = 'openai_luna_chat'").stdout.strip()
    newp = psql("select id from public.ai_prompt where code = 'akabiz_rewrite_content_luna'").stdout.strip()
    filters = [c for c in HAIKU if c.endswith('_v2')]
    buttons = ['app_ai_rewrite_content', 'app_ai_write_multi_other_content']
    back = [c for c in HAIKU + LUNA if c not in filters + buttons]
    check('V645: 15 mã ngoài bộ lọc về đúng như trước V644 (mô hình, request_options, lời dặn)', len(back) == 15 and all(s['using'][c] == before['using'][c] for c in back))
    check('V645: 5 mã lọc bài / comment vẫn dùng Haiku', len(filters) == 5 and all(str(s['using'][c]['m']) == hid for c in filters))
    check('V645: hai nút trong form giữ gpt-6-luna cổng chat', all(str(s['using'][c]['m']) == lid for c in buttons))
    check('V645: lời dặn 1 về chữ cũ; nút Viết lại dùng lời dặn riêng có câu không markdown; lời dặn 2 giữ bản V644',
          s['p']['akabiz_rewrite_content']['md5'] == '587ca6f3a4e1c94bd9073922bbbac480'
          and s['p']['akabiz_rewrite_content_luna'] == {'md5': 'ef7c3e20fee46ef5f25ef4e51f4cca51', 'active': True}
          and str(s['using']['app_ai_rewrite_content']['p']) == newp and int(newp) > 75
          and s['p']['akabiz_write_multi_other_content']['md5'] == '6933cbed6ece1318859a25227ac6eb95' and s['using']['app_ai_write_multi_other_content']['p'] == 2)
    check('V645: tắt ai.model_fallbacks, hai dòng ai_model vẫn bật', s['set'] == before['set']
          and {m['code']: m['active'] for m in s['models']} == {'anthropic_haiku_5_5_chat_compat': True, 'openai_luna_chat': True})
    psql("insert into supabase_migrations.schema_migrations values ('20261124110000','migration_v645_ai_revert_non_filter_models',null);")
    r = psql(V645, ok=False)
    check('V645: chạy lại bị từ chối', r.returncode != 0 and 'không chạy lại' in r.stderr)
    psql(RB645)
    g = json.loads(snap())
    check('gỡ V645 đưa lại đúng trạng thái sau V644 (lời dặn riêng chỉ tắt, không xoá)', g['using'] == after644['using'] and g['set'] == after644['set']
          and g['models'] == after644['models'] and g['p'].pop('akabiz_rewrite_content_luna') == {'md5': 'ef7c3e20fee46ef5f25ef4e51f4cca51', 'active': False}
          and g['p'] == after644['p'])
    r = psql(RB645, ok=False)
    check('gỡ V645 lần hai dừng', r.returncode != 0 and 'không thấy trạng thái sau V645' in r.stderr)
    print(f'PASS {passed} kiểm')
finally:
    run([f'{PGBIN}/pg_ctl', '-D', data, '-m', 'immediate', 'stop']); shutil.rmtree(base, ignore_errors=True)
