#!/usr/bin/env python3
"""Chạy V643 và bản gỡ trên PostgreSQL cục bộ (bảng tối thiểu, khuôn box 17 đọc production 24/11).
Chạy: PGBIN=/usr/lib/postgresql/16/bin python3 scripts/fb-ai-filter/test_v643.py"""
import json, os, shutil, subprocess, tempfile
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
PGBIN = os.environ.get('PGBIN', '/usr/lib/postgresql/16/bin')
MIG = open(os.path.join(ROOT, 'migrations/migration_v643_aka_settings_sonnet_filter_models.sql'), encoding='utf-8').read()
RB = open(os.path.join(ROOT, 'migrations/rollback_v643_aka_settings_sonnet_filter_models.sql'), encoding='utf-8').read()
SCHEMA = json.dumps(json.load(open(os.path.join(ROOT, 'scripts/fixtures/fb-ai-filter/form-config-17-live-20261124.json'), encoding='utf-8'))['output_schema'])
base = tempfile.mkdtemp(prefix='v643-', dir='/var/tmp'); os.chmod(base, 0o777)
data = os.path.join(base, 'data'); as_pg = ['runuser', '-u', 'postgres', '--'] if os.geteuid() == 0 else []
env = {**os.environ, 'LC_ALL': 'C'}; passed = 0
def run(cmd, **kw): return subprocess.run(as_pg + cmd, env=env, capture_output=True, text=True, **kw)
def psql(sql, ok=True):
    r = run([f'{PGBIN}/psql', '-h', base, '-p', '5643', '-d', 'postgres', '-v', 'ON_ERROR_STOP=1', '-At', '-q'], input=sql)
    if ok and r.returncode: raise SystemExit('psql lỗi: ' + r.stderr[-1500:])
    return r
def check(name, cond):
    global passed
    if not cond: raise SystemExit('FAIL ' + name)
    passed += 1; print('ok -', name)
def state():
    return psql("""select json_build_object('cfg', (select json_build_object('model', m.code, 'req', c.request_options, 'sort', c.output_schema #> '{properties,changes,properties,commentPostSort}')
      from public.ai_form_configs c join public.ai_model m on m.id = c.model_id where c.id = 17),
      'using', (select model_id from public.ai_using where code = 'fb_prepare_seeding_iterations_ai_filter'),
      'models', (select json_agg(json_build_object('code', code, 'model', model, 'active', is_active, 'key', api_key) order by id) from public.ai_model where id > 30));""").stdout.strip()
try:
    r = run([f'{PGBIN}/initdb', '-D', data, '-U', 'postgres', '-A', 'trust']); assert r.returncode == 0, r.stderr
    r = run([f'{PGBIN}/pg_ctl', '-D', data, '-l', os.path.join(base, 'pg.log'), '-o', f'-k {base} -p 5643 -c listen_addresses=', '-w', 'start']); assert r.returncode == 0, r.stderr
    psql(f"""create schema supabase_migrations; create table supabase_migrations.schema_migrations (version text, name text, statements text[]);
create table public.ai_model (id bigint generated by default as identity primary key, code text unique, model text, endpoint text, provider text,
  is_active boolean default true, is_system boolean default false, default_body jsonb, organization_id bigint, api_key text, created_at timestamptz default now(), updated_at timestamptz);
insert into public.ai_model (id, code, model, endpoint, provider, default_body, api_key) values
 (1,'openai_akabiz_write_content','gpt-5-nano','https://api.openai.com/v1/responses','openai','{{}}','k-openai'),
 (16,'openai_luna','gpt-6-luna','https://api.openai.com/v1/responses','openai','{{}}','k-openai'),
 (21,'openai_campaign_diagnostics_sol61','gpt-6.1-sol','https://api.openai.com/v1/responses','openai','{{}}','k-openai'),
 (24,'app_campaign_content_haiku_5_5','claude-haiku-5-5','https://api.anthropic.com/v1/messages','claude','{{"max_tokens":16384}}','k-claude'),
 (27,'anthropic_journey_agent_sonnet_5_5','claude-sonnet-5-5','https://api.anthropic.com/v1/messages','claude','{{"max_tokens":32000}}','k-claude'),
 (30,'anthropic_aka_assistant_sonnet_5_5','claude-sonnet-5-5','https://api.anthropic.com/v1/messages','claude','{{"max_tokens":8000}}','k-claude');
select setval(pg_get_serial_sequence('public.ai_model','id'), 38);
create table public.ai_form_configs (id bigint primary key, desktop_section_id text, model_id bigint references public.ai_model(id), request_options jsonb, output_schema jsonb, updated_at timestamptz);
insert into public.ai_form_configs values (17, 'campaign.facebook.post_search', 21, '{{}}', $s${SCHEMA}$s$, now());
create table public.ai_using (id bigint primary key, code text unique, model_id bigint, prompt_id bigint);
insert into public.ai_using values (21, 'fb_prepare_seeding_iterations_ai_filter', 1, 6);""")
    before = state()
    psql("update public.ai_using set model_id = 2 where id = 21;")
    r = psql(MIG, ok=False)
    check('mã lọc bài cũ không còn dùng ai_model 1 thì dừng, không ghi gì', r.returncode != 0 and 'không còn dùng ai_model 1' in r.stderr and psql("select count(*) from public.ai_model where id > 38").stdout.strip() == '0')
    psql("update public.ai_using set model_id = 1 where id = 21;")
    psql(MIG)
    s = json.loads(state())
    check('box 17 dùng Sonnet 5.5 mới, effort medium, bỏ enum', s['cfg'] == {'model': 'campaign_form_aka_settings_sonnet_5_5', 'req': {'output_config': {'effort': 'medium'}}, 'sort': {'type': ['string', 'null']}})
    check('lọc bài cũ dùng gpt-6-luna', s['using'] == 16)
    check('thêm 2 dòng ai_model Claude, khoá chép từ dòng có sẵn', [(m['code'], m['model'], m['active'], m['key']) for m in s['models']] == [
        ('campaign_form_aka_settings_sonnet_5_5', 'claude-sonnet-5-5', True, 'k-claude'), ('fb_ai_content_filter_haiku_5_5', 'claude-haiku-5-5', True, 'k-claude')])
    psql("insert into supabase_migrations.schema_migrations values ('20261124090000','migration_v643_aka_settings_sonnet_filter_models',null);")
    r = psql(MIG, ok=False)
    check('chạy lại bị từ chối', r.returncode != 0 and 'không chạy lại' in r.stderr)
    psql(RB)
    s2 = json.loads(state()); b = json.loads(before)
    check('gỡ: box 17 và mã lọc bài cũ về như trước', s2['cfg'] == b['cfg'] and s2['using'] == b['using'])
    check('gỡ: khuôn box 17 trùng từng byte bản production', psql("select output_schema = $s$" + SCHEMA + "$s$::jsonb from public.ai_form_configs where id = 17").stdout.strip() == 't')
    check('gỡ: hai dòng ai_model mới bị tắt, không xoá', [m['active'] for m in s2['models']] == [False, False])
    r = psql(RB, ok=False)
    check('gỡ lần hai dừng', r.returncode != 0 and 'không còn dùng dòng Sonnet' in r.stderr)
    print(f'PASS {passed} kiểm')
finally:
    run([f'{PGBIN}/pg_ctl', '-D', data, '-m', 'immediate', 'stop']); shutil.rmtree(base, ignore_errors=True)
