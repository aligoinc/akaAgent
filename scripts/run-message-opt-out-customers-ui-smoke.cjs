const assert = require('node:assert/strict')
const { mkdtempSync, writeFileSync, rmSync } = require('node:fs')
const { join, resolve } = require('node:path')
const { tmpdir } = require('node:os')
const { build } = require('esbuild')
const { _electron } = require('playwright')

async function main() {
  const directory = mkdtempSync(join(tmpdir(), 'akaagent-opt-out-ui-'))
  let app
  try {
    await build({entryPoints:[join(__dirname,'message-opt-out-customers-ui-smoke.tsx')],outdir:directory,bundle:true,
      platform:'browser',format:'iife',jsx:'automatic',target:'chrome120',define:{'process.env.NODE_ENV':'"development"'},logLevel:'warning'})
    writeFileSync(join(directory,'index.html'),'<!doctype html><html lang="vi"><meta charset="utf-8"><link rel="stylesheet" href="message-opt-out-customers-ui-smoke.css"><body><div id="root"></div><script src="message-opt-out-customers-ui-smoke.js"></script></body></html>')
    writeFileSync(join(directory,'main.cjs'),`const {app,BrowserWindow}=require('electron');app.whenReady().then(()=>{
      const win=new BrowserWindow({show:false,width:1550,height:900,webPreferences:{sandbox:true,contextIsolation:true,nodeIntegration:false}});
      win.webContents.session.webRequest.onBeforeRequest((details,cb)=>cb({cancel:/^https?:/.test(details.url)}));
      win.loadFile(${JSON.stringify(join(directory,'index.html'))});});`)
    const env={...process.env};delete env.ELECTRON_RUN_AS_NODE
    app=await _electron.launch({executablePath:require('electron'),args:[join(directory,'main.cjs')],cwd:resolve(__dirname,'..'),env})
    const page=await app.firstWindow();page.setDefaultTimeout(15000)
    const errors=[];page.on('pageerror',error=>errors.push(String(error)))
    await page.getByRole('dialog',{name:'Cài đặt chung'}).waitFor()
    assert.equal(await page.evaluate(()=>window.optOutSmoke.state.calls.length),0,'loads only after menu selection')
    const nav=page.locator('.general-settings-sidebar button')
    const labels=await nav.allTextContents()
    assert.equal(labels.indexOf('Khách hàng từ chối nhận tin'),labels.indexOf('Danh sách không gửi tin')+1)
    await page.getByRole('button',{name:'Khách hàng từ chối nhận tin',exact:true}).click()
    const table=page.getByRole('table',{name:'Khách hàng từ chối nhận tin'})
    await table.getByText('Nguyễn Thị Lan',{exact:true}).waitFor()
    assert.deepEqual(await table.locator('th').allTextContents(),['STT','Ảnh đại diện','Tên Zalo','SĐT','Email','Zalo global ID','Ngày từ chối','Từ chiến dịch','Từ chi tiết chiến dịch'])
    assert.equal(await table.locator('tbody tr').count(),50)
    assert((await table.locator('tbody tr').first().textContent()).includes('20/09/2026 10:30'))
    await table.locator('tbody tr').first().getByLabel('Không có ảnh đại diện').waitFor()
    assert.equal(await table.locator('tbody tr').nth(1).locator('td').last().textContent(),'—')
    await page.screenshot({path:'/tmp/message-opt-out-customers-desktop.png'})
    await page.getByRole('button',{name:'Trang sau',exact:true}).click()
    await table.getByText('Khách hàng 51',{exact:true}).waitFor()
    assert.equal(await table.locator('tbody tr').first().locator('td').first().textContent(),'51')
    const search=page.getByRole('textbox',{name:'Tìm khách hàng từ chối nhận tin'})
    await search.fill('lan@example.com')
    await table.getByText('Nguyễn Thị Lan',{exact:true}).waitFor()
    assert.equal(await table.locator('tbody tr').count(),1)
    assert.equal(await page.evaluate(()=>window.optOutSmoke.state.calls.at(-1).page),1)
    await search.fill('không tồn tại')
    await table.getByText('Không tìm thấy khách hàng phù hợp.').waitFor()
    await page.evaluate(()=>{window.optOutSmoke.state.fail=true})
    await page.getByRole('button',{name:'Tải lại',exact:true}).click()
    await table.getByRole('alert').waitFor()
    await page.evaluate(()=>{window.optOutSmoke.state.fail=false})
    await table.getByRole('button',{name:'Thử lại',exact:true}).click()
    await table.getByText('Không tìm thấy khách hàng phù hợp.').waitFor()
    await page.evaluate(()=>{window.optOutSmoke.state.hold=true})
    await search.fill('Khách hàng 51')
    await page.waitForFunction(()=>window.optOutSmoke.state.pending.length===1)
    await page.evaluate(()=>{window.optOutSmoke.state.hold=false})
    await search.fill('lan@example.com')
    await table.getByText('Nguyễn Thị Lan',{exact:true}).waitFor()
    await page.evaluate(()=>window.optOutSmoke.release())
    assert.equal(await table.getByText('Khách hàng 51',{exact:true}).count(),0,'stale results must not replace newer search')
    await page.setViewportSize({width:1000,height:720})
    assert(await table.evaluate(element=>element.scrollWidth>element.parentElement.clientWidth),'narrow screen scrolls inside the table')
    assert.deepEqual(errors,[])
    console.log('PASS UI: menu, lazy fetch, column order, date, avatar fallback, paging, search, retry, stale response, narrow viewport')
  } finally { await app?.close();rmSync(directory,{recursive:true,force:true}) }
}
main().catch(error=>{console.error(error);process.exitCode=1})
