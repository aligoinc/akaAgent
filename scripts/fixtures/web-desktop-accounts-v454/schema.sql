CREATE FUNCTION private.campaign_log_page(p_campaign_id bigint, p_options jsonb) RETURNS jsonb
LANGUAGE sql STABLE AS $$
  SELECT jsonb_build_object('campaignId', p_campaign_id, 'items',
    coalesce((SELECT jsonb_agg(jsonb_build_object('id', l.id::text, 'log', l.log) ORDER BY l.id DESC)
      FROM public.auto_campaign_logs l WHERE l.campaign_id = p_campaign_id), '[]'::jsonb))
$$;
CREATE FUNCTION public.resolve_organization_zalo_account_capabilities(p_organization_id bigint)
RETURNS TABLE(entitlement_id bigint, qr_enabled boolean, web_enabled boolean, server_enabled boolean,
  max_accounts integer, max_sends_per_day integer, capability_revision text)
LANGUAGE sql STABLE AS $$
  SELECT max(p.id), count(*) > 0, coalesce(bool_or(p.is_zalo_show_web), false), coalesce(bool_or(p.is_zalo_server), false),
    max(p.max_accounts), max(p.max_sends_per_day), 'r1'
  FROM public.org_organization_product p
  WHERE p.organization_id = p_organization_id AND p.is_deleted IS FALSE AND p.product_id IN (16, 18)
    AND p.expiration_date >= now()
$$;
