-- Cùng hành vi trigger production: đổi trạng thái chiến dịch xóa claim (không xóa unit lease).
CREATE FUNCTION public.aka_agent_clear_campaign_runtime_claim_metadata() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.status IS DISTINCT FROM OLD.status THEN
    NEW.runtime_claim_token := NULL; NEW.runtime_claim_target := NULL;
    NEW.runtime_claim_vietnam_date := NULL; NEW.runtime_claimed_at := NULL;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_clear_claim BEFORE UPDATE OF status ON public.auto_campaigns
  FOR EACH ROW EXECUTE FUNCTION public.aka_agent_clear_campaign_runtime_claim_metadata();

