const ROOT = path.resolve(__dirname, '../../..')
function requireFrom(name) {
  const dirs = [process.env.CHAT_REPO, path.resolve(ROOT, '../akaAgentChatApi'), path.resolve(ROOT, '../../../../akaAgentChatApi'), ROOT].filter(Boolean)
  for (const dir of dirs) { try { return require(require.resolve(name, { paths: [dir] })) } catch { /* thử thư mục kế */ } }
  throw new Error(`Không tìm thấy module ${name}; đặt CHAT_REPO trỏ tới akaAgentChatApi`)
}
