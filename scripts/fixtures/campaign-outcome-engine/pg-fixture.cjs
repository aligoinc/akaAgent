const ident = s => '"' + String(s).replaceAll('"', '""') + '"'
const assert = require('node:assert/strict')

async function buildFixture(db, skipped) {
  await db.query(`CREATE ROLE anon NOLOGIN; CREATE ROLE authenticated NOLOGIN; CREATE ROLE service_role NOLOGIN BYPASSRLS;
    CREATE ROLE aka_agent_chat_api NOLOGIN BYPASSRLS; CREATE ROLE aka_agent_desktop NOLOGIN; CREATE SCHEMA private;`)
  // Như Supabase: đối tượng mới trong public mặc định được cấp cho anon/authenticated/service_role,
  // nên phép kiểm quyền sau migration chỉ đạt khi migration thật sự thu hồi.
  await db.query(`ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO anon, authenticated, service_role;
    ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO anon, authenticated, service_role;
    ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON FUNCTIONS TO anon, authenticated, service_role;`)
  const sequences = new Set()
  for (const c of SNAP.columns) { const m = /nextval\('([^']+)'::regclass\)/.exec(c.default || ''); if (m) sequences.add(m[1]) }
  for (const s of sequences) await db.query(`CREATE SEQUENCE ${s}`)
  for (const t of TABLES) {
    const cols = SNAP.columns.filter(c => c.table === t)
    assert.ok(cols.length > 0, `snapshot thiếu bảng ${t}`)
    const defs = cols.map(c => `${ident(c.name)} ${c.type}` + (c.identity === 'a' ? ' GENERATED ALWAYS AS IDENTITY'
      : c.identity === 'd' ? ' GENERATED BY DEFAULT AS IDENTITY' : '') + (c.not_null && !c.identity ? ' NOT NULL' : ''))
    await db.query(`CREATE TABLE public.${ident(t)} (${defs.join(', ')})`)
    for (const c of cols.filter(c => c.default && !c.identity)) {
      try { await db.query(`ALTER TABLE public.${ident(t)} ALTER COLUMN ${ident(c.name)} SET DEFAULT ${c.default}`) }
      catch (e) { skipped.push(`default ${t}.${c.name}: ${e.message}`) }
    }
  }
  // org_organization không nằm trong ảnh chụp 12 bảng: bảng tối thiểu với cột cờ V371 mà engine đọc để chọn
  // tổ chức (production có đủ cột và trigger, đã đọc chỉ đọc 06/11).
  await db.query(`CREATE TABLE public.org_organization (id bigint PRIMARY KEY, name text, use_new_zalo_runtime boolean NOT NULL DEFAULT false)`)
  // Hạn mức (aka_agent_engine_action_limit) đọc nhóm tài khoản và gói của tổ chức: bảng tối thiểu, kiểu cột như production.
  await db.query(`CREATE TABLE public.auto_account_groups (id bigint PRIMARY KEY, settings jsonb NOT NULL DEFAULT '{}'::jsonb,
    staff_id bigint NOT NULL DEFAULT 0, organization_id bigint, is_delete boolean NOT NULL DEFAULT false)`)
  await db.query(`CREATE TABLE public.org_organization_product (id bigserial PRIMARY KEY, organization_id bigint NOT NULL, product_id bigint,
    package_type text, expiration_date timestamptz, is_deleted boolean NOT NULL DEFAULT false, max_sends_per_day integer)`)
  const own = new Set(TABLES)
  for (const kind of ['p', 'u', 'c', 'f']) {
    for (const c of SNAP.constraints.filter(c => c.type === kind && own.has(c.table))) {
      if (kind === 'f') {
        const ref = /REFERENCES (?:public\.)?([a-z_]+)\(/.exec(c.def)
        if (!ref || !own.has(ref[1])) continue
      }
      await db.query(`ALTER TABLE public.${ident(c.table)} ADD CONSTRAINT ${ident(c.name)} ${c.def}`)
    }
  }
  const constraintNames = new Set(SNAP.constraints.map(c => c.name))
  for (const i of SNAP.indexes.filter(i => own.has(i.table) && !constraintNames.has(i.name))) {
    try { await db.query(i.def) } catch (e) { skipped.push(`index ${i.name}: ${e.message}`) }
  }
  // Guard thật của lịch sử (v361) để lệnh ghi của engine phải qua đúng kiểm tra như production.
  await db.query(`CREATE FUNCTION public.aka_agent_guard_detail_result_v361() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $function$
DECLARE p public.auto_account_action_status_policies%ROWTYPE;
BEGIN
 IF NEW.status_id IS NULL AND NEW.sub_status_id IS NULL AND NEW.action_status_policy_id IS NULL AND NEW.policy_snapshot IS NULL AND NEW.result_key IS NULL AND NEW.report_group IS NULL THEN RETURN NEW; END IF;
 IF EXISTS (SELECT 1 FROM unnest(ARRAY[NEW.status_id,NEW.sub_status_id]) i LEFT JOIN public.auto_status s ON s.id=i WHERE i IS NOT NULL AND (s.id IS NULL OR s.component_type<>'campaign_detail')) THEN
   RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='result_status_component_invalid';
 END IF;
 IF NEW.action_status_policy_id IS NOT NULL THEN
   SELECT * INTO p FROM public.auto_account_action_status_policies WHERE id=NEW.action_status_policy_id;
   IF NOT FOUND OR p.status_id IS DISTINCT FROM NEW.status_id OR (p.action_code IS NOT NULL AND p.action_code IS DISTINCT FROM NEW.action_code) THEN
     RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='result_policy_identity_mismatch';
   END IF;
 END IF;
 RETURN NEW;
END $function$;
CREATE TRIGGER auto_detail_result_guard BEFORE INSERT OR UPDATE OF status_id, sub_status_id, action_status_policy_id ON public.auto_campaign_details
FOR EACH ROW EXECUTE FUNCTION public.aka_agent_guard_detail_result_v361();`)
  for (const t of ['auto_status', 'auto_account_actions', 'auto_error', 'auto_account_action_status_policies', 'auto_campaign_actions']) {
    const cols = [...new Set(SNAP.rows[t].flatMap(r => Object.keys(r)))].map(ident).join(', ') // cột không có trong ảnh chụp dùng default
    await db.query(`INSERT INTO public.${ident(t)} (${cols}) SELECT ${cols} FROM jsonb_populate_recordset(NULL::public.${ident(t)}, $1::jsonb)`, [JSON.stringify(SNAP.rows[t])])
  }
  for (const t of TABLES) {
    const idDefault = SNAP.columns.find(c => c.table === t && c.name === 'id' && /nextval/.test(c.default || ''))
    if (!idDefault) continue
    const seq = /nextval\('([^']+)'/.exec(idDefault.default)[1]
    await db.query(`SELECT setval('${seq}', greatest(coalesce((SELECT max(id) FROM public.${ident(t)}), 0), 1))`)
  }
  await db.query(`INSERT INTO public.auto_system_settings(key, value, description) VALUES ('notifications.dispatch_mode', 'pg_net', 'fixture')`)
}

/**
 * Khởi động cụm PG17 trong thư mục tạm. Treo quá timeoutMs thì tự dừng cụm và thoát tiến trình (không để tiến trình mồ côi).
 * LC_ALL cố định: trên macOS thiếu locale hợp lệ thì postmaster dừng với "became multithreaded during startup".
 */
function startCluster({ port, label = 'aka-v495-', timeoutMs = 240000 }) {
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), label))
  const env = { ...process.env, LC_ALL: 'C', LANG: 'C' }
  const run = (cmd, args) => { const r = spawnSync(path.join(BIN, cmd), args, { encoding: 'utf8', env }); if (r.status !== 0) throw new Error(r.stderr || r.stdout); return r.stdout }
  run('initdb', ['-D', path.join(temp, 'db'), '-A', 'trust', '-U', 'postgres', '--encoding=UTF8', '--locale=C'])
  run('pg_ctl', ['-D', path.join(temp, 'db'), '-l', path.join(temp, 'pg.log'), '-o', `-h '' -k ${temp} -p ${port} -c max_connections=30 -c timezone=UTC`, '-w', 'start'])
  let stopped = false
  const stop = () => {
    if (stopped) return
    stopped = true
    try { run('pg_ctl', ['-D', path.join(temp, 'db'), '-m', 'immediate', '-w', 'stop']) } catch { /* đã dừng */ }
    fs.rmSync(temp, { recursive: true, force: true })
  }
  const watchdog = setTimeout(() => { console.error(`TIMEOUT: smoke treo quá ${timeoutMs / 1000} giây`); stop(); process.exit(2) }, timeoutMs)
  watchdog.unref()
  const connect = async () => { const c = new Client({ host: temp, port, user: 'postgres', database: 'postgres' }); await c.connect(); return c }
  return { temp, connect, stop }
}

