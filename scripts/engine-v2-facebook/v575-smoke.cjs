async function classifyGrid(db) {
  const combos = SIGNALS.flatMap(([platform, action, signal]) => PHASES.map(phase => ({ platform, action, phase, signal })))
  const { rows } = await db.query(`SELECT c->>'platform' AS platform, c->>'action' AS action, c->>'phase' AS phase, c->'signal'->>'message' AS message,
      (SELECT s.error_code FROM public.aka_agent_engine_classify_signal(c->>'platform', c->>'action', c->>'phase', c->'signal') s) AS code
    FROM jsonb_array_elements($1::jsonb) c`, [JSON.stringify(combos)])
  return new Map(rows.map(r => [`${r.platform}|${r.action}|${r.phase}|${r.message}`, r.code]))
}

/** Câu chờ của mọi mã, chờ tới 00:00 và tới giữa ngày. */
async function waitNotes(db) {
  const { rows } = await db.query(`SELECT e.error_code, public.aka_agent_engine_wait_note(e.error_code, timestamptz '2026-11-19 00:00:00+07') AS midnight,
      public.aka_agent_engine_wait_note(e.error_code, timestamptz '2026-11-18 15:34:00+07') AS noon,
      public.aka_agent_engine_wait_note(e.error_code, NULL) AS none
    FROM public.auto_error e ORDER BY e.error_code`)
  return new Map(rows.map(r => [r.error_code, r]))
}

/** Dòng của 5 bảng, bỏ trường tự đổi khi ghi (thời điểm, người ghi, số bản). */
async function tableDump(db) {
  const dump = {}
  for (const table of ['auto_error', 'auto_outcome_policies', 'auto_outcome_signal_rules', 'auto_status', 'auto_system_settings']) {
    const { rows } = await db.query(`SELECT to_jsonb(t) - 'updated_at' - 'updated_by' - 'revision' AS row FROM public.${table} t ORDER BY id`)
    dump[table] = rows.map(r => r.row)
  }
  return dump
}

const strip = (p, keys) => { const o = { ...p }; for (const k of keys) delete o[k]; return o }

async function main() {
  const cluster = startCluster({ port: PORT, label: 'aka-fb-v575-', timeoutMs: 600_000 })
  const db = await cluster.connect()
  try {
    await buildReplica(db)
    const migrationMd5 = md5(MIGRATION)

    await check('bản sinh trùng file migration / bản gỡ (không sửa tay)', async () => {
      assert.equal(V575.migration, MIGRATION)
      assert.equal(V575.rollback, ROLLBACK)
    })
    await check('bản sao giống production ở các điểm kiểm trước (dấu hiệu, thân câu chờ, CFG01)', async () => {
      const { rows } = await db.query(`SELECT (SELECT md5(value) FROM public.auto_system_settings WHERE key = 'facebook.error_signs') AS signs,
        md5(pg_get_functiondef('public.aka_agent_engine_wait_note(text, timestamp with time zone)'::regprocedure)) AS wait`)
      assert.equal(rows[0].signs, V575.SIGNS_BEFORE_MD5)
      assert.equal(rows[0].wait, V575.WAIT_NOTE_BEFORE_MD5)
    })

    const policiesBefore = await policyGrid(db)
    const classifyBefore = await classifyGrid(db)
    const notesBefore = await waitNotes(db)
    const tablesBefore = await tableDump(db)

    await check('sổ migration đã có V575 thì từ chối', async () => {
      await db.query(`INSERT INTO supabase_migrations.schema_migrations (version, name) VALUES ('1', '${V575.NAME}')`)
      await assert.rejects(db.query(MIGRATION), /sổ migration đã có migration_v575_/)
      await db.query('ROLLBACK')
      await db.query(`DELETE FROM supabase_migrations.schema_migrations WHERE version = '1'`)
    })

    let applied = false
    await check(`apply V575 (md5 ${migrationMd5.slice(0, 8)}…): kiểm trước / sau trong file đạt`, async () => {
      try { await db.query(MIGRATION); applied = true } catch (error) { await db.query('ROLLBACK').catch(() => {}); throw error }
    })
    if (!applied) throw new Error('V575 không apply được trên bản sao, dừng')

    await check('chính sách gộp: chỉ đổi đúng chỗ anh chốt', async () => {
      const after = await policyGrid(db)
      const changed = []
      for (const [key, before] of policiesBefore) {
        const now = after.get(key)
        const [code, action, campaignAction] = key.split('|')
        if (JSON.stringify(strip(before, ['policy_ids', 'revisions'])) === JSON.stringify(strip(now, ['policy_ids', 'revisions']))) continue
        if (code === V575.CFG01.code) {
          assert.deepEqual(strip(now, ['policy_ids', 'revisions', 'log_template', 'campaign_note_template']),
            strip(before, ['policy_ids', 'revisions', 'log_template', 'campaign_note_template']), key)
          assert.equal(now.log_template, V575.CFG01.title, key)
          continue
        }
        if (code === V575.FB41.code && action === 'fb_comment' && V575.FB41_SIGN_CAMPAIGN_ACTIONS.includes(campaignAction)) {
          assert.deepEqual(strip(now, ['policy_ids', 'revisions', 'quota_effect', 'log_template']),
            strip(before, ['policy_ids', 'revisions', 'quota_effect', 'log_template']), key)
          assert.equal(now.quota_effect, 'count', key)
          assert.equal(now.log_template, '{message}', key)
          continue
        }
        changed.push(key)
      }
      assert.deepEqual(changed, [])
    })

    await check('mã mới: FB46 như SYS99 ở hộp thư Page, CFG20 như CFG01 (dừng ngay, data về hàng đợi) ở Zalo lẫn Facebook', async () => {
      const after = await policyGrid(db)
      const drop = ['policy_ids', 'revisions', 'error_class', 'log_template', 'campaign_note_template', 'requeue_after_minutes']
      for (const phase of PHASES) {
        const fb46 = (await db.query(`SELECT public.aka_agent_engine_resolve_policy($1, NULL, 'fb_message_page_inbox_customer', 'facebook_page_to_message', 'desktop', $2) AS p`,
          [V575.FB46.code, phase])).rows[0].p
        assert.deepEqual(strip(fb46, drop), strip(after.get(`err_undefined|fb_message_page_inbox_customer|facebook_page_to_message|desktop|${phase}`), drop), phase)
        assert.equal(fb46.streak_threshold, 8)
      }
      for (const [action, ca] of [...FB_ACTIONS.map(a => [...a, 'desktop']), ...ZALO_ACTIONS.flatMap(a => [[...a, 'desktop'], [...a, 'fly']])]) {
        const [a, c, rt] = action.length === 3 ? action : [action, ca, 'desktop']
        const cfg20 = (await db.query(`SELECT public.aka_agent_engine_resolve_policy($1, NULL, $2, $3, $4, 'before_send') AS p`, [V575.CFG20.code, a, c, rt])).rows[0].p
        assert.deepEqual(strip(cfg20, drop), strip(after.get(`${V575.CFG01.code}|${a}|${c}|${rt}|before_send`), drop), `${a} ${rt}`)
        assert.equal(cfg20.target_effect, 'requeue')
        assert.equal(cfg20.campaign_effect, 'pause')
        assert.equal(cfg20.campaign_note_template, `${V575.CFG20.title} (CFG20). ${V575.CFG20.help}`)
      }
    })

    await check('phân loại tín hiệu: chỉ lỗi mạng lúc mở trang Facebook và lỗi tệp trong block đổi mã', async () => {
      const after = await classifyGrid(db)
      const changes = []
      for (const [key, before] of classifyBefore) if (after.get(key) !== before) changes.push(`${key} : ${before} → ${after.get(key)}`)
      assert.deepEqual(changes.sort(), [
        'facebook|fb_comment|before_send|net::ERR_INTERNET_DISCONNECTED : err_undefined → err_network_offline',
        'facebook|fb_message_page_inbox_customer|after_send|Không dùng được media "a.jpg": không có local path hoặc cloud URL hợp lệ : err_undefined → err_media_file_missing',
        'facebook|fb_message_page_inbox_customer|before_send|Không dùng được media "a.jpg": không có local path hoặc cloud URL hợp lệ : err_undefined → err_media_file_missing',
        'facebook|fb_message_page_inbox_customer|in_flight|Không dùng được media "a.jpg": không có local path hoặc cloud URL hợp lệ : err_undefined → err_media_file_missing',
        "facebook|fb_post_group|after_send|Không dùng được media \"a.jpg\": local path không tồn tại và cloud URL không tải được (HTTP 404) : err_undefined → err_media_file_missing",
        "facebook|fb_post_group|after_send|Không dùng được media \"a.jpg\": local path không tồn tại và không có cloud URL fallback : err_undefined → err_media_local_file_missing",
        "facebook|fb_post_group|before_send|ERR_NETWORK_IO_SUSPENDED (-331) loading 'https://www.facebook.com/groups/1' : err_engine_fb_ui_not_ready → err_network_offline",
        "facebook|fb_post_group|before_send|Không dùng được media \"a.jpg\": local path không tồn tại và cloud URL không tải được (HTTP 404) : err_undefined → err_media_file_missing",
        "facebook|fb_post_group|before_send|Không dùng được media \"a.jpg\": local path không tồn tại và không có cloud URL fallback : err_undefined → err_media_local_file_missing",
        "facebook|fb_post_group|in_flight|Không dùng được media \"a.jpg\": local path không tồn tại và cloud URL không tải được (HTTP 404) : err_undefined → err_media_file_missing",
        "facebook|fb_post_group|in_flight|Không dùng được media \"a.jpg\": local path không tồn tại và không có cloud URL fallback : err_undefined → err_media_local_file_missing"
      ].sort())
    })

    await check('câu chờ: chỉ mốc 00:00 đổi sang "chạy tiếp vào ngày", CFG01 đổi câu', async () => {
      const after = await waitNotes(db)
      for (const [code, before] of notesBefore) {
        const now = after.get(code)
        if (code === V575.CFG01.code) {
          assert.equal(now.noon, `⏳ ${V575.CFG01.title}, chạy tiếp lúc 15:34 18/11 (CFG01)`)
          assert.equal(now.midnight, `⏳ ${V575.CFG01.title}, chạy tiếp vào ngày 19/11 (CFG01)`)
          continue
        }
        assert.equal(now.noon, before.noon, code)
        assert.equal(now.none, before.none, code)
        assert.equal(now.midnight, before.midnight.replace(', chạy tiếp lúc 00:00 19/11', ', chạy tiếp vào ngày 19/11'), code)
        assert.notEqual(now.midnight, before.midnight, code)
      }
      assert.equal(after.get('error_limit_in_day').midnight, '⏳ Đạt giới hạn trong ngày, chạy tiếp vào ngày 19/11 (LIM01)')
    })

    await check('không apply lại được', async () => {
      await assert.rejects(db.query(MIGRATION), /đã có mã FB46 \/ CFG20/)
      await db.query('ROLLBACK')
    })

    await check('bản gỡ trả danh mục, câu chờ, dấu hiệu về như cũ (dòng mới chỉ tắt)', async () => {
      await db.query(ROLLBACK)
      assert.equal(md5((await db.query(`SELECT pg_get_functiondef('public.aka_agent_engine_wait_note(text, timestamp with time zone)'::regprocedure) AS d`)).rows[0].d),
        V575.WAIT_NOTE_BEFORE_MD5)
      const after = await tableDump(db)
      for (const table of Object.keys(tablesBefore)) {
        const ids = new Set(tablesBefore[table].map(r => r.id))
        const kept = after[table].filter(r => ids.has(r.id))
        assert.deepEqual(kept, tablesBefore[table], table)
        for (const extra of after[table].filter(r => !ids.has(r.id))) assert.equal(extra.is_active, false, `${table} ${extra.id}`)
      }
      const policies = await policyGrid(db)
      for (const [key, before] of policiesBefore) assert.deepEqual(strip(policies.get(key), ['revisions']), strip(before, ['revisions']), key)
      const classify = await classifyGrid(db)
      for (const [key, before] of classifyBefore) assert.equal(classify.get(key), before, key)
      const notes = await waitNotes(db)
      for (const [code, before] of notesBefore) assert.deepEqual(notes.get(code), before, code)
    })
  } finally {
    await db.end().catch(() => {})
    cluster.stop()
  }
  console.log(`\n${passed} PASS, ${failed} FAIL`)
  process.exit(failed ? 1 : 0)
}

main().catch(error => { console.error(error); process.exit(1) })
