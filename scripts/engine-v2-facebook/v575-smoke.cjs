const path = require('node:path')
const { ROOT, startCluster } = require('../fixtures/campaign-outcome-engine/pg-fixture.cjs')
const V575 = require('../build-v575-sql.cjs')

const PORT = Number(process.env.ENGINE_FB_V575_PORT || 55575)
const CATALOG = JSON.parse(fs.readFileSync(path.join(ROOT, 'scripts/fixtures/engine-v2-facebook/v575-catalog-20261118.json'), 'utf8'))
const MIGRATION = fs.readFileSync(path.join(ROOT, 'migrations', `${V575.NAME}.sql`), 'utf8')
const ROLLBACK = fs.readFileSync(path.join(ROOT, 'migrations', `${V575.ROLLBACK_NAME}.sql`), 'utf8')
const md5 = text => crypto.createHash('md5').update(text, 'utf8').digest('hex')
let passed = 0
let failed = 0
async function check(name, fn) {
  try { await fn(); passed++; console.log(`PASS ${name}`) } catch (error) { failed++; console.log(`FAIL ${name}: ${error.stack || error.message}`) }
}

const TABLE_ORDER = ['auto_status', 'auto_error', 'auto_outcome_policies', 'auto_outcome_signal_rules', 'auto_system_settings', 'auto_outcome_policy_history']
const q = name => `"${name.replace(/"/g, '""')}"`

/** Bản sao danh mục production: bảng (đủ cột), ràng buộc, chỉ mục, hàm, trigger, dòng. */
async function buildReplica(db) {
  await db.query(`CREATE SCHEMA IF NOT EXISTS private; CREATE SCHEMA IF NOT EXISTS supabase_migrations;
    CREATE TABLE supabase_migrations.schema_migrations (version text PRIMARY KEY, statements text[], name text, created_by text);
    -- trg_auto_table_log ghi nhật ký thay đổi ở production; bản sao không cần.
    CREATE FUNCTION private.aka_agent_capture_table_change() RETURNS trigger LANGUAGE plpgsql AS $f$ BEGIN RETURN NULL; END $f$;`)
  for (const table of TABLE_ORDER) {
    const cols = CATALOG.columns[table]
    for (const c of cols) {
      const seq = /^nextval\('([a-z0-9_]+)'::regclass\)$/.exec(c.default || '')
      if (seq) await db.query(`CREATE SEQUENCE IF NOT EXISTS public.${seq[1]}`)
    }
    const defs = cols.map(c => {
      const identity = c.identity === 'a' ? ' GENERATED ALWAYS AS IDENTITY' : c.identity === 'd' ? ' GENERATED BY DEFAULT AS IDENTITY' : ''
      const dflt = !identity && c.default ? ` DEFAULT ${c.default}` : ''
      return `${q(c.name)} ${c.type}${identity}${dflt}${c.notnull ? ' NOT NULL' : ''}`
    })
    await db.query(`CREATE TABLE public.${table} (${defs.join(', ')})`)
  }
  for (const c of CATALOG.checks) await db.query(`ALTER TABLE ${c.table} ADD CONSTRAINT ${q(c.name)} ${c.def}`)
  for (const def of CATALOG.indexes) await db.query(def)
  await db.query('SET check_function_bodies = off')
  for (const f of CATALOG.functions) await db.query(f.def)
  await db.query('RESET check_function_bodies')
  for (const t of CATALOG.triggers) await db.query(t.def)
  for (const table of TABLE_ORDER) {
    const data = CATALOG.tables[table]
    if (!data || !data.rows.length) continue
    const objects = data.rows.map(row => Object.fromEntries(data.columns.map((c, i) => [c, row[i]])))
    const list = data.columns.map(q).join(', ')
    const overriding = CATALOG.columns[table].some(c => c.identity === 'a') ? 'OVERRIDING SYSTEM VALUE' : ''
    await db.query(`INSERT INTO public.${table} (${list}) ${overriding} SELECT ${list} FROM jsonb_populate_recordset(NULL::public.${table}, $1::jsonb)`,
      [JSON.stringify(objects)])
    const seq = CATALOG.columns[table].map(c => /^nextval\('([a-z0-9_]+)'::regclass\)$/.exec(c.default || '')).find(Boolean)
    if (seq) await db.query(`SELECT setval('public.${seq[1]}', (SELECT max(id) FROM public.${table}))`)
  }
}

const FB_ACTIONS = [['fb_post_group', 'facebook_group_post'], ['fb_comment', 'facebook_group_post'], ['fb_comment', 'facebook_comment_seeding'],
  ['fb_comment', 'facebook_comment_seeding_post'], ['fb_comment', 'facebook_timeline_post'], ['fb_comment', 'facebook_newsfeed_interaction'],
  ['fb_post_timeline', 'facebook_timeline_post'], ['fb_message_page_inbox_customer', 'facebook_page_to_message'], ['fb_message', 'facebook_message_uid'],
  ['fb_add_friend', 'facebook_add_friend'], ['fb_join_group', 'facebook_join_group'], ['fb_like_post', 'facebook_comment_seeding']]
const ZALO_ACTIONS = [['zalo_find_phone_user', 'zalo_message_phone'], ['zalo_message_stranger', 'zalo_message_phone'], ['zalo_message_group', 'zalo_message_group'],
  ['zalo_message_friend', 'zalo_message_friend'], ['zalo_add_friend', 'zalo_message_phone']]
const PHASES = ['before_send', 'in_flight', 'after_send']

/** Mọi quyết định chính sách: mã đang bật × thao tác × nơi chạy × pha (một lần gọi SQL). */
async function policyGrid(db) {
  const combos = []
  const codes = (await db.query(`SELECT error_code FROM public.auto_error WHERE is_active AND NOT is_delete ORDER BY error_code`)).rows.map(r => r.error_code)
  for (const code of codes) {
    for (const [action, ca] of FB_ACTIONS) for (const phase of PHASES) combos.push([code, action, ca, 'desktop', phase])
    for (const [action, ca] of ZALO_ACTIONS) for (const rt of ['desktop', 'fly']) for (const phase of PHASES) combos.push([code, action, ca, rt, phase])
  }
  const { rows } = await db.query(`SELECT c->>0 AS code, c->>1 AS action, c->>2 AS ca, c->>3 AS rt, c->>4 AS phase,
      public.aka_agent_engine_resolve_policy(c->>0, NULL, c->>1, c->>2, c->>3, c->>4) AS p
    FROM jsonb_array_elements($1::jsonb) c`, [JSON.stringify(combos)])
  return new Map(rows.map(r => [`${r.code}|${r.action}|${r.ca}|${r.rt}|${r.phase}`, r.p]))
}

