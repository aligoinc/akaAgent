const assert = require('node:assert/strict')
const { mkdtempSync } = require('node:fs'), { join } = require('node:path'), { tmpdir } = require('node:os')
module.exports = async page => {
  await page.waitForFunction(() => !!window.scheduleSmoke)
  const trigger = page.getByRole('button', { name: 'Tạo nhóm loại trừ bằng AI', exact: true })
  const panel = page.getByRole('dialog', { name: 'Tạo nhóm loại trừ bằng AI', exact: true })
  const editor = page.getByRole('dialog', { name: 'Thêm nhóm loại trừ', exact: true })
  const card = page.getByRole('region', { name: 'Loại trừ gửi cho khách hàng', exact: true })
  const patch = { name: 'VIP hoặc đã gửi 7 ngày', matchMode: 'or',
    rules: [{ fieldId: 2, operatorId: 3, value: ['7'], isEnabled: true, sortOrder: 20 },
      { fieldId: 4, operatorId: 5, value: 7, isEnabled: true, sortOrder: 40 }] }
  const open = async () => {
    await page.evaluate(() => window.scheduleSmoke.openExclusions())
    await trigger.waitFor()
    await page.waitForFunction(() => !document.querySelector('[aria-label="Tạo nhóm loại trừ bằng AI"]').disabled)
  }
  const send = async () => {
    await trigger.click()
    await panel.getByLabel('Mô tả khách hàng muốn loại trừ').fill('Loại trừ tag VIP hoặc đã gửi trong 7 ngày')
    await panel.getByLabel('Mô tả khách hàng muốn loại trừ').press('Enter')
    await page.waitForFunction(() => window.scheduleSmoke.state.pending.length > 0)
  }
  const resolve = value => page.evaluate(patch => window.scheduleSmoke.resolve({ ok: true, patch }), value)
  const saves = () => page.evaluate(() => window.scheduleSmoke.state.calls.filter(call =>
    ['saveSendExclusionGroup', 'createCampaign', 'updateCampaign'].includes(call.method)))
  await open(); await send()
  const request = await page.evaluate(() => window.scheduleSmoke.state.requests.at(-1))
  assert.equal(request.context.accountId, 11); assert.equal(request.context.actionId, 'zalo_message_friend')
  assert.deepEqual(Object.keys(request).sort(), ['context','description','requestId'])
  assert(await page.getByRole('button', { name: 'Lưu chiến dịch', exact: true }).isDisabled())
  assert(await page.getByRole('button', { name: 'Điền lịch bằng AI', exact: true }).isDisabled())
  await resolve(patch); await editor.waitFor(); await panel.waitFor({ state: 'detached' })
  assert.equal(await editor.getByLabel('Tên nhóm', { exact: true }).inputValue(), patch.name)
  assert(await editor.getByLabel('Tag Zalo', { exact: true }).isChecked())
  assert(await editor.getByLabel('Đã gửi tin trong', { exact: true }).isChecked())
  assert.equal(await editor.getByLabel('Trạng thái bạn bè', { exact: true }).isChecked(), false)
  assert.equal(await editor.getByRole('button', { name: 'VIP', exact: true }).getAttribute('aria-pressed'), 'true')
  assert.equal(await editor.getByRole('button', { name: 'HOẶC — Một điều kiện', exact: true }).getAttribute('aria-pressed'), 'true')
  assert.deepEqual(await saves(), [])
  assert.match(await card.getByRole('button', { name: 'Nhóm điều kiện loại trừ', exact: true }).innerText(), /Đã sửa/)
  assert.equal(await card.locator('.exclusion-list-chip').innerText().then(s => s.includes('VIP')), true)
  const output = mkdtempSync(join(tmpdir(), 'aka-exclusion-ai-ui-'))
  for (const theme of ['dark', 'light']) {
    await page.evaluate(theme => document.body.classList.toggle('theme-light', theme === 'light'), theme)
    await editor.screenshot({ path: join(output, `new-group-${theme}.png`) })
  }
  await editor.getByRole('button', { name: 'Hủy', exact: true }).click()
  assert.deepEqual(await saves(), [])
  await send(); await resolve(patch); await editor.waitFor()
  await editor.getByRole('button', { name: 'Lưu nhóm', exact: true }).click()
  await editor.waitFor({ state: 'detached' })
  const writes = await saves()
  assert.equal(writes.length, 1); assert.equal(writes[0].method, 'saveSendExclusionGroup')
  assert.equal(writes[0].args[0].id, undefined); assert.equal(writes[0].args[0].accountId, 11)
  assert.equal(writes[0].args[0].revision, 0); assert.deepEqual(writes[0].args[0].rules, patch.rules)
  assert.match(await card.getByRole('button', { name: 'Nhóm điều kiện loại trừ', exact: true }).innerText(), /VIP hoặc/)
  assert.match(await card.locator('.exclusion-list-chip').innerText(), /VIP/)
  await open()
  const accountPicker = card.getByLabel('Từ Zalo nào', { exact: true })
  await accountPicker.selectOption('12')
  await page.waitForFunction(() => !document.querySelector('[aria-label="Tạo nhóm loại trừ bằng AI"]').disabled)
  await send()
  assert.equal(await page.evaluate(() => window.scheduleSmoke.state.requests.at(-1).context.accountId), 12)
  // Programmatic account changes also cancel a request, even though normal input is locked while waiting.
  await accountPicker.evaluate(select => { select.value = '11'; select.dispatchEvent(new Event('change', { bubbles: true })) })
  await resolve(patch); assert.equal(await editor.count(), 0)
  await panel.getByRole('button', { name: 'Đóng nhập điều kiện AI' }).click()
  await open(); await send()
  await panel.getByRole('button', { name: 'Hủy yêu cầu' }).click()
  await resolve(patch); assert.equal(await editor.count(), 0)
  await panel.getByRole('button', { name: 'Đóng nhập điều kiện AI' }).click()
  await send(); await page.evaluate(() => window.scheduleSmoke.expire()); await panel.getByRole('alert').waitFor()
  await resolve(patch); assert.equal(await editor.count(), 0)
  await panel.getByRole('button', { name: 'Đóng nhập điều kiện AI' }).click()
  await send()
  await resolve({ ...patch, rules: [{ ...patch.rules[0], value: ['not-in-catalog'] }] })
  await panel.getByRole('alert').waitFor(); assert.equal(await editor.count(), 0)
  await panel.getByRole('button', { name: 'Đóng nhập điều kiện AI' }).click()
  await send(); await open(); await resolve(patch); assert.equal(await editor.count(), 0, 'closed form ignores late result')
  await send(); await page.evaluate(() => window.scheduleSmoke.switchUser()); await resolve(patch)
  assert.equal(await editor.count(), 0, 'new session ignores late result')
  assert.equal((await saves()).length, 1, 'only the explicit Save group writes')
  await page.evaluate(() => {
    window.scheduleSmoke.state.formAiRows = [{ sectionId: 'campaign.send_exclusions', campaignScope: 'selected', campaignActionIds: ['zalo_message_phone'] }]
    window.scheduleSmoke.openExclusions()
  })
  await card.waitFor()
  assert.equal(await trigger.count(), 0, 'metadata scope hides the button')
  console.log('Screenshots: ' + output)
  console.log('PASS full campaign form: opens new group with conditions, preserves selected group/lists until manual Save, shared lock, invalid IDs, cancel/deadline/form/auth, no automatic writes')
}
