const assert = require('node:assert/strict')
const { mkdtempSync, writeFileSync, readFileSync, rmSync, mkdirSync } = require('node:fs')
const { join, resolve } = require('node:path')
const { tmpdir } = require('node:os')
const { build } = require('esbuild')
const { _electron } = require('playwright')
async function main() {
  const dir = mkdtempSync(join(tmpdir(), 'aka-phone-ui-')); let app, page
  try {
    await build({ entryPoints: [join(__dirname, 'zalo-phone-check-ui-smoke.tsx')], outdir: dir, bundle: true, platform: 'browser', format: 'iife', jsx: 'automatic', target: 'chrome120', define: { 'process.env.NODE_ENV': '"development"' }, loader: { '.png': 'dataurl', '.svg': 'dataurl', '.woff2': 'dataurl' }, logLevel: 'warning', plugins: [{ name: 'count-row-renders', setup(b) { b.onLoad({ filter: /ZaloPhoneCheckModal.tsx$/ }, args => ({ loader: 'tsx', contents: readFileSync(args.path, 'utf8').replace('writeFile(book,', ';(window as any).phoneSmoke.captureExport(book,') })); b.onLoad({ filter: /ZaloPhoneCheckTable.tsx$/ }, args => ({ loader: 'tsx', contents: readFileSync(args.path, 'utf8').replace('  const row = useStore', '  const counts = (window as any).phoneSmoke.renders; counts[id] = (counts[id] || 0) + 1\n  const row = useStore') })) } }] })
    writeFileSync(join(dir, 'index.html'), '<html lang="vi"><meta charset="utf-8"><link rel="stylesheet" href="zalo-phone-check-ui-smoke.css"><body><div id="root"></div><script src="zalo-phone-check-ui-smoke.js"></script></body></html>')
    writeFileSync(join(dir, 'main.cjs'), `const{app,BrowserWindow}=require('electron');app.whenReady().then(()=>{const w=new BrowserWindow({show:false,width:1440,height:1000,webPreferences:{sandbox:true,contextIsolation:true,nodeIntegration:false}});w.webContents.session.webRequest.onBeforeRequest((d,c)=>c({cancel:/^https?:/.test(d.url)}));w.loadFile(${JSON.stringify(join(dir, 'index.html'))})})`)
    const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE
    app = await _electron.launch({ executablePath: require('electron'), args: [join(dir, 'main.cjs')], cwd: resolve(__dirname, '..'), env })
    page = await app.firstWindow(); page.setDefaultTimeout(10000)
    const errors = []; page.on('pageerror', error => errors.push(error.message))
    await page.locator('[data-phone-row]').last().waitFor()
    assert.equal(await page.locator('[data-phone-row]').count(), 300)
    await page.evaluate(() => { const s = window.phoneSmoke; s.renders = {}; s.store.begin('run-perf', 71, 300); s.store.row({ runId: 'run-perf', accountId: 71, sequence: 1, row: { ...s.store.getState().rows[s.phones[0]], status: 'checking' } }) })
    await page.locator('.phone-check-status.is-checking').waitFor()
    assert.deepEqual(await page.evaluate(() => window.phoneSmoke.renders), { '0900000000': 1 })
    await page.evaluate(() => { const previous = document.createElement('div'); previous.className = 'data-group-manager-backdrop'; previous.id = 'original-group-picker'; document.body.append(previous); window.phoneSmoke.show() })
    const dialog = page.getByRole('dialog', { name: 'Kiểm tra SĐT có Zalo', exact: true })
    await dialog.waitFor()
    assert.equal(await page.evaluate(() => Number(getComputedStyle(document.querySelector('#original-group-picker')).zIndex) < Number(getComputedStyle(document.querySelector('.phone-check-overlay')).zIndex)), true)
    assert.equal(await dialog.getByLabel('Số lượng kiểm tra').inputValue(), '300')
    await dialog.getByRole('button', { name: 'Tải data', exact: true }).click()
    await page.getByRole('textbox').first().fill('0901234567\n+84 901 234 567\n0912345678\ninvalid')
    await page.getByRole('button', { name: 'Format chuẩn dữ liệu', exact: true }).click()
    await page.locator('.campaign-feedback-modal').getByRole('button', { name: 'Đóng', exact: true }).click()
    await page.getByRole('button', { name: 'Thêm SĐT', exact: true }).click()
    await dialog.getByText('2 SĐT', { exact: true }).waitFor()
    await dialog.getByLabel('Số lượng kiểm tra').fill('1')
    await dialog.getByRole('button', { name: 'Bắt đầu kiểm tra', exact: true }).click()
    await page.waitForFunction(() => window.phoneSmoke.startCount === 1)
    assert.equal(await dialog.getByRole('button', { name: 'Tải data', exact: true }).isDisabled(), true)
    const request = await page.evaluate(() => window.phoneSmoke.request)
    assert.deepEqual(request.phones, ['0901234567', '0912345678']); assert.equal(request.limit, 1)
    await page.evaluate(() => { const s = window.phoneSmoke; s.row({ runId: s.request.runId, accountId: 71, sequence: 1, row: { id: '0901234567', phone: '0901234567', name: 'Tên Zalo từ API', uid: '12345678901234567890', status: 'found', note: '', accountId: 71 } }) })
    await dialog.getByText('Tên Zalo từ API', { exact: true }).waitFor()
    mkdirSync('/tmp/akaagent-phone-check-ui', { recursive: true }); await dialog.screenshot({ path: '/tmp/akaagent-phone-check-ui/modal.png' })
    await dialog.getByRole('button', { name: 'Đóng kiểm tra SĐT', exact: true }).click()
    await page.getByRole('button', { name: 'Tiếp tục kiểm tra', exact: true }).click()
    assert.equal(await page.evaluate(() => window.phoneSmoke.cancels.length), 0)
    await dialog.getByRole('button', { name: 'Đóng kiểm tra SĐT', exact: true }).click()
    await page.getByRole('button', { name: 'Dừng và đóng', exact: true }).click()
    await page.getByText('Đã đóng', { exact: true }).waitFor()
    assert.equal(await page.evaluate(() => window.phoneSmoke.cancels.length), 1)
    // Import a real Excel file carrying metadata. Only phone crosses into the checker.
    const XLSX = require('xlsx')
    const book = XLSX.utils.book_new()
    XLSX.utils.book_append_sheet(book, XLSX.utils.aoa_to_sheet([
      ['Fullname', 'Uid', 'Mobile', 'Email', 'Info1', 'Info2', 'Info3', 'Info4', 'Info5'],
      ['NAME_FROM_FILE', '999999', '0901234567', 'file@example.test', 'SECRET_INFO', '', '', '', '']
    ]), 'akaBiz')
    const file = join(dir, 'source.xlsx'); XLSX.writeFile(book, file)
    await page.evaluate(() => window.phoneSmoke.show())
    await dialog.getByRole('button', { name: 'Tải data', exact: true }).click()
    await page.getByRole('tab', { name: 'Từ template Excel akaBiz', exact: true }).click()
    await page.locator('input[type="file"][accept=".xlsx,.xls,.csv"]').setInputFiles(file)
    await page.getByRole('button', { name: 'Thêm SĐT', exact: true }).click()
    await dialog.getByText('1 SĐT', { exact: true }).waitFor()
    assert.equal(await dialog.getByText('NAME_FROM_FILE', { exact: true }).count(), 0)
    assert.equal(await dialog.getByText('999999', { exact: true }).count(), 0)
    assert.equal(await dialog.getByText('SECRET_INFO', { exact: true }).count(), 0)
    await dialog.getByRole('checkbox', { name: 'Chọn 0901234567', exact: true }).check()
    await dialog.getByRole('button', { name: 'Tải về Excel mẫu akaBiz', exact: true }).click()
    const exportedBook = await page.evaluate(() => window.phoneSmoke.exported)
    const outputPath = join(dir, 'exported.xlsx'); XLSX.writeFile(exportedBook, outputPath)
    const exported = XLSX.readFile(outputPath).Sheets.akaBiz
    assert.equal(exported.C2.v, '0901234567'); assert.equal(exported.C2.t, 's')
    for (const column of ['A', 'B', 'D', 'E', 'F', 'G', 'H', 'I']) assert.equal(exported[column + '2'].v, '')
    // The exported template is accepted by the same phone-mode campaign importer.
    await dialog.getByRole('button', { name: 'Tải data', exact: true }).click()
    await page.getByRole('tab', { name: 'Từ template Excel akaBiz', exact: true }).click()
    await page.locator('input[type="file"][accept=".xlsx,.xls,.csv"]').setInputFiles({ name: 'template.xlsx', mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer: readFileSync(outputPath) })
    await page.getByRole('button', { name: 'Thêm SĐT', exact: true }).click()
    await dialog.getByText('1 SĐT', { exact: true }).waitFor()
    await dialog.getByRole('checkbox', { name: 'Chọn 0901234567', exact: true }).check()
    await dialog.getByRole('button', { name: 'Lưu vào nhóm data', exact: true }).click()
    await page.getByRole('button', { name: 'Nhóm Zalo UID', exact: true }).click()
    await page.getByText('Nhóm Zalo UID chỉ nhận các dòng Có Zalo, có Zalo ID và tài khoản đã kiểm tra.', { exact: true }).waitFor()
    await page.locator('.campaign-feedback-modal').getByRole('button', { name: 'Đóng', exact: true }).click()
    await page.getByRole('button', { name: 'Nhóm SĐT', exact: true }).click()
    const picker = page.getByRole('dialog', { name: 'Quản lý nhóm data', exact: true })
    await picker.getByRole('button', { name: 'Chọn nhóm data', exact: true }).click()
    await page.waitForFunction(() => !!window.phoneSmoke.ingested)
    const saved = await page.evaluate(() => window.phoneSmoke.ingested)
    assert.equal(saved.dataTypeCategoryItemId, 1); assert.equal(saved.rows.length, 1)
    assert.equal(saved.rows[0].phone, '0901234567'); assert.equal(saved.rows[0].uid, null)
    assert.equal(await dialog.getByRole('checkbox', { name: 'Chọn 0901234567', exact: true }).isChecked(), true)
    await page.locator('.campaign-feedback-modal').getByRole('button', { name: 'Đóng', exact: true }).click()
    await dialog.getByRole('button', { name: 'Bắt đầu kiểm tra', exact: true }).click()
    await page.waitForFunction(() => window.phoneSmoke.startCount === 2)
    await page.evaluate(() => { const s = window.phoneSmoke; const row = { id: '0901234567', phone: '0901234567', name: 'Tên API', uid: '12345678901234567890', status: 'found', note: '', accountId: 71 }; s.row({ runId: s.request.runId, accountId: 71, sequence: 1, row }); s.complete([row]) })
    await dialog.getByRole('button', { name: 'Lưu vào nhóm data', exact: true }).click()
    await page.getByRole('button', { name: 'Nhóm Zalo UID', exact: true }).click()
    await picker.getByRole('button', { name: 'Chọn nhóm data', exact: true }).click()
    await page.waitForFunction(() => window.phoneSmoke.ingested.dataTypeCategoryItemId === 2)
    const savedUid = await page.evaluate(() => window.phoneSmoke.ingested)
    assert.equal(savedUid.rows[0].uid, '12345678901234567890'); assert.equal(savedUid.rows[0].sourceAccountId, 71)
    assert.equal(await dialog.getByRole('checkbox', { name: 'Chọn 0901234567', exact: true }).isChecked(), true)
    assert.deepEqual(errors, [])
    console.log('PASS Electron: 300 rows, exactly 1 row renders per update, real text/Excel import strips metadata, template round-trip, both group types, live result, locked form and stop/close confirmation')
  } catch (error) { if (page) console.error((await page.locator('body').innerText()).slice(-2500)); throw error }
  finally { if (app) await app.close(); rmSync(dir, { recursive: true, force: true }) }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
