// "Nâng cấp và mua gói": giao diện Desktop (mục menu, Thông tin tài khoản, dải thông báo, màn đăng nhập, thông báo tính năng
// chưa kích hoạt, khung form) với IPC giả lập. Dựng renderer bằng esbuild rồi mở bằng Chromium của Playwright (cùng nhân với
// Electron), không cần binary Electron và không kết nối mạng. Form dùng <webview> nên chỉ kiểm phần khung và các lệnh gửi
// xuống tiến trình chính, không kiểm trang CRM bên trong.
//   node scripts/run-upgrade-portal-ui-smoke.cjs            # kiểm
//   UPGRADE_UI_SHOTS=<thư mục> node scripts/run-upgrade-portal-ui-smoke.cjs   # kiểm + chụp màn hình
const assert = require('node:assert/strict')
const { mkdtempSync, writeFileSync, rmSync, mkdirSync, existsSync } = require('node:fs')
const { join } = require('node:path')
const { tmpdir } = require('node:os')
const { build } = require('esbuild')
const { chromium } = require('playwright')

async function main() {
  const directory = mkdtempSync(join(tmpdir(), 'akaagent-upgrade-portal-ui-'))
  const shots = process.env.UPGRADE_UI_SHOTS || ''
  if (shots) mkdirSync(shots, { recursive: true })
  await build({ entryPoints: [join(__dirname, 'upgrade-portal-ui-smoke.tsx')], outdir: directory,
    bundle: true, platform: 'browser', format: 'iife', jsx: 'automatic', target: 'chrome120',
    // TopBar lấy ảnh biểu tượng bằng `new URL(..., import.meta.url)`; bản dựng iife không có import.meta nên cho một địa chỉ giả.
    define: { 'process.env.NODE_ENV': '"development"', 'import.meta.url': '"file:///akaagent/smoke/TopBar.tsx"' }, loader: { '.png': 'dataurl', '.svg': 'dataurl', '.jpg': 'dataurl', '.woff2': 'dataurl', '.woff': 'dataurl', '.ttf': 'dataurl' }, logLevel: 'warning' })
  writeFileSync(join(directory, 'index.html'), '<!doctype html><html lang="vi"><meta charset="utf-8"><link rel="stylesheet" href="upgrade-portal-ui-smoke.css"><body><div id="root"></div><script src="upgrade-portal-ui-smoke.js"></script></body></html>')
  const chromiumPath = process.env.UPGRADE_UI_CHROMIUM || (existsSync('/opt/pw-browsers/chromium') ? '/opt/pw-browsers/chromium' : '')
  const browser = await chromium.launch(chromiumPath ? { executablePath: chromiumPath, args: ['--no-sandbox'] } : {})
  let cases = 0
  try {
    const context = await browser.newContext({ viewport: { width: 1280, height: 760 }, timezoneId: 'Asia/Ho_Chi_Minh', locale: 'vi-VN' })
    await context.route(/^https?:/, route => route.abort())
    const page = await context.newPage()
    page.setDefaultTimeout(10000)
    await page.goto(`file://${join(directory, 'index.html')}`)
    await page.waitForFunction(() => window.upgradeSmoke)
    const smoke = (method, ...args) => page.evaluate(([name, params]) => window.upgradeSmoke[name](...params), [method, args])
    const calls = name => page.evaluate(method => window.upgradeSmoke.state.calls.filter(call => call.method === method).map(call => call.args), name)
    const clicks = () => page.evaluate(() => window.upgradeSmoke.state.clicks)
    const setState = values => page.evaluate(next => Object.assign(window.upgradeSmoke.state, next), values)
    const shot = async name => { if (shots) await page.screenshot({ path: join(shots, `desktop-${name}.png`) }) }
    const ok = name => { cases += 1; console.log(`PASS ${name}`) }
    const form = page.locator('.renewal-reminder-window')
    const formTitle = page.locator('#renewal-reminder-window-title')
    const alertBox = page.locator('.campaign-feedback-modal')
    const closeForm = async () => { await form.getByTitle('Đóng').click(); await form.waitFor({ state: 'detached' }) }

    // 1. Mục menu ngay dưới "Thông tin tài khoản", có dòng phụ; bấm mở form trong phần mềm.
    await page.locator('.app-sidebar-account-button').click()
    const items = page.locator('.app-sidebar-flyout-item')
    await items.first().waitFor()
    const labels = (await items.allInnerTexts()).map(text => text.replace(/\s+/g, ' ').trim())
    assert.equal(labels[0], 'Thông tin tài khoản')
    assert.equal(labels[1], 'Nâng cấp và mua gói Gia hạn, thêm tài khoản, dùng thử')
    await shot('menu')
    await items.nth(1).click()
    await form.waitFor()
    assert.equal(await formTitle.innerText(), 'Nâng cấp và mua gói')
    assert.equal(await page.locator('.app-sidebar-flyout-item').count(), 0, 'menu phải đóng lại')
    assert.deepEqual(await calls('openUpgradePortal'), [[{ from: 'menu', entitlementId: null }]])
    assert.equal(await form.getByRole('button', { name: 'Tải lại' }).count(), 1)
    assert.equal(await form.getByRole('button', { name: 'Mở bằng trình duyệt' }).count(), 1)
    assert.equal(await form.locator('webview').getAttribute('src'), 'about:blank', 'giao diện chỉ gắn about:blank, link do main nạp')
    assert.equal(await form.locator('webview').getAttribute('partition'), 'akaagent_renewal')
    await shot('form-dang-mo')
    ok('mục menu ngay dưới Thông tin tài khoản mở form "Nâng cấp và mua gói"')

    // 2. Trạng thái từ main: không có vé thì nhắc đăng nhập cổng; trang báo kích hoạt thì hiện dấu; nút dự phòng gọi đúng lệnh.
    await smoke('web', { signed: false })
    await form.locator('.renewal-reminder-window-note').waitFor()
    assert.match(await form.locator('.renewal-reminder-window-note').innerText(), /đăng nhập trang này bằng tài khoản akaAgent/)
    await smoke('web', { signed: true, orderCompleted: true })
    await form.locator('.renewal-reminder-window-done').waitFor()
    assert.match(await form.locator('.renewal-reminder-window-done').innerText(), /Đã kích hoạt gói\./)
    await form.getByRole('button', { name: 'Tải lại' }).click()
    await form.getByRole('button', { name: 'Mở bằng trình duyệt' }).click()
    await page.waitForFunction(() => window.upgradeSmoke.state.calls.some(call => call.method === 'openUpgradePortalExternal'))
    assert.equal((await calls('reloadUpgradePortal')).length, 1)
    assert.deepEqual(await calls('openUpgradePortalExternal'), [[{ from: 'menu', entitlementId: null }]])
    ok('khung form: ghi chú đăng nhập khi không có vé, dấu đã kích hoạt, nút Tải lại và Mở bằng trình duyệt')

    // 3. Hai lối bấm liên tiếp dùng lại một form; đóng form gọi main đúng một lần, gói đổi thì báo.
    await smoke('open', 'account', 501)
    await smoke('open', 'feature')
    assert.equal(await form.count(), 1)
    assert.equal((await calls('openUpgradePortal')).length, 1)
    assert.deepEqual(await smoke('shop'), { request: { from: 'menu', entitlementId: null }, openSeq: 1 })
    await setState({ closeUpdated: true })
    await closeForm()
    await alertBox.waitFor()
    assert.match(await alertBox.innerText(), /Gói đã được cập nhật\./)
    assert.equal((await calls('closeUpgradePortal')).length, 1)
    await shot('goi-da-cap-nhat')
    await alertBox.getByRole('button', { name: 'Đóng' }).click()
    await setState({ closeUpdated: false })
    ok('hai lối bấm liên tiếp dùng lại một form; đóng form đọc lại gói và báo "Gói đã được cập nhật."')

    // 4. Thông tin tài khoản: mỗi gói có nút "Gia hạn / Nâng cấp", cuối danh sách có nút mua thêm.
    await smoke('clear')
    await page.evaluate(() => window.upgradeSmokeProfile(true))
    const profile = page.locator('.account-profile-modal')
    await profile.waitFor()
    const productButtons = profile.getByRole('button', { name: 'Gia hạn / Nâng cấp' })
    assert.equal(await productButtons.count(), 2)
    const more = profile.locator('.account-profile-more-button')
    assert.match((await more.innerText()).replace(/\s+/g, ' '), /Mua thêm hoặc dùng thử sản phẩm khác Dùng thử miễn phí trước khi mua/)
    await shot('thong-tin-tai-khoan')
    await productButtons.nth(1).click()
    await form.waitFor()
    assert.equal(await profile.count(), 0, 'hộp Thông tin tài khoản đóng lại như nút gia hạn sẵn có')
    assert.deepEqual(await calls('openUpgradePortal'), [[{ from: 'account', entitlementId: 502 }]])
    await closeForm()
    await smoke('clear')
    await page.evaluate(() => window.upgradeSmokeProfile(true))
    await more.click()
    await form.waitFor()
    assert.deepEqual(await calls('openUpgradePortal'), [[{ from: 'account', entitlementId: null }]])
    await closeForm()
    ok('Thông tin tài khoản: nút của từng gói gửi đúng id dòng sản phẩm, nút mua thêm mở chế độ mua hàng')

    // 5. Gói đang được nhắc giữ nút cũ (cửa sổ "Gia hạn gói"); đang mở cửa sổ đó mà bấm lối khác thì dùng lại cửa sổ đang mở.
    await smoke('login', 7, { reminder: true })
    await page.waitForFunction(() => window.upgradeSmoke.state.reminder === true)
    await page.waitForTimeout(200)
    await smoke('clear')
    await page.evaluate(() => window.upgradeSmokeProfile(true))
    await profile.waitFor()
    assert.equal(await profile.getByRole('button', { name: 'Gia hạn / Nâng cấp' }).count(), 1, 'chỉ gói không được nhắc có nút mới')
    const renewButton = profile.locator('.renewal-reminder-primary')
    assert.equal(await renewButton.count(), 1)
    await shot('thong-tin-tai-khoan-co-nhac')
    await renewButton.click()
    await form.waitFor()
    assert.equal(await formTitle.innerText(), 'Gia hạn gói')
    assert.equal((await calls('openRenewalReminderWindow')).length, 1)
    assert.equal(await form.getByRole('button', { name: 'Tải lại' }).count(), 0, 'cửa sổ gia hạn giữ nguyên như trước')
    await smoke('open', 'menu')
    await smoke('open', 'account', 502)
    assert.equal(await form.count(), 1)
    assert.equal(await formTitle.innerText(), 'Gia hạn gói')
    assert.equal((await calls('openUpgradePortal')).length, 0)
    await closeForm()
    assert.equal((await calls('closeRenewalReminderWindow')).length, 1)
    await smoke('login', 7, { reminder: false })
    await page.waitForTimeout(200)
    ok('gói đang được nhắc giữ cửa sổ "Gia hạn gói"; đang mở thì các lối mới dùng lại cửa sổ đó')

    // 6. Dải thông báo: link tới cổng mở form, link khác vẫn để trình duyệt mở.
    await smoke('clear')
    await setState({ notification: { id: 1, title: 'Gói sắp hết hạn', message: 'Gia hạn sớm để không gián đoạn.', level: 'warning', linkLabel: 'Gia hạn', linkUrl: 'https://crm.akabiz.net/gia-han?next=%2Fgia-han%2Fhet-han-goi&src=banner.d7', startsAt: null, endsAt: null } })
    await page.evaluate(() => window.upgradeSmokeReloadBar())
    const barLink = page.locator('.app-notification-link')
    await barLink.waitFor()
    await shot('dai-thong-bao')
    await barLink.click()
    await form.waitFor()
    assert.deepEqual(await calls('openUpgradePortal'), [[{ from: 'banner', entitlementId: null }]])
    assert.deepEqual((await clicks()).map(item => item.handledInApp), [true])
    await closeForm()
    await smoke('clear')
    await setState({ notification: { id: 2, title: 'Tin mới', message: 'Xem hướng dẫn.', level: 'info', linkLabel: 'Xem', linkUrl: 'https://akabiz.net/huong-dan', startsAt: null, endsAt: null } })
    await page.evaluate(() => window.upgradeSmokeReloadBar())
    await page.locator('.app-notification-link', { hasText: 'Xem' }).click()
    assert.deepEqual(await clicks(), [{ href: 'https://akabiz.net/huong-dan', handledInApp: false }])
    assert.equal(await form.count(), 0)
    assert.equal((await calls('openUpgradePortal')).length, 0)
    await setState({ notification: null })
    await page.evaluate(() => window.upgradeSmokeReloadBar())
    ok('dải thông báo: link tới cổng mở form, link khác vẫn mở trình duyệt')

    // 7. Thông báo "tính năng chưa kích hoạt": thêm nút "Mua hoặc dùng thử"; thông báo khác giữ nguyên.
    await smoke('clear')
    await smoke('alert', 'Tính năng Zalo chưa được kích hoạt hoặc đã hết hạn.', 'error')
    await alertBox.waitFor()
    assert.deepEqual(await alertBox.locator('.modal-footer button').allInnerTexts(), ['Đóng', 'Mua hoặc dùng thử'])
    await shot('thong-bao-tinh-nang')
    await alertBox.getByRole('button', { name: 'Mua hoặc dùng thử' }).click()
    await form.waitFor()
    assert.equal(await alertBox.count(), 0)
    assert.deepEqual(await calls('openUpgradePortal'), [[{ from: 'feature', entitlementId: null }]])
    await closeForm()
    await smoke('alert', 'Tính năng Zalo chưa được kích hoạt hoặc đã hết hạn.', 'error')
    await alertBox.getByRole('button', { name: 'Đóng' }).click()
    assert.equal(await alertBox.count(), 0)
    assert.equal(await form.count(), 0)
    await smoke('alert', 'Không thể lưu chiến dịch.', 'error')
    assert.deepEqual(await alertBox.locator('.modal-footer button').allInnerTexts(), ['Đóng'])
    await alertBox.getByRole('button', { name: 'Đóng' }).click()
    await smoke('alert', 'Tính năng Zalo chưa được kích hoạt hoặc đã hết hạn.', 'error', true)
    assert.deepEqual(await alertBox.locator('.modal-footer button').allInnerTexts(), ['Thử lại'], 'thông báo đã có nút riêng thì giữ nguyên')
    await alertBox.getByRole('button', { name: 'Thử lại' }).click()
    await smoke('alert', 'Đã lưu. Gói chưa được kích hoạt hoặc đã hết hạn.', 'info')
    assert.deepEqual(await alertBox.locator('.modal-footer button').allInnerTexts(), ['Đóng'], 'chỉ thông báo lỗi mới thêm nút')
    await alertBox.getByRole('button', { name: 'Đóng' }).click()
    ok('thông báo tính năng chưa kích hoạt có nút "Mua hoặc dùng thử"; thông báo khác không đổi')

    // 8. Đổi tài khoản: form đang mở biến mất, giao diện không gọi đóng (main tự đóng theo phiên).
    await smoke('clear')
    await smoke('open', 'menu')
    await form.waitFor()
    await smoke('login', 8)
    await form.waitFor({ state: 'detached' })
    assert.equal((await calls('closeUpgradePortal')).length, 0)
    assert.equal((await smoke('shop')).request, null)
    ok('đổi tài khoản thì form đóng')

    // 9. Màn đăng nhập: link "Nâng cấp và thanh toán" tới cổng mở form; link khác và địa chỉ khác vẫn mở trình duyệt.
    await smoke('login', 0)
    const resources = page.locator('.login-resource')
    await resources.first().waitFor()
    await smoke('clear')
    await shot('man-dang-nhap')
    await resources.filter({ hasText: 'Nâng cấp và thanh toán' }).click()
    await form.waitFor()
    assert.equal(await formTitle.innerText(), 'Nâng cấp và mua gói')
    assert.deepEqual(await calls('openUpgradePortal'), [[{ from: 'login', entitlementId: null }]])
    await shot('man-dang-nhap-form')
    await closeForm()
    await resources.filter({ hasText: 'Website' }).click()
    assert.deepEqual((await clicks()).map(item => item.handledInApp), [true, false])
    assert.equal(await form.count(), 0)
    await smoke('alert', 'Tính năng Zalo chưa được kích hoạt hoặc đã hết hạn.', 'error')
    assert.deepEqual(await alertBox.locator('.modal-footer button').allInnerTexts(), ['Đóng'], 'chưa đăng nhập thì không có lối mua trong thông báo')
    await alertBox.getByRole('button', { name: 'Đóng' }).click()
    await smoke('clear')
    await setState({ upgradePayment: 'https://akabiz.net/bang-gia' })
    await smoke('login', 7)
    await page.locator('.app-sidebar-account-button').waitFor()
    await smoke('login', 0)
    await resources.first().waitFor()
    await resources.filter({ hasText: 'Nâng cấp và thanh toán' }).click()
    assert.deepEqual(await clicks(), [{ href: 'https://akabiz.net/bang-gia', handledInApp: false }])
    assert.equal(await form.count(), 0)
    assert.equal((await calls('openUpgradePortal')).length, 0)
    ok('màn đăng nhập: link tới cổng mở form không cần đăng nhập, địa chỉ khác vẫn mở trình duyệt')

    const errors = await page.evaluate(() => window.upgradeSmoke.state.errors)
    assert.deepEqual(errors, [], `lỗi trong trang: ${errors.join(' | ')}`)
    ok('không có lỗi JavaScript trong trang')
  } finally {
    await browser.close()
    rmSync(directory, { recursive: true, force: true })
  }
  console.log(`\n${cases} nhóm đạt.`)
}

main().catch(error => { console.error(error); process.exit(1) })
