  local out
  if out=$("$@" 2>&1); then fail "$label: lệnh chạy được nhưng lẽ ra phải lỗi"; fi
  grep -q -- "$needle" <<<"$out" || fail "$label: lỗi không chứa '$needle': $out"
}
