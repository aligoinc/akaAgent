q() { as_pg "${PSQL[@]}" -c "$1"; }
run_file() { as_pg "${PSQL[@]}" -f "$1"; }
pass=0
ok() { pass=$((pass + 1)); echo "ok $pass - $1"; }
fail() { echo "FAIL - $1" >&2; exit 1; }
expect_error() { # $1 mô tả, $2 chuỗi lỗi phải có, phần còn lại: lệnh
