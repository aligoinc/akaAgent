const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const m = require('./action-status-policy-migration.cjs')
const seed = require('./action-status-policy-seed.cjs')
const before = m.checkedBackup()
const { quote: q, jsonSQL: j } = m
const policy = m.newTable
const newFunctions = ['aka_agent_guard_result_catalog_v361()', 'aka_agent_guard_detail_result_v361()', 'aka_agent_guard_result_status_v361()']
const additions = {
  auto_status: ['status_value', 'color'],
  auto_error: ['detail_status_id', 'detail_mode', 'input_effect'],
  auto_campaign_details: ['status_id', 'sub_status_id', 'action_status_policy_id', 'report_group', 'policy_snapshot', 'result_key'],
  auto_automation_trigger_statuses: ['sub_status_ids']
}
const statusValues = before.tables.auto_status.rows.filter(x => x.row.component_type === 'campaign_detail').map(({row}) => {
  const values = [...new Set(before.tables.auto_campaign_action_detail_statuses.rows.filter(x => x.row.status_id === row.id).map(x => x.row.status_value))]
  assert.equal(values.length, 1, `Ambiguous legacy text: ${row.code}`)
  return { id: row.id, code: row.code, status_value: values[0] }
})
for (const row of seed.rows) {
  const def = seed.rows.find(x => x.status_code === row.status_code && x.action_code === null)
  if (row.action_code && def) assert(['report_group','counts_toward_limit','bad_target_effect','reset_error_streak','input_effect'].some(k => row[k] !== def[k]), 'Redundant override')
  if (row.action_code) assert(before.tables.auto_account_actions.rows.some(x => x.row.code === row.action_code))
}
const structural = s => Object.fromEntries(Object.entries(s).filter(([k]) => !['sequence', 'incoming_foreign_keys'].includes(k)))
const schemaGuards = before.schema.filter(s => s.exists).map(s => `IF (${m.schemaSQL(s.table)} - 'sequence' - 'incoming_foreign_keys') IS DISTINCT FROM ${j(structural(s), 'schema_' + s.table)} THEN RAISE EXCEPTION 'v361 schema changed: ${s.table}'; END IF;`).join('\n')
const rowGuards = Object.entries(before.tables).map(([table,data]) => {
  if (table==='auto_campaign_action_detail_statuses') return `-- This untouched catalog's existing runtime UPSERT refreshes updated_at on every detail.
IF (SELECT count(*) FROM public.${table})<>${data.count} OR EXISTS (SELECT 1 FROM jsonb_array_elements(${j(data.rows.map(x=>x.row),'mapping_rows')}) h LEFT JOIN public.${table} t ON t.id=(h->>'id')::bigint WHERE t.id IS NULL OR (to_jsonb(t)-'updated_at') IS DISTINCT FROM (h-'updated_at')) THEN RAISE EXCEPTION 'v361 catalog content changed'; END IF;`
  return `IF (SELECT count(*) FROM public.${table}) <> ${data.count} OR EXISTS (SELECT 1 FROM jsonb_each_text(${j(Object.fromEntries(data.rows.map(x => [x.row.id, x.md5])), 'hash_' + table)}) h LEFT JOIN public.${table} t ON t.id=h.key::bigint WHERE t.id IS NULL OR md5(to_jsonb(t)::text) <> h.value) THEN RAISE EXCEPTION 'v361 rows changed: ${table}'; END IF;`
}).join('\n')
const preflight = `DO $preflight$ BEGIN
${schemaGuards}
${rowGuards}
IF to_regclass('public.${policy}') IS NOT NULL THEN RAISE EXCEPTION 'v361 policy table already exists'; END IF;
${newFunctions.map(f => `IF to_regprocedure('public.${f}') IS NOT NULL THEN RAISE EXCEPTION 'v361 function already exists: ${f}'; END IF;`).join('\n')}
IF EXISTS (SELECT 1 FROM supabase_migrations.schema_migrations WHERE name ~ '^migration_v361(_|$)') THEN RAISE EXCEPTION 'v361 version already used'; END IF;
END $preflight$;`

const sql = `-- Generated from the verified live backup by scripts/build-action-status-policy-migration.cjs.
-- Preparation only: old writers stay on their existing path; no old business RPC is replaced.
BEGIN;
SET LOCAL lock_timeout = '3s';
SET LOCAL statement_timeout = '30s';
${preflight}
ALTER TABLE public.auto_status ADD COLUMN status_value text, ADD COLUMN color text;
CREATE TABLE public.${policy} (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 action_code text REFERENCES public.auto_account_actions(code) ON DELETE RESTRICT,
 status_id bigint NOT NULL REFERENCES public.auto_status(id) ON DELETE RESTRICT,
 report_group text NOT NULL CHECK (report_group IN ('success','failure','skipped','pending')),
 counts_toward_limit boolean NOT NULL,
 bad_target_effect text NOT NULL CHECK (bad_target_effect IN ('increment','reset','ignore')),
 reset_error_streak boolean NOT NULL,
 input_effect text NOT NULL CHECK (input_effect IN ('complete','pause','requeue','none')),
 description text NOT NULL,
 is_active boolean NOT NULL DEFAULT true,
 is_delete boolean NOT NULL DEFAULT false,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX auto_aasp_default_status_uq ON public.${policy}(status_id) WHERE action_code IS NULL;
CREATE UNIQUE INDEX auto_aasp_action_status_uq ON public.${policy}(action_code,status_id) WHERE action_code IS NOT NULL;
CREATE INDEX auto_aasp_status_idx ON public.${policy}(status_id);
ALTER TABLE public.${policy} ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.${policy} FROM PUBLIC,anon,authenticated;
GRANT SELECT ON public.${policy} TO anon,authenticated,aka_agent_chat_api;
GRANT ALL ON public.${policy} TO service_role;
REVOKE ALL ON SEQUENCE public.${policy}_id_seq FROM PUBLIC,anon,authenticated;
GRANT USAGE,SELECT ON SEQUENCE public.${policy}_id_seq TO service_role;
CREATE POLICY action_status_catalog_read ON public.${policy} FOR SELECT TO anon,authenticated,aka_agent_chat_api USING (true);
ALTER TABLE public.auto_error ADD COLUMN detail_status_id bigint REFERENCES public.auto_status(id) ON DELETE RESTRICT,
 ADD COLUMN detail_mode text CHECK (detail_mode IN ('inherit','override','suppress')),
 ADD COLUMN input_effect text CHECK (input_effect IN ('complete','pause','requeue','none')),
 ADD CONSTRAINT auto_error_detail_override_check CHECK (detail_mode IS DISTINCT FROM 'override' OR detail_status_id IS NOT NULL);
CREATE INDEX auto_error_detail_status_idx ON public.auto_error(detail_status_id) WHERE detail_status_id IS NOT NULL;
ALTER TABLE public.auto_campaign_details
 ADD COLUMN status_id bigint,
 ADD COLUMN sub_status_id bigint,
 ADD COLUMN action_status_policy_id bigint,
 ADD COLUMN report_group text,
 ADD COLUMN policy_snapshot jsonb,
 ADD COLUMN result_key text,
 ADD CONSTRAINT auto_detail_status_fk FOREIGN KEY (status_id) REFERENCES public.auto_status(id) ON DELETE RESTRICT NOT VALID,
 ADD CONSTRAINT auto_detail_sub_status_fk FOREIGN KEY (sub_status_id) REFERENCES public.auto_status(id) ON DELETE RESTRICT NOT VALID,
 ADD CONSTRAINT auto_detail_policy_fk FOREIGN KEY (action_status_policy_id) REFERENCES public.${policy}(id) ON DELETE RESTRICT NOT VALID,
 ADD CONSTRAINT auto_detail_report_group_check CHECK (report_group IN ('success','failure','skipped','pending')) NOT VALID,
 ADD CONSTRAINT auto_detail_snapshot_check CHECK (policy_snapshot IS NULL OR jsonb_typeof(policy_snapshot)='object') NOT VALID,
 ADD CONSTRAINT auto_detail_result_key_check CHECK (result_key IS NULL OR length(btrim(result_key))>0) NOT VALID;
ALTER TABLE public.auto_automation_trigger_statuses ADD COLUMN sub_status_ids bigint[],
 ADD CONSTRAINT auto_automation_sub_status_ids_check CHECK (sub_status_ids IS NULL OR (cardinality(sub_status_ids)>0 AND array_ndims(sub_status_ids)=1 AND array_position(sub_status_ids,NULL) IS NULL));

-- New guard functions only. Legacy rows with NULL metadata return without catalog reads.
CREATE FUNCTION public.aka_agent_guard_result_catalog_v361() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $body$
DECLARE ids bigint[];
BEGIN
 IF TG_TABLE_NAME='auto_account_action_status_policies' THEN ids:=ARRAY[NEW.status_id];
 ELSIF TG_TABLE_NAME='auto_error' THEN ids:=CASE WHEN NEW.detail_status_id IS NULL THEN NULL ELSE ARRAY[NEW.detail_status_id] END;
 ELSE ids:=NEW.sub_status_ids;
 END IF;
 IF ids IS NOT NULL AND EXISTS (SELECT 1 FROM unnest(ids) i LEFT JOIN public.auto_status s ON s.id=i WHERE s.id IS NULL OR s.component_type<>'campaign_detail') THEN
   RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='result_status_component_invalid';
 END IF;
 RETURN NEW;
END $body$;
REVOKE ALL ON FUNCTION public.aka_agent_guard_result_catalog_v361() FROM PUBLIC,anon,authenticated;
CREATE TRIGGER auto_aasp_component_guard BEFORE INSERT OR UPDATE OF status_id ON public.${policy} FOR EACH ROW EXECUTE FUNCTION public.aka_agent_guard_result_catalog_v361();
CREATE TRIGGER auto_error_result_component_guard BEFORE INSERT OR UPDATE OF detail_status_id ON public.auto_error FOR EACH ROW EXECUTE FUNCTION public.aka_agent_guard_result_catalog_v361();
CREATE TRIGGER auto_automation_sub_status_guard BEFORE INSERT OR UPDATE OF sub_status_ids ON public.auto_automation_trigger_statuses FOR EACH ROW EXECUTE FUNCTION public.aka_agent_guard_result_catalog_v361();

CREATE FUNCTION public.aka_agent_guard_detail_result_v361() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $body$
DECLARE p public.${policy}%ROWTYPE;
BEGIN
 IF NEW.status_id IS NULL AND NEW.sub_status_id IS NULL AND NEW.action_status_policy_id IS NULL AND NEW.policy_snapshot IS NULL AND NEW.result_key IS NULL AND NEW.report_group IS NULL THEN RETURN NEW; END IF;
 IF EXISTS (SELECT 1 FROM unnest(ARRAY[NEW.status_id,NEW.sub_status_id]) i LEFT JOIN public.auto_status s ON s.id=i WHERE i IS NOT NULL AND (s.id IS NULL OR s.component_type<>'campaign_detail')) THEN
   RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='result_status_component_invalid';
 END IF;
 IF NEW.action_status_policy_id IS NOT NULL THEN
   SELECT * INTO p FROM public.${policy} WHERE id=NEW.action_status_policy_id;
   IF NOT FOUND OR p.status_id IS DISTINCT FROM NEW.status_id OR (p.action_code IS NOT NULL AND p.action_code IS DISTINCT FROM NEW.action_code) THEN
     RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='result_policy_identity_mismatch';
   END IF;
 END IF;
 RETURN NEW;
END $body$;
REVOKE ALL ON FUNCTION public.aka_agent_guard_detail_result_v361() FROM PUBLIC,anon,authenticated;
CREATE TRIGGER auto_detail_result_guard BEFORE INSERT OR UPDATE OF status_id,sub_status_id,action_status_policy_id ON public.auto_campaign_details FOR EACH ROW EXECUTE FUNCTION public.aka_agent_guard_detail_result_v361();

CREATE FUNCTION public.aka_agent_guard_result_status_v361() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $body$
BEGIN
 IF NEW.component_type IS DISTINCT FROM OLD.component_type AND OLD.component_type='campaign_detail' AND (
  EXISTS (SELECT 1 FROM public.${policy} WHERE status_id=OLD.id) OR
  EXISTS (SELECT 1 FROM public.auto_error WHERE detail_status_id=OLD.id) OR
  EXISTS (SELECT 1 FROM public.auto_campaign_details WHERE status_id=OLD.id OR sub_status_id=OLD.id) OR
  EXISTS (SELECT 1 FROM public.auto_automation_trigger_statuses WHERE OLD.id=ANY(sub_status_ids))
 ) THEN RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='result_status_component_in_use'; END IF;
 RETURN NEW;
END $body$;
REVOKE ALL ON FUNCTION public.aka_agent_guard_result_status_v361() FROM PUBLIC,anon,authenticated;
CREATE TRIGGER auto_status_result_component_guard BEFORE UPDATE OF component_type ON public.auto_status FOR EACH ROW EXECUTE FUNCTION public.aka_agent_guard_result_status_v361();

UPDATE public.auto_status s SET status_value=v.status_value FROM jsonb_to_recordset(${j(statusValues,'status_values')}) AS v(id bigint,code text,status_value text) WHERE s.id=v.id AND s.code=v.code;
INSERT INTO public.auto_status(code,name,status_key,status_value,description,is_terminal,sort_order,component_type)
 SELECT code,name,status_key,status_value,description,is_terminal,sort_order,'campaign_detail' FROM jsonb_to_recordset(${j(seed.newStatuses,'new_statuses')}) AS s(code text,name text,status_key text,status_value text,description text,is_terminal boolean,sort_order integer);
INSERT INTO public.${policy}(action_code,status_id,report_group,counts_toward_limit,bad_target_effect,reset_error_streak,input_effect,description)
 SELECT p.action_code,s.id,p.report_group,p.counts_toward_limit,p.bad_target_effect,p.reset_error_streak,p.input_effect,p.description FROM jsonb_to_recordset(${j(seed.rows,'policy_seed')}) AS p(status_code text,action_code text,report_group text,counts_toward_limit boolean,bad_target_effect text,reset_error_streak boolean,input_effect text,description text) JOIN public.auto_status s ON s.code=p.status_code;
COMMIT;
`
const migrationPath = path.join(m.root,'migrations',m.name+'.sql')
fs.writeFileSync(migrationPath,sql)
fs.writeFileSync(path.join(m.directory,'seed-evidence.json'),JSON.stringify({ ...seed, status_values:statusValues,
  unseeded_main_statuses: statusValues.filter(s=>!seed.rows.some(p=>p.status_code===s.code)),
  note:'An unseeded status may be a secondary observation. Using it as a main result requires an explicit verified policy; absence never infers its role.' },null,2)+'\n')
fs.writeFileSync(path.join(m.directory,'objects.json'),JSON.stringify({version:m.version,new_table:policy,new_functions:newFunctions,columns:additions},null,2)+'\n')
