// Isolated in-memory Postgres. Uses the existing PGlite dependency of the sibling Chat API repo.
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { resolve } = require('node:path')
const { PGlite } = require(require.resolve('@electric-sql/pglite', { paths: [resolve(__dirname, '../../akaAgentChatApi')] }))
const baseline = require('./fixtures/message-opt-out-live-baseline.json')
const migration = readFileSync(resolve(__dirname, '../migrations/migration_v295_message_opt_out_customers.sql'), 'utf8')

async function main() {
  const db = new PGlite()
  try {
    await db.exec(`
      CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role; CREATE ROLE aka_agent_chat_api;
      CREATE SCHEMA auth;
      CREATE FUNCTION auth.jwt() RETURNS jsonb LANGUAGE sql AS $$ SELECT nullif(current_setting('request.jwt.claims',true),'')::jsonb $$;
      CREATE TABLE org_staff(id bigint PRIMARY KEY, organization_id bigint, username text, password text, is_active boolean, deleted_at timestamptz);
      CREATE TABLE auto_accounts(id bigint PRIMARY KEY, staff_id bigint, organization_id bigint, flatform_type text, is_delete boolean DEFAULT false);
      CREATE TABLE auto_campaigns(id bigint PRIMARY KEY, staff_id bigint, organization_id bigint, account_id bigint, name text, action_id text, is_delete boolean DEFAULT false);
      CREATE TABLE auto_campaign_input_data(id bigint PRIMARY KEY, campaign_id bigint, email text, uid text);
      CREATE TABLE auto_campaign_details(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, input_data_id bigint, campaign_id bigint,
        account_id bigint, action_code text, action_name text, status text, data jsonb, is_delete boolean DEFAULT false, created_at timestamptz DEFAULT now());
      CREATE TABLE auto_zalo_message_opt_outs(id uuid PRIMARY KEY DEFAULT gen_random_uuid(), phone text, email text, zalo_global_id text NOT NULL,
        staff_id bigint NOT NULL, organization_id bigint NOT NULL, created_at timestamptz NOT NULL DEFAULT clock_timestamp(), confirmed_at timestamptz);
      CREATE UNIQUE INDEX auto_zalo_message_opt_outs_scope_global_id_uidx ON auto_zalo_message_opt_outs(staff_id,organization_id,zalo_global_id);
      ALTER TABLE auto_zalo_message_opt_outs ENABLE ROW LEVEL SECURITY;
      INSERT INTO org_staff VALUES (1,10,'staff1','secret1',true,NULL),(2,10,'staff2','secret2',true,NULL),(3,20,'staff3','secret3',true,NULL);
      INSERT INTO auto_accounts(id,staff_id,organization_id,flatform_type) VALUES(100,1,10,'zalo'),(200,2,10,'zalo'),(300,3,20,'zalo');
      INSERT INTO auto_campaigns(id,staff_id,organization_id,account_id,name,action_id) VALUES
        (1000,1,10,100,'Chiến dịch A','zalo_message_friend'),(1001,1,10,100,'Chiến dịch B','zalo_message_phone'),(2000,2,10,200,'Khác','zalo_message_friend');
      INSERT INTO auto_campaign_input_data VALUES(11,1000,'lan@example.com','user-1'),(12,1001,'lan@example.com','user-1'),(21,2000,'other@example.com','user-2');
    `)
    await db.exec(require('./fixtures/message-opt-out-normalize-phone.json').definition)
    for (const fn of baseline.functions) await db.exec(fn.definition)
    await db.exec(migration.replace(/COMMIT;\s*$/, 'ROLLBACK;'))
    assert.equal((await db.query("SELECT to_regprocedure('public.auto_capture_message_opt_out_source()') AS fn")).rows[0].fn, null)
    await db.exec(migration)
    await db.exec(readFileSync(resolve(__dirname, '../migrations/tests/zalo_message_opt_out_smoke.sql'), 'utf8'))
    const id = '11111111-1111-4111-8111-111111111111'
    await db.query(`INSERT INTO auto_zalo_message_opt_outs(id,staff_id,organization_id,zalo_global_id,phone,created_at)
      VALUES($1,1,10,'global-1','0900000000','2026-09-20T00:00:00Z')`, [id])
    const metadata = sentAt => ({ version: 1, optOutId: id, zaloGlobalId: 'global-1', zaloName: 'Lan', zaloAvatar: 'https://example.com/avatar.png', sentAt })
    const insert = async ({ campaign = 1000, input = 11, account = 100, action = 'zalo_message_friend', status = 'thành công', source, target = 'global-1' } = {}) => {
      const result = await db.query(`INSERT INTO auto_campaign_details(campaign_id,input_data_id,account_id,action_code,action_name,status,data)
        VALUES($1,$2,$3,$4,'Nhắn tin',$5,$6) RETURNING id`, [campaign,input,account,action,status,JSON.stringify({target:{uid:'user-1',globalId:target},messageOptOutSource:source})])
      return result.rows[0].id
    }
    const read = async () => (await db.query('SELECT * FROM auto_zalo_message_opt_outs WHERE id=$1',[id])).rows[0]
    const first = await insert({source:metadata('2026-09-20T01:00:00Z')})
    assert.equal((await read()).source_detail_id, first)
    const second = await insert({campaign:1001,input:12,action:'zalo_message_stranger',source:metadata('2026-09-20T02:00:00Z')})
    assert.equal((await read()).source_campaign_name, 'Chiến dịch B')
    assert.equal((await read()).email, 'lan@example.com')
    for (const options of [
      { status:'thất bại' }, { action:'zalo_find_phone' }, { action:'zalo_tag_contact' },
      { campaign:2000, input:21, account:200 }, { input:21 }, { account:200 }, { target:'global-wrong' },
      { source: {...metadata('2026-09-20T03:00:00Z'), optOutId:'bad-uuid'} },
      { source: metadata('not-a-date') }, { source:null }
    ]) await insert({source:metadata('2026-09-20T03:00:00Z'),...options})
    assert.equal((await read()).source_detail_id, second)
    await insert({source:metadata('2026-09-20T01:30:00Z')})
    assert.equal((await read()).source_detail_id, second, 'late older result must not replace latest')
    await db.query("UPDATE auto_zalo_message_opt_outs SET confirmed_at='2026-09-20T03:00:00Z' WHERE id=$1",[id])
    await insert({source:metadata('2026-09-20T03:01:00Z')})
    assert.equal((await read()).source_detail_id, second, 'send after confirmation must not replace source')
    const delayed = await insert({source:metadata('2026-09-20T02:59:00Z')})
    assert.equal((await read()).source_detail_id, delayed, 'delayed pre-confirmation send fills correct source')
    await db.exec(`DELETE FROM auto_campaign_details; DELETE FROM auto_campaigns WHERE id=1000;`)
    assert.equal((await read()).source_campaign_name, 'Chiến dịch A', 'snapshot survives hard deletion')

    await db.exec(`INSERT INTO auto_zalo_message_opt_outs(staff_id,organization_id,zalo_global_id,confirmed_at)
      SELECT 1,10,'legacy-'||n,'2026-09-19T00:00:00Z'::timestamptz FROM generate_series(1,54)n;
      INSERT INTO auto_zalo_message_opt_outs(staff_id,organization_id,zalo_global_id,confirmed_at)
      VALUES(1,10,'pending',NULL),(2,10,'other-staff',now()),(3,20,'other-org',now());
      SET ROLE anon; SET request.jwt.claim.role='anon';`)
    const list = async (staff=1,org=10,username='staff1',password='secret1',search='',page=1) =>
      (await db.query('SELECT aka_agent_list_message_opt_out_customers($1,$2,$3,$4,$5,$6) AS page',[staff,org,username,password,search,page])).rows[0].page
    let result = await list()
    assert.equal(result.total,55); assert.equal(result.items.length,50); assert.equal(result.items[0].id,id)
    assert.equal(result.items[1].sourceDetailId,null)
    result = await list(1,10,'staff1','secret1','',2)
    assert.equal(result.items.length,5); assert.equal(result.pageSize,50)
    assert.equal((await list(1,10,'staff1','secret1','',999)).page,2)
    for (const search of ['Lan','0900000000','lan@example.com','global-1','Chiến dịch A']) assert.equal((await list(1,10,'staff1','secret1',search)).total,1)
    assert.equal((await list(1,10,'staff1','secret1','%')).total,0, 'wildcards are literal')
    await assert.rejects(list(2,10,'staff1','secret1'))
    await assert.rejects(list(1,20,'staff1','secret1'))
    await assert.rejects(list(1,10,'staff1','wrong'))
    await assert.rejects(db.query('SELECT * FROM auto_zalo_message_opt_outs'))
    await db.exec('RESET ROLE;')
    for (const fn of baseline.functions) {
      const result = await db.query('SELECT md5(pg_get_functiondef(to_regprocedure($1))) AS checksum',[fn.signature])
      assert.equal(result.rows[0].checksum,fn.checksum,'existing function preserved: '+fn.signature)
    }
    console.log('PASS database: migration rollback, unchanged RPCs, latest successful source, delayed writes, tenant isolation, snapshots, paging and literal search')
    await assert.rejects(db.exec(migration), /already exist/)
    await db.exec('ROLLBACK;')
  } finally { await db.close() }
}
main().catch(error => { console.error(error); process.exitCode=1 })
