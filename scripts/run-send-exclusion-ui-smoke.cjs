const assert=require('node:assert/strict')
const {mkdtempSync,writeFileSync,rmSync}=require('node:fs')
const {join,resolve}=require('node:path')
const {tmpdir}=require('node:os')
const {build}=require('esbuild')
const {_electron}=require('playwright')
async function main(){
 const dir=mkdtempSync(join(tmpdir(),'akaagent-exclusions-ui-'));let app
 const output=mkdtempSync(join(tmpdir(),'akaagent-exclusions-ui-artifacts-'))
 try{
  await build({entryPoints:[resolve(__dirname,'send-exclusion-ui-smoke.tsx')],outdir:dir,bundle:true,platform:'browser',format:'iife',jsx:'automatic',define:{'process.env.NODE_ENV':'"development"'}})
  writeFileSync(join(dir,'index.html'),'<!doctype html><html lang="vi"><meta charset="utf-8"><link rel="stylesheet" href="send-exclusion-ui-smoke.css"><body><div id="root"></div><script src="send-exclusion-ui-smoke.js"></script></body></html>')
  writeFileSync(join(dir,'main.cjs'),`const {app,BrowserWindow}=require('electron');app.whenReady().then(()=>{const win=new BrowserWindow({show:false,width:1100,height:1000,webPreferences:{sandbox:true,contextIsolation:true,nodeIntegration:false}});win.webContents.session.webRequest.onBeforeRequest((d,cb)=>cb({cancel:/^https?:/.test(d.url)}));win.loadFile(${JSON.stringify(join(dir,'index.html'))});});`)
  const env={...process.env};delete env.ELECTRON_RUN_AS_NODE
  app=await _electron.launch({executablePath:require('electron'),args:[join(dir,'main.cjs')],env})
  const page=await app.firstWindow();page.setDefaultTimeout(10000)
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.evaluate(()=>document.body.classList.add('theme-light'))
  const groupPicker=page.getByRole('button',{name:'Nhóm điều kiện loại trừ',exact:true})
  await groupPicker.focus()
  await page.keyboard.press('ArrowDown')
  await page.getByRole('listbox').waitFor()
  await page.keyboard.press('End')
  assert.match(await page.locator(':focus').innerText(),/Giới tính nữ/)
  await page.keyboard.press('Escape')
  assert.equal(await groupPicker.getAttribute('aria-expanded'),'false')
  assert(await groupPicker.evaluate(el=>el===document.activeElement))
  await page.getByRole('button',{name:'Thêm nhóm loại trừ'}).click()
  const dialog=page.getByRole('dialog')
  assert(await dialog.getByRole('button',{name:'Lưu nhóm',exact:true}).isDisabled())
  await dialog.getByLabel('Tên nhóm',{exact:true}).fill('Khách hàng nữ')
  await dialog.getByLabel('Giới tính',{exact:true}).check()
  await dialog.getByRole('button',{name:'Nữ',exact:true}).click()
  await dialog.getByLabel('Tag Zalo',{exact:true}).check()
  await dialog.getByRole('button',{name:'VIP',exact:true}).click()
  await dialog.getByRole('button',{name:'Khách mới',exact:true}).click()
  assert.equal(await dialog.getByRole('button',{name:'VIP',exact:true}).getAttribute('aria-pressed'),'true')
  assert.equal(await dialog.getByRole('button',{name:'Khách mới',exact:true}).getAttribute('aria-pressed'),'true')
  await dialog.getByLabel('Trạng thái bạn bè',{exact:true}).check()
  await dialog.getByRole('button',{name:'Bạn bè',exact:true}).click()
  await dialog.getByRole('button',{name:'HOẶC — Một điều kiện',exact:true}).click()
  assert((await dialog.innerText()).includes('Giới tính bằng Nữ'))
  const layout=await dialog.evaluate(el=>({width:el.getBoundingClientRect().width,
    columns:[...el.querySelectorAll('.exclusion-condition-body')].map(row=>row.getBoundingClientRect().left),
    overflow:[...el.querySelectorAll('.exclusion-condition')].some(row=>row.scrollWidth>row.clientWidth)}))
  assert.equal(layout.width,660)
  assert(layout.columns.every(left=>left===layout.columns[0]))
  assert.equal(layout.overflow,false)
  await page.screenshot({path:join(output,'modal-wide.png')})
  await page.evaluate(()=>window.exclusionSmoke.delay=150)
  await dialog.getByRole('button',{name:'Lưu nhóm',exact:true}).dblclick()
  await dialog.waitFor({state:'hidden'})
  assert.equal(await page.evaluate(()=>window.exclusionSmoke.saves),1)
  assert.equal(await page.evaluate(()=>window.exclusionSmoke.value['100'].groupId),50)
  await page.locator('.exclusion-lists summary').click()
  await page.locator('.exclusion-lists').getByRole('checkbox',{name:/^VIP/}).check()
  await page.locator('.exclusion-lists').getByRole('checkbox',{name:/^B/}).check()
  assert.deepEqual(await page.evaluate(()=>window.exclusionSmoke.value['100'].blocklistIds),[4,9])
  await page.locator('.exclusion-lists summary').click()
  await page.screenshot({path:join(output,'card-selected.png')})
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(390,844))
  await page.screenshot({path:join(output,'card-narrow.png')})
  assert(await page.locator('.send-exclusions').evaluate(el=>el.scrollWidth<=el.clientWidth))
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(1100,1000))
  await page.getByRole('button',{name:'Bỏ danh sách 9',exact:true}).click()
  assert.equal(await page.locator('.exclusion-lists').evaluate(el=>el.open),false)
  await page.locator('.exclusion-lists summary').click()
  await page.locator('.exclusion-lists').getByRole('checkbox',{name:/^B/}).check()
  await page.keyboard.press('Escape')
  await page.getByLabel('Từ Zalo nào',{exact:true}).selectOption('101')
  assert.equal(await page.getByRole('button',{name:'Nhóm điều kiện loại trừ',exact:true}).innerText().then(v=>v.includes('Chọn nhóm điều kiện loại trừ')),true)
  await page.getByLabel('Từ Zalo nào',{exact:true}).selectOption('100')
  assert.equal(await page.getByRole('button',{name:'Nhóm điều kiện loại trừ',exact:true}).innerText().then(v=>v.includes('Nhóm #50')),true)
  await page.evaluate(()=>window.exclusionSmoke.fail=true)
  await page.getByRole('button',{name:'Quản lý danh sách'}).click()
  await page.getByRole('alert').filter({hasText:'offline'}).waitFor()
  assert.equal(await page.evaluate(()=>window.exclusionSmoke.value['100'].blocklistIds.length),2)
  await page.evaluate(()=>window.exclusionSmoke.fail=false)
  await page.getByRole('button',{name:'Thử lại'}).click()
  await page.getByRole('button',{name:'Thêm nhóm loại trừ'}).click()
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(390,844))
  await dialog.getByLabel('Tên nhóm',{exact:true}).fill('Nhóm hẹp')
  await dialog.getByLabel('Đã gửi tin trong',{exact:true}).check()
  await page.locator('.exclusion-modal-body').evaluate(el=>el.scrollTop=0)
  await page.screenshot({path:join(output,'modal-narrow.png')})
  await dialog.getByLabel('Đã gửi tin trong',{exact:true}).scrollIntoViewIfNeeded()
  await page.screenshot({path:join(output,'modal-narrow-scrolled.png')})
  assert(await dialog.locator('footer').evaluate(el=>{const rect=el.getBoundingClientRect();return rect.top>=0&&rect.bottom<=innerHeight}))
  await page.evaluate(()=>document.body.classList.remove('theme-light'))
  await page.screenshot({path:join(output,'modal-narrow-dark.png')})
  assert(await page.evaluate(()=>[...document.querySelectorAll('.exclusion-modal, .exclusion-condition')].every(el=>el.scrollWidth<=el.clientWidth)))
  await dialog.getByRole('button',{name:'Lưu nhóm',exact:true}).focus()
  await page.keyboard.press('Tab')
  assert(await dialog.getByRole('button',{name:'Đóng',exact:true}).evaluate(el=>el===document.activeElement))
  await page.keyboard.press('Escape');await dialog.waitFor({state:'hidden'})
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(1100,1000))
  for(const retired of ['operator','field','source','disabled']){
    await page.evaluate(value=>{window.exclusionSmoke.retired=value;window.exclusionSmoke.delay=0},retired)
    await page.getByRole('button',{name:'Quản lý danh sách'}).click()
    const picker=page.getByRole('button',{name:'Nhóm điều kiện loại trừ',exact:true})
    await picker.click()
    await page.getByRole('option',{name:/^Nhóm cũ/}).click()
    await page.getByRole('button',{name:'Sửa nhóm',exact:true}).click()
    if(retired==='disabled')await dialog.getByRole('button',{name:'Bỏ điều kiện Đã gửi tin trong',exact:true}).click()
    else await dialog.getByLabel('Đã gửi tin trong',{exact:true}).click()
    await dialog.getByRole('button',{name:'Lưu nhóm',exact:true}).click()
    await dialog.waitFor({state:'hidden'})
    const saved=await page.evaluate(()=>window.exclusionSmoke.lastSaved)
    assert.equal(saved.rules.length,1,retired)
    assert.equal(saved.rules[0].isEnabled,true,retired)
  }
  assert.deepEqual(errors,[])
  console.log('PASS UI: DB-defined fifth field, AND/OR, create/save single-flight, multiple lists, account isolation, failed reload preserving choices, retry, narrow layout, Escape/focus; remove retired operators/fields/unsupported sources, including disabled rules. Screenshots: '+output)
 }finally{await app?.close();rmSync(dir,{recursive:true,force:true})}
}
main().catch(e=>{console.error(e);process.exitCode=1})
