CREATE OR REPLACE FUNCTION private.aka_agent_staff_scope_for_request()
 RETURNS bigint LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path TO 'pg_catalog'
AS $function$
DECLARE v_claims jsonb; v_user uuid; v_staff bigint;
BEGIN
 IF current_setting('role',true) IS DISTINCT FROM 'aka_agent_desktop' THEN RETURN NULL; END IF;
 BEGIN
  v_claims := NULLIF(current_setting('request.jwt.claims',true),'')::jsonb;
  IF v_claims->>'role' IS DISTINCT FROM 'aka_agent_desktop' THEN RETURN 0; END IF;
  v_user := NULLIF(v_claims->>'sub','')::uuid;
 EXCEPTION WHEN invalid_text_representation THEN RETURN 0;
 END;
 SELECT staff_id INTO v_staff FROM private.aka_agent_desktop_users WHERE auth_user_id=v_user;
 RETURN COALESCE(v_staff,0);
END;
$function$;

CREATE OR REPLACE FUNCTION private.aka_agent_zalo_same_nick_accounts(p_account bigint)
 RETURNS bigint[] LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'pg_catalog', 'public'
AS $function$
 WITH me AS (
  SELECT a.organization_id org, za.zalo_uid zuid, ca.zalo_id czid FROM public.auto_accounts a
   LEFT JOIN public.zalo_accounts za ON za.id=a.zalo_account_id
   LEFT JOIN public.chat_zalo_account_organization ao ON ao.auto_account_id=a.id
   LEFT JOIN public.chat_zalo_account ca ON ca.id=ao.chat_zalo_account_id
  WHERE a.id=p_account)
 SELECT COALESCE(array_agg(DISTINCT x.id ORDER BY x.id),ARRAY[p_account]) FROM (
  SELECT p_account id
  UNION ALL
  SELECT a.id FROM me JOIN public.zalo_accounts za ON za.zalo_uid IN (NULLIF(btrim(me.zuid),''),NULLIF(btrim(me.czid),''))
   JOIN public.auto_accounts a ON a.zalo_account_id=za.id AND a.organization_id=me.org
  UNION ALL
  SELECT ao.auto_account_id FROM me JOIN public.chat_zalo_account ca ON ca.zalo_id IN (NULLIF(btrim(me.zuid),''),NULLIF(btrim(me.czid),''))
   JOIN public.chat_zalo_account_organization ao ON ao.chat_zalo_account_id=ca.id AND ao.organization_id=me.org
 ) x WHERE x.id IS NOT NULL;
$function$;

