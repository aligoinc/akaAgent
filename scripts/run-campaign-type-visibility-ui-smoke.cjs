const assert = require('node:assert/strict')
const { mkdtempSync, writeFileSync, rmSync } = require('node:fs')
const { join, resolve } = require('node:path')
const { tmpdir } = require('node:os')
const { build } = require('esbuild')
const { _electron } = require('playwright')
async function main() {
  const directory = mkdtempSync(join(tmpdir(), 'aka-visibility-ui-'))
  let app
  let checks = 0
  const pass = text => { checks++; console.log('PASS', text) }
  try {
    await build({ entryPoints: [join(__dirname, 'campaign-type-visibility-ui-smoke.tsx')], outdir: directory, bundle: true,
      platform: 'browser', format: 'iife', jsx: 'automatic', target: 'chrome120', define: { 'process.env.NODE_ENV': '"development"' },
      loader: { '.png': 'dataurl', '.svg': 'dataurl' }, logLevel: 'warning' })
    writeFileSync(join(directory, 'index.html'), '<!doctype html><html lang="vi" data-theme="light"><meta charset="utf-8"><link rel="stylesheet" href="campaign-type-visibility-ui-smoke.css"><body class="theme-light"><div id="root"></div><script src="campaign-type-visibility-ui-smoke.js"></script></body></html>')
    writeFileSync(join(directory, 'main.cjs'), `const { app, BrowserWindow } = require('electron'); app.whenReady().then(() => {
      const win = new BrowserWindow({ show: false, width: 1440, height: 1000, webPreferences: { sandbox: true, contextIsolation: true, nodeIntegration: false } });
      win.webContents.session.webRequest.onBeforeRequest((d, cb) => cb({ cancel: /^https?:/.test(d.url) }));
      win.loadFile(${JSON.stringify(join(directory, 'index.html'))}); });`)
    const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE
    app = await _electron.launch({ executablePath: require('electron'), args: [join(directory, 'main.cjs')], cwd: resolve(__dirname, '..'), env })
    const page = await app.firstWindow(); page.setDefaultTimeout(10000)
    await page.setViewportSize({width:1440,height:1000})
    const box = page.locator('.campaign-type-visibility')
    const group = page.getByRole('checkbox', { name: 'Nhóm Zalo', exact: true })
    await group.waitFor()
    const settingsLayout = () => page.evaluate(() => ['.general-settings-modal', '.general-settings-sidebar', '.general-settings-content'].map(selector => {
      const element = document.querySelector(selector)
      const { x, y, width, height } = element.getBoundingClientRect()
      return { x, y, width, height, padding: getComputedStyle(element).padding }
    }))
    const bounds = await settingsLayout()
    await page.getByRole('button', { name: 'Đồng bộ Chat', exact: true }).click()
    assert.deepEqual(await settingsLayout(), bounds)
    await page.getByRole('button', { name: 'Hiển thị loại chiến dịch', exact: true }).click()
    await group.waitFor()
    assert.deepEqual(await settingsLayout(), bounds)
    assert.equal(await page.locator('.ctv-platform').count(),4)
    await page.screenshot({ path: '/tmp/aka-campaign-visibility-desktop.png' })
    pass('existing settings layout stays unchanged across tabs; actual 27-type catalog')
    const item = box.locator('.ctv-items input').first()
    await item.focus(); await page.keyboard.press('Space')
    await page.waitForFunction(() => document.querySelector('input[aria-label="Nhóm Zalo"]').indeterminate)
    assert.equal(await group.getAttribute('aria-checked'),'mixed')
    await box.getByText(/Đã tự lưu/).waitFor()
    pass('keyboard toggle and native indeterminate checkbox')
    await box.getByRole('textbox').fill('zalo_message_phone')
    await group.click(); await box.getByText(/Đã tự lưu/).waitFor()
    const last = await page.evaluate(() => window.visibilitySmoke.state.writes.at(-1))
    assert.equal(last.length,11); assert(last.every(c=>c.visible))
    pass('partial group selects its full catalog during search')
    await group.click(); await box.getByText(/Đã tự lưu/).waitFor()
    await box.getByRole('textbox').fill('')
    await box.getByText(/Đang ẩn toàn bộ loại chiến dịch Zalo/).waitFor()
    await box.getByRole('button',{name:'Hiện tất cả'}).click(); await box.getByText(/Đã tự lưu/).waitFor()
    pass('hide entire platform and restore all')
    await page.evaluate(() => { window.visibilitySmoke.state.hold = true })
    const before = await page.evaluate(() => ({ revision:window.visibilitySmoke.snapshot().revision, refreshes:window.visibilitySmoke.state.refreshes }))
    await item.click(); await page.waitForFunction(() => !!window.visibilitySmoke.state.release)
    assert(await page.getByRole('button',{name:'Đóng',exact:true}).isDisabled())
    assert.equal(await page.evaluate(()=>window.visibilitySmoke.snapshot().revision),before.revision)
    assert.equal(await page.evaluate(()=>window.visibilitySmoke.state.refreshes),before.refreshes)
    await item.click()
    await page.evaluate(()=>{ const s=window.visibilitySmoke.state;s.fail=true;s.hold=false;s.release() })
    await box.getByRole('alert').waitFor(); assert(await item.isChecked())
    await page.evaluate(()=>{ window.visibilitySmoke.state.fail=false })
    await box.getByRole('button',{name:'Thử lại'}).click(); await box.getByText(/Đã tự lưu/).waitFor()
    assert(await item.isChecked())
    pass('failed save keeps latest intent; no list update before acknowledgement; explicit retry')
    await page.evaluate(()=>window.visibilitySmoke.reopen(false)); await group.waitFor()
    assert(await group.isDisabled()); assert(await box.getByRole('textbox').isEnabled())
    await box.getByRole('button',{name:'Thu gọn Zalo'}).click()
    await box.getByRole('button',{name:'Mở rộng Zalo'}).waitFor()
    pass('staff read-only can search and collapse')
    await page.setViewportSize({width:680,height:700})
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
    await page.screenshot({path:'/tmp/aka-campaign-visibility-desktop-small.png'})
    const compactBounds = await settingsLayout()
    await page.getByRole('button', { name: 'Đồng bộ Chat', exact: true }).click()
    assert.deepEqual(await settingsLayout(), compactBounds)
    await page.getByRole('button', { name: 'Hiển thị loại chiến dịch', exact: true }).click()
    await group.waitFor()
    assert.deepEqual(await settingsLayout(), compactBounds)
    pass('compact viewport keeps the existing settings layout and has no horizontal document overflow')
    await page.setViewportSize({width:1440,height:1000})
    await page.evaluate(()=>window.visibilitySmoke.openForm())
    const form = page.locator('.campaign-full-modal')
    await form.getByRole('button',{name:'Zalo',exact:true}).click()
    const action = form.locator('select').first()
    await action.selectOption('zalo_message_phone')
    await page.getByPlaceholder('Nhập tên chiến dịch...').fill('Nội dung chưa lưu')
    await page.evaluate(()=>{ window.visibilitySmoke.state.canEdit=true; window.visibilitySmoke.openSettings() })
    await group.waitFor()
    await box.locator('.ctv-item').filter({hasText:'zalo_message_phone'}).getByRole('checkbox').uncheck()
    await box.getByText(/Đã tự lưu/).waitFor()
    await page.getByRole('dialog',{name:'Cài đặt chung',exact:true}).getByRole('button',{name:'Đóng',exact:true}).click()
    assert.equal(await page.getByPlaceholder('Nhập tên chiến dịch...').inputValue(),'Nội dung chưa lưu')
    assert.equal(await action.inputValue(),'zalo_message_phone')
    assert((await page.evaluate(()=>window.visibilitySmoke.state.reads)).includes(false))
    pass('existing form stays mounted; form snapshot read excludes count query')
    assert.deepEqual(await page.evaluate(()=>window.visibilitySmoke.state.errors),[])
    console.log(`PASS ${checks} Electron scenarios; screenshots /tmp/aka-campaign-visibility-desktop*.png`)
  } finally { await app?.close(); rmSync(directory,{recursive:true,force:true}) }
}
main().catch(error=>{console.error(error);process.exitCode=1})
