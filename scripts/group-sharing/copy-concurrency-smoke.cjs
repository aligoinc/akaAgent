// Isolated PostgreSQL tests for copy-name allocation against the actual V409 RPC.
// No production connections or persistent fixtures.
const fs = require('node:fs'), os = require('node:os'), path = require('node:path'), cp = require('node:child_process'), assert = require('node:assert/strict')
const { Client } = require(require.resolve('pg', { paths: [path.resolve(__dirname, '../../../akaAgentChatApi')] }))
const bin = '/opt/homebrew/opt/postgresql@16/bin', dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sharing-copy-pg-')), port = 55410, clients = []
let started = false
const run = (exe, args) => cp.execFileSync(path.join(bin, exe), args, { stdio: 'pipe' })
const connect = async () => { const c = new Client({ host: dir, port, user: 'postgres', database: 'postgres' }); await c.connect(); clients.push(c); return c }
const scalar = async (c, sql, values) => Object.values((await c.query(sql, values)).rows[0])[0]
const copy = (c, groupId, requestId) => scalar(c, "SELECT aka_agent_group_sharing(2,9,NULL,NULL,'copy',$1::jsonb)", [{ kind: 'content', groupId, requestId }])
async function waitForLock(monitor, pid) {
  for (let i = 0; i < 100; i++) {
    if (await scalar(monitor, "SELECT wait_event_type='Lock' FROM pg_stat_activity WHERE pid=$1", [pid])) return
    await new Promise(resolve => setTimeout(resolve, 10))
  }
  throw new Error('Expected the second writer to wait for a name conflict')
}
async function main() {
  try {
    run('initdb', ['-D', path.join(dir, 'data'), '-U', 'postgres', '-A', 'trust', '--no-locale', '--encoding=UTF8'])
    run('pg_ctl', ['-D', path.join(dir, 'data'), '-l', path.join(dir, 'log'), '-o', `-k ${dir} -p ${port} -c listen_addresses='' -c max_connections=8`, '-w', 'start'])
    started = true
    const a = await connect(), b = await connect(), monitor = await connect()
    await a.query(`
      CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role; CREATE SCHEMA private;
      CREATE TABLE org_organization(id bigint PRIMARY KEY);
      CREATE TABLE org_staff(id bigint PRIMARY KEY,organization_id bigint,name text,is_active boolean,deleted_at timestamptz);
      CREATE TABLE auto_account_contact_groups(id bigint PRIMARY KEY,staff_id bigint,organization_id bigint,purpose text,is_delete boolean);
      CREATE TABLE auto_content_groups(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,staff_id bigint,organization_id bigint,is_delete boolean,is_active boolean,name text,description text,stt integer);
      CREATE TABLE auto_content_templates(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name text,content text,group_id bigint,content_type_id bigint,image_urls text[],channels jsonb,channel_image_urls jsonb,base_content_html text,staff_id bigint,organization_id bigint,is_delete boolean);
      CREATE UNIQUE INDEX uq_auto_content_groups_staff_name_active ON auto_content_groups(staff_id,lower(btrim(name))) WHERE staff_id IS NOT NULL AND is_delete=false;
      CREATE UNIQUE INDEX uq_auto_content_templates_staff_name_active ON auto_content_templates(staff_id,lower(btrim(name))) WHERE is_delete=false;
      CREATE TABLE auto_campaign_data_group_sources(id bigint PRIMARY KEY,group_id bigint,staff_id bigint,organization_id bigint,campaign_id bigint,status text,stop_reason text,stopped_at timestamptz,updated_at timestamptz);
      CREATE FUNCTION auto_assert_automation_identity(bigint,bigint,text,text) RETURNS void LANGUAGE plpgsql AS $$ BEGIN IF NOT EXISTS(SELECT 1 FROM org_staff WHERE id=$1 AND organization_id=$2 AND is_active AND deleted_at IS NULL) THEN RAISE EXCEPTION 'access denied'; END IF; END $$;
      CREATE FUNCTION aka_agent_lock_campaign_input_serialization(bigint) RETURNS void LANGUAGE sql AS $$ SELECT pg_advisory_xact_lock($1) $$;
      INSERT INTO org_organization VALUES(9);
      INSERT INTO org_staff VALUES(1,9,'Owner A',true,NULL),(2,9,'Recipient',true,NULL),(3,9,'Owner B',true,NULL);
    `)
    for (const name of ['schema.sql', 'copy.sql', 'rpc.sql']) await a.query(fs.readFileSync(path.join(__dirname, name), 'utf8'))
    const first = await scalar(a, "INSERT INTO auto_content_groups(name,staff_id,organization_id,is_active,is_delete,sharing_scope) VALUES('Nhóm',1,9,true,false,'organization') RETURNING id")
    const second = await scalar(a, "INSERT INTO auto_content_groups(name,staff_id,organization_id,is_active,is_delete,sharing_scope) VALUES('Nhóm',3,9,true,false,'organization') RETURNING id")
    await a.query("INSERT INTO auto_content_templates(name,content,group_id,staff_id,organization_id,is_delete) VALUES('Mẫu','first',$1,1,9,false),('Mẫu','second',$2,3,9,false)", [first, second])
    const pid = await scalar(b, 'SELECT pg_backend_pid()')
    await a.query('BEGIN')
    const resultA = await copy(a, first, 'copy-a')
    const pendingB = copy(b, second, 'copy-b')
    await waitForLock(monitor, pid)
    await a.query('COMMIT')
    const resultB = await pendingB
    assert.notEqual(resultA.groupId, resultB.groupId)
    assert.deepEqual((await a.query('SELECT name FROM auto_content_groups WHERE staff_id=2 ORDER BY id')).rows.map(row => row.name), ['Nhóm - Bản sao', 'Nhóm - Bản sao (2)'])
    assert.deepEqual((await a.query('SELECT name,content FROM auto_content_templates WHERE staff_id=2 ORDER BY id')).rows, [{ name: 'Mẫu', content: 'first' }, { name: 'Mẫu - Bản sao', content: 'second' }])
    assert.deepEqual(await copy(a, first, 'copy-a'), resultA)
    assert.deepEqual(await copy(b, second, 'copy-b'), resultB)
    assert.equal(await scalar(a, 'SELECT count(*)::int FROM auto_content_templates WHERE staff_id=2'), 2)
    // An ordinary template insert uses the same unique index, without joining
    // any special copy lock. Copy must survive this writer winning the name.
    const third = await scalar(a, "INSERT INTO auto_content_groups(name,staff_id,organization_id,is_active,is_delete,sharing_scope) VALUES('Other group',1,9,true,false,'organization') RETURNING id")
    await a.query("INSERT INTO auto_content_templates(name,content,group_id,staff_id,organization_id,is_delete) VALUES('Manual collision','source',$1,1,9,false)", [third])
    await a.query('BEGIN')
    await a.query("INSERT INTO auto_content_templates(name,content,staff_id,organization_id,is_delete) VALUES('  MANUAL COLLISION  ','manual',2,9,false)")
    const pendingC = copy(b, third, 'copy-c')
    await waitForLock(monitor, pid)
    await a.query('COMMIT')
    const resultC = await pendingC
    assert.equal(await scalar(a, 'SELECT name FROM auto_content_templates WHERE group_id=$1', [resultC.groupId]), 'Manual collision - Bản sao')
    assert.equal(await scalar(a, 'SELECT content FROM auto_content_templates WHERE group_id=$1', [third]), 'source')
    // Different source order must not create opposite waits on overlapping
    // destination template names when whole groups are copied concurrently.
    const fourth = await scalar(a, "INSERT INTO auto_content_groups(name,staff_id,organization_id,is_active,is_delete,sharing_scope) VALUES('Batch A',1,9,true,false,'organization') RETURNING id")
    const fifth = await scalar(a, "INSERT INTO auto_content_groups(name,staff_id,organization_id,is_active,is_delete,sharing_scope) VALUES('Batch B',3,9,true,false,'organization') RETURNING id")
    await a.query("INSERT INTO auto_content_templates(name,content,group_id,staff_id,organization_id,is_delete) VALUES('Overlap A','a',$1,1,9,false),('Overlap B','b',$1,1,9,false),('Overlap B','b',$2,3,9,false),('Overlap A','a',$2,3,9,false)", [fourth, fifth])
    const batches = await Promise.all([copy(a, fourth, 'batch-a'), copy(b, fifth, 'batch-b')])
    assert.deepEqual(batches.map(result => result.count), [2, 2])
    assert.equal(await scalar(a, "SELECT count(*)::int FROM auto_content_templates WHERE staff_id=2 AND name LIKE 'Overlap %'"), 4)
    console.log('PASS concurrent same-named copies, overlapping template orders, ordinary-create race, case/space collisions and idempotent retries')
  } finally {
    await Promise.allSettled(clients.map(client => client.end()))
    if (started) run('pg_ctl', ['-D', path.join(dir, 'data'), '-m', 'immediate', '-w', 'stop'])
    fs.rmSync(dir, { recursive: true, force: true })
  }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
