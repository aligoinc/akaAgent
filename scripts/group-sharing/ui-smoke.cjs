const assert = require('node:assert/strict')
const fs = require('node:fs'), path = require('node:path'), os = require('node:os')
const { build } = require('esbuild')
const { _electron, chromium } = require('playwright')
const root = path.resolve(__dirname, '../..')
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'group-sharing-ui-'))
async function checkPanel(page) {
 const trigger = page.getByRole('button', { name: 'Chia sẻ', exact: true })
 await trigger.waitFor()
 assert.equal(await page.getByLabel('Chia sẻ trong tổ chức', { exact: true }).count(), 0)
 assert.equal(await page.evaluate(() => window.sharingUi.state.calls.filter(c => c.method === 'getSharing').length), 0)
 await trigger.click()
 await page.getByRole('dialog', { name: 'Chia sẻ nhóm' }).waitFor()
 const centered = await page.locator('dialog.group-sharing-dialog').evaluate(element => {
  const rect = element.getBoundingClientRect()
  return Math.abs(rect.left + rect.width / 2 - innerWidth / 2) < 2 && Math.abs(rect.top + rect.height / 2 - innerHeight / 2) < 2
 })
 assert.equal(centered, true)
 await page.getByLabel('Chia sẻ trong tổ chức', { exact: true }).check()
 await page.getByLabel('Chọn nhân viên', { exact: true }).check()
 await page.getByLabel('Tìm nhân viên để chia sẻ').fill('Lan')
 assert.equal(await page.getByLabel(/Minh Trần/).count(), 0)
 await page.getByLabel(/Lan Nguyễn/).check()
 await page.getByRole('button', { name: 'Lưu chia sẻ', exact: true }).click()
 await page.getByRole('dialog', { name: 'Chia sẻ nhóm' }).waitFor({state:'detached'})
 assert.deepEqual(await page.evaluate(() => window.sharingUi.state.recipients), [8])
 assert.equal(await trigger.evaluate(element => element === document.activeElement), true)
 await page.evaluate(() => { window.sharingUi.state.conflict = true })
 await trigger.click()
 await page.getByRole('button', { name: 'Lưu chia sẻ', exact: true }).click()
 await page.getByRole('alert').getByText(/Cấu hình chia sẻ đã thay đổi/).waitFor()
 await page.keyboard.press('Escape')
 await page.getByRole('dialog', { name: 'Chia sẻ nhóm' }).waitFor({state:'detached'})
 await page.evaluate(() => { window.sharingUi.state.conflict = false; window.sharingUi.state.fail = true })
 await trigger.click()
 await page.getByRole('alert').getByText('Lỗi tải tạm thời').waitFor()
 await page.evaluate(() => { window.sharingUi.state.fail = false })
 await page.getByRole('button', { name: 'Tải lại', exact: true }).click()
 await page.getByLabel('Chia sẻ trong tổ chức', { exact: true }).waitFor()
 await page.keyboard.press('Escape')
 await page.evaluate(() => window.sharingUi.select(2))
 await page.locator('.group-sharing-badge').getByText('Chủ nhóm', { exact: true }).waitFor()
 assert.equal(await trigger.count(), 0)
 await page.getByRole('button', { name: 'Sao chép nhóm về kho riêng' }).click()
 await page.waitForFunction(() => window.sharingUi.state.calls.some(c => c.method === 'copy'))
 // A pending owner response must not reopen the dialog after selecting a shared group.
 await page.evaluate(() => { window.sharingUi.state.hold = true; window.sharingUi.select(1) })
 await trigger.click()
 await page.waitForFunction(() => window.sharingUi.state.releases.length === 1)
 await page.evaluate(() => window.sharingUi.select(2))
 await page.getByRole('dialog', { name: 'Chia sẻ nhóm' }).waitFor({state:'detached'})
 await page.evaluate(() => window.sharingUi.release())
 assert.equal(await page.getByLabel('Chia sẻ trong tổ chức', { exact: true }).count(), 0)
 assert.equal(await trigger.count(), 0)
 console.log('PASS sharing dialog: lazy load, save/close/focus, CAS conflict, Escape, load retry, recipient, copy, stale request')
}
