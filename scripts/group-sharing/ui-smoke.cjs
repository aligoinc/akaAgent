  assert.equal(await page.getByRole('tab',{name:/Đồng bộ ngoài/}).count(),0)
  assert.equal(await page.locator('.data-group-manager-group-row').filter({hasText:'Kho chia sẻ'}).getByTitle('Sửa nhóm').isDisabled(),true)
  assert.equal(await page.getByRole('button',{name:'Chia sẻ',exact:true}).count(),0)
  await page.locator('.data-group-manager-group-row').filter({hasText:'Kho riêng'}).locator('.data-group-manager-group-name').click()
  await page.locator('.data-group-info-name-row').getByRole('button',{name:'Chia sẻ',exact:true}).click()
  await page.getByRole('dialog',{name:'Chia sẻ nhóm'}).waitFor()
  await page.getByLabel('Chia sẻ trong tổ chức', {exact:true}).waitFor()
  await page.screenshot({path:'/tmp/group-sharing-dialog-electron.png'})
  await page.keyboard.press('Escape')
  await page.getByRole('dialog',{name:'Chia sẻ nhóm'}).waitFor({state:'detached'})
  await page.locator('.data-group-info-name-row').getByRole('button',{name:'Chia sẻ',exact:true}).waitFor()
  // Auth changes close the owner's dialog even while its request is pending.
  await page.evaluate(() => { window.sharingUi.state.hold = true })
  await page.getByRole('button',{name:'Chia sẻ',exact:true}).click()
