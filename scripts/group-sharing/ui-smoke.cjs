  await page.getByRole('dialog',{name:'Chia sẻ nhóm'}).waitFor()
  await page.keyboard.press('Escape')
  await page.getByRole('dialog',{name:'Chia sẻ nhóm'}).waitFor({state:'detached'})
  await page.getByRole('button',{name:'Tất cả mẫu',exact:false}).first().click()
  assert.equal(await page.getByRole('button',{name:'Chia sẻ',exact:true}).count(),0)
  await page.evaluate(() => window.sharingUi.show('data'))
  await page.locator('.data-group-manager-group-row').filter({hasText:'Kho chia sẻ'}).waitFor()
