const assert=require('node:assert/strict')
const {mkdtempSync,writeFileSync,rmSync,mkdirSync}=require('node:fs')
const {join,resolve}=require('node:path')
const {tmpdir}=require('node:os')
const {build}=require('esbuild')
const {_electron}=require('playwright')
async function main(){
 const dir=mkdtempSync(join(tmpdir(),'aka-diagnostics-ui-'));let app,page
 try{
  await build({entryPoints:[join(__dirname,'campaign-edit-ui-smoke.tsx')],outdir:dir,bundle:true,platform:'browser',format:'iife',jsx:'automatic',target:'chrome120',define:{'process.env.NODE_ENV':'"development"'},loader:{'.png':'dataurl','.svg':'dataurl'},logLevel:'warning'})
  writeFileSync(join(dir,'index.html'),'<html lang="vi"><meta charset="utf-8"><link rel="stylesheet" href="campaign-edit-ui-smoke.css"><body><div id="root"></div><script src="campaign-edit-ui-smoke.js"></script></body></html>')
  writeFileSync(join(dir,'main.cjs'),`const{app,BrowserWindow}=require('electron');app.whenReady().then(()=>{const w=new BrowserWindow({show:false,width:1600,height:1000,webPreferences:{sandbox:true,contextIsolation:true,nodeIntegration:false}});w.webContents.session.webRequest.onBeforeRequest((d,c)=>c({cancel:/^https?:/.test(d.url)}));w.loadFile(${JSON.stringify(join(dir,'index.html'))})})`)
  const env={...process.env};delete env.ELECTRON_RUN_AS_NODE
  app=await _electron.launch({executablePath:require('electron'),args:[join(dir,'main.cjs')],cwd:resolve(__dirname,'..'),env});page=await app.firstWindow();page.setDefaultTimeout(12000)
  await page.waitForFunction(()=>!!window.editSmoke)
  const row=page.locator('.campaign-table-row').filter({has:page.getByText('Chiến dịch 91',{exact:true})})
  const open=async(label)=> { await row.getByRole('button',{name:'Hành động',exact:true}).click(); await page.getByText(label,{exact:true}).click() }
  await open('Cập nhật giới hạn gửi')
  const gate=page.getByRole('dialog',{name:'Tạm dừng để sửa chiến dịch',exact:true})
  await gate.getByRole('button',{name:'Không',exact:true}).click()
  assert.equal(await page.evaluate(()=>window.editSmoke.state.pauses),0)
  await open('Cập nhật giới hạn gửi');await gate.getByRole('button',{name:'Có',exact:true}).click()
  await gate.getByText('Đang chờ chiến dịch tạm dừng…',{exact:true}).waitFor()
  assert.equal(await page.getByText('Giới hạn hành động',{exact:true}).count(),0)
  await page.evaluate(()=>window.editSmoke.ready())
  await gate.waitFor({state:'hidden'})
  await page.getByRole('button',{name:'Lưu',exact:true}).click()
  const choice=page.getByRole('dialog',{name:'Trạng thái sau khi lưu',exact:true})
  await choice.waitFor();assert.equal(await choice.getByRole('button',{name:'Tạm dừng',exact:true}).evaluate(el=>el===document.activeElement),true)
  await choice.getByRole('button',{name:'Đóng',exact:true}).click();assert.equal(await page.evaluate(()=>window.editSmoke.state.writes),0)
  await page.getByRole('button',{name:'Lưu',exact:true}).click()
  await page.evaluate(()=>window.editSmoke.state.failResume=true)
  await choice.getByRole('button',{name:'Chờ xử lý',exact:true}).click()
  await page.getByText(/Cấu hình chiến dịch đã lưu; chưa hoàn tất/).waitFor()
  assert.equal(await page.evaluate(()=>window.editSmoke.state.writes),1)
  await page.locator('.campaign-feedback-modal').getByRole('button',{name:'Đóng',exact:true}).click()
  await page.evaluate(()=>window.editSmoke.state.failResume=false)
  await page.getByRole('button',{name:'Thử lại hoàn tất',exact:true}).click()
  await page.getByText('Đã cập nhật giới hạn gửi.',{exact:true}).waitFor()
  assert.deepEqual(await page.evaluate(()=>({writes:window.editSmoke.state.writes,resumes:window.editSmoke.state.resumes,pauses:window.editSmoke.state.pauses})),{writes:1,resumes:2,pauses:1})
  await page.locator('.campaign-feedback-modal').getByRole('button',{name:'Đóng',exact:true}).click()
  await page.evaluate(()=>window.pendingSmoke.patch(91,{status:'tạm dừng'}))
  await open('Sửa')
  await page.getByRole('button',{name:'Lưu chiến dịch',exact:true}).waitFor()
  await page.getByRole('button',{name:'Lưu chiến dịch',exact:true}).click()
  await choice.waitFor()
  mkdirSync('/tmp/akaagent-edit-ui',{recursive:true});await choice.screenshot({path:'/tmp/akaagent-edit-ui/desktop-save-status.png'})
  await choice.getByRole('button',{name:'Tạm dừng',exact:true}).click()
  await page.getByText('Lưu chiến dịch thành công!',{exact:true}).waitFor()
  assert.equal(await page.evaluate(()=>window.editSmoke.state.writes),2)
  mkdirSync('/tmp/akaagent-edit-ui',{recursive:true});await page.screenshot({path:'/tmp/akaagent-edit-ui/desktop.png'})
  await page.locator('.campaign-feedback-modal').getByRole('button',{name:'Đóng',exact:true}).click()
  await page.locator('.campaign-full-modal').waitFor({state:'hidden'})
  for(const [mode, action] of [['quick','sms_send'],['full','voice_call']]) {
    await page.evaluate(([mode,action])=>window.editSmoke.openMobileEditor(mode,action),[mode,action])
    const save=page.getByRole('button',{name:mode==='full'?'Lưu chiến dịch':'Lưu',exact:true})
    const beforeResume=await page.evaluate(()=>window.editSmoke.state.resumes)
    await save.click();await choice.getByRole('button',{name:'Chờ xử lý',exact:true}).click()
    await page.getByText(/Cấu hình chiến dịch đã lưu, nhưng cập nhật data chưa hoàn tất/).waitFor()
    assert.equal(await page.evaluate(()=>window.editSmoke.state.resumes),beforeResume)
    await page.locator('.campaign-feedback-modal').getByRole('button',{name:'Đóng',exact:true}).click()
    await page.evaluate(()=>window.editSmoke.state.failInputs=false)
    await save.click();await choice.getByRole('button',{name:'Chờ xử lý',exact:true}).click()
    await page.getByText(mode==='full'?'Lưu chiến dịch thành công!':'Đã cập nhật nội dung và media.',{exact:true}).waitFor()
    const writes=await page.evaluate(()=>window.editSmoke.state.mobileWrites)
    assert.equal(writes.length,2)
    assert.equal(writes[0].expectedUpdatedAt,'mobile-original')
    assert.equal(writes[1].expectedUpdatedAt,'mobile-version-1')
    assert.equal(typeof writes[1].retrySmsInputSchedule,'boolean')
    assert.equal(await page.evaluate(()=>window.editSmoke.state.resumes),beforeResume+1)
    await page.locator('.campaign-feedback-modal').getByRole('button',{name:'Đóng',exact:true}).click()
  }
  assert.deepEqual(await page.evaluate(()=>window.pendingSmoke.state.errors),[])
  console.log('PASS Desktop real menu, confirmation, actual release, focus, cancel save, retry-only activation and SMS/voice partial-save retry in quick/full forms')
 }catch(e){if(page)console.error((await page.locator('body').innerText()).slice(-10000));throw e}
 finally{if(app)await app.close();rmSync(dir,{recursive:true,force:true})}
}
main().catch(e=>{console.error(e);process.exitCode=1})
