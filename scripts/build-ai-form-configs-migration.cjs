// Build the migration from captured live rows and unchanged TypeScript schemas.
const fs = require('node:fs'), path = require('node:path'), os = require('node:os')
const assert = require('node:assert/strict'), crypto = require('node:crypto')
const { buildSync } = require('esbuild')
const root = path.resolve(__dirname, '..')
const dir = path.join(root, 'migrations/snapshots/ai-form-configs-v416')
const snapshot = JSON.parse(fs.readFileSync(path.join(dir, 'source.json'), 'utf8'))
assert.equal(snapshot.table_exists, null)
assert.equal(snapshot.guard_signature, null)
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'form-ai-schema-'))
function readSchema(name, symbol) {
  const output = path.join(tmp, `${name}.cjs`)
  buildSync({ entryPoints: [path.join(root, `src/shared/${name}.ts`)], bundle: true, platform: 'node', format: 'cjs', outfile: output })
  return require(output)[symbol]
}
const schemas = {
  app_campaign_schedule: readSchema('campaignScheduleAi', 'SCHEDULE_AI_SCHEMA'),
  app_campaign_action_limits: readSchema('campaignLimitsAi', 'LIMITS_AI_SCHEMA')
}
fs.rmSync(tmp, { recursive: true })
const q = value => "'" + String(value).replace(/'/g, "''") + "'"
fs.writeFileSync(path.join(dir, 'schemas.json'), JSON.stringify(schemas, null, 2) + '\n')
const sql = `-- V416: one form configuration per section; preserve live prompts and wire schemas.
-- Generated by scripts/build-ai-form-configs-migration.cjs from the captured source.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';
DO $preflight$
BEGIN
  IF to_regclass('public.ai_form_configs') IS NOT NULL
    OR to_regprocedure('private.validate_ai_form_config()') IS NOT NULL THEN
    RAISE EXCEPTION 'V416 objects already exist; do not overwrite or reapply';
  END IF;
  PERFORM id FROM public.ai_using WHERE code IN ('app_campaign_schedule','app_campaign_action_limits') ORDER BY id FOR SHARE;
  PERFORM id FROM public.ai_prompt WHERE id IN (49,52) ORDER BY id FOR SHARE;
  IF (SELECT count(*) FROM public.ai_using WHERE code IN ('app_campaign_schedule','app_campaign_action_limits')) <> 2 THEN
    RAISE EXCEPTION 'V416 source count changed';
  END IF;
${snapshot.source.map(s => `  IF (SELECT md5(to_jsonb(u)::text) FROM public.ai_using u WHERE id=${s.using.id}) IS DISTINCT FROM ${q(s.using_md5)}
    OR (SELECT md5(to_jsonb(p)::text) FROM public.ai_prompt p WHERE id=${s.prompt.id}) IS DISTINCT FROM ${q(s.prompt_md5)} THEN
    RAISE EXCEPTION 'V416 live source changed: ${s.using.code}';
  END IF;`).join('\n')}
END $preflight$;

CREATE TABLE public.ai_form_configs (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  code text NOT NULL UNIQUE CHECK (code ~ '^[a-z][a-z0-9_]{0,119}$'),
  name text NOT NULL CHECK (btrim(name) <> ''),
  desktop_section_id text UNIQUE CHECK (desktop_section_id IS NULL OR btrim(desktop_section_id) <> ''),
  web_section_id text UNIQUE CHECK (web_section_id IS NULL OR btrim(web_section_id) <> ''),
  mobile_section_id text UNIQUE CHECK (mobile_section_id IS NULL OR btrim(mobile_section_id) <> ''),
  prompt_system text,
  prompt_user text NOT NULL DEFAULT '',
  output_schema jsonb NOT NULL CHECK (jsonb_typeof(output_schema) = 'object'),
  model_id bigint NOT NULL REFERENCES public.ai_model(id),
  campaign_scope text NOT NULL DEFAULT 'all' CHECK (campaign_scope IN ('all','selected')),
  campaign_action_ids text[] NOT NULL DEFAULT '{}',
  is_active boolean NOT NULL DEFAULT true,
  is_reasoning boolean NOT NULL DEFAULT false,
  timeout_ms integer NOT NULL DEFAULT 120000 CHECK (timeout_ms BETWEEN 1000 AND 120000),
  response_parser text NOT NULL DEFAULT 'auto',
  response_path text,
  request_options jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(request_options) = 'object'),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (num_nonnulls(desktop_section_id,web_section_id,mobile_section_id) > 0),
  CHECK (btrim(coalesce(prompt_system,'')) <> '' OR btrim(prompt_user) <> ''),
  CHECK ((campaign_scope='all' AND cardinality(campaign_action_ids)=0)
    OR (campaign_scope='selected' AND cardinality(campaign_action_ids)>0)),
  CHECK (cardinality(campaign_action_ids)=0 OR array_ndims(campaign_action_ids)=1),
  CHECK (array_position(campaign_action_ids,NULL) IS NULL)
);
CREATE INDEX ai_form_configs_model_idx ON public.ai_form_configs(model_id);

-- New signature verified absent in the source snapshot; no existing RPC is replaced.
CREATE FUNCTION private.validate_ai_form_config() RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER SET search_path = ''
AS $guard$
BEGIN
  IF EXISTS (SELECT 1 FROM unnest(NEW.campaign_action_ids) a(id)
    LEFT JOIN public.auto_campaign_actions c ON c.id=a.id
    WHERE c.id IS NULL OR c.is_delete IS TRUE) THEN
    RAISE EXCEPTION 'Unknown campaign action in AI configuration' USING ERRCODE='23514';
  END IF;
  IF cardinality(NEW.campaign_action_ids) <> (SELECT count(DISTINCT id) FROM unnest(NEW.campaign_action_ids) a(id)) THEN
    RAISE EXCEPTION 'Duplicate campaign action in AI configuration' USING ERRCODE='23514';
  END IF;
  IF EXISTS (SELECT 1 FROM public.ai_model WHERE id=NEW.model_id AND organization_id IS NOT NULL) THEN
    RAISE EXCEPTION 'Form AI requires a global model' USING ERRCODE='23514';
  END IF;
  NEW.updated_at := now();
  RETURN NEW;
END $guard$;
REVOKE ALL ON FUNCTION private.validate_ai_form_config() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION private.validate_ai_form_config() TO service_role;
CREATE TRIGGER ai_form_configs_validate BEFORE INSERT OR UPDATE ON public.ai_form_configs
FOR EACH ROW EXECUTE FUNCTION private.validate_ai_form_config();

ALTER TABLE public.ai_form_configs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.ai_form_configs FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.ai_form_configs TO anon, authenticated;
GRANT ALL ON public.ai_form_configs TO service_role;
REVOKE ALL ON SEQUENCE public.ai_form_configs_id_seq FROM PUBLIC, anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.ai_form_configs_id_seq TO service_role;
CREATE POLICY ai_form_configs_active_read ON public.ai_form_configs
FOR SELECT TO anon, authenticated USING (is_active);

ALTER TABLE public.ai_log ADD COLUMN form_config_id bigint REFERENCES public.ai_form_configs(id);
CREATE INDEX ai_log_form_config_idx ON public.ai_log(form_config_id) WHERE form_config_id IS NOT NULL;

${snapshot.source.map(s => {
  const section = s.using.code === 'app_campaign_schedule' ? 'campaign.schedule' : 'campaign.action_limits'
  return `INSERT INTO public.ai_form_configs
  (code,name,desktop_section_id,web_section_id,prompt_system,prompt_user,output_schema,model_id,is_active,
   is_reasoning,timeout_ms,response_parser,response_path,request_options)
SELECT u.code,p.name,${q(section)},${q(section)},p.prompt_system,p.prompt_user,
  ${q(JSON.stringify(schemas[s.using.code]))}::jsonb,u.model_id,u.is_active,
  p.is_reasoning,u.timeout_ms,u.response_parser,u.response_path,u.request_options
FROM public.ai_using u JOIN public.ai_prompt p ON p.id=u.prompt_id WHERE u.id=${s.using.id};`
}).join('\n\n')}

DO $verify$
BEGIN
  IF (SELECT count(*) FROM public.ai_form_configs) <> 2 OR EXISTS (
    SELECT 1 FROM public.ai_form_configs f
    JOIN public.ai_using u ON u.code=f.code JOIN public.ai_prompt p ON p.id=u.prompt_id
    WHERE f.prompt_system IS DISTINCT FROM p.prompt_system OR f.prompt_user IS DISTINCT FROM p.prompt_user
      OR f.model_id IS DISTINCT FROM u.model_id OR f.request_options IS DISTINCT FROM u.request_options
      OR f.timeout_ms IS DISTINCT FROM u.timeout_ms OR f.is_reasoning IS DISTINCT FROM p.is_reasoning
      OR f.response_parser IS DISTINCT FROM u.response_parser OR f.response_path IS DISTINCT FROM u.response_path
  ) THEN RAISE EXCEPTION 'V416 copy mismatch'; END IF;
END $verify$;
NOTIFY pgrst, 'reload schema';
COMMIT;
`
fs.writeFileSync(path.join(root, 'migrations/migration_v416_ai_form_configs.sql'), sql)
console.log('Generated V416; schemas SHA256:', crypto.createHash('sha256').update(JSON.stringify(schemas)).digest('hex'))
