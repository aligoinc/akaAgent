DECLARE v_results jsonb := '[]'::jsonb; v_r jsonb; v_member bigint;
BEGIN
  DELETE FROM public.auto_account_contact_group_member_origins
   WHERE membership_id IN (SELECT id FROM public.auto_account_contact_group_members WHERE group_id IN (600, 601));
  DELETE FROM public.auto_account_contact_group_members WHERE group_id IN (600, 601);
  DELETE FROM public.auto_account_contact_dynamic_filter_queue WHERE contact_id BETWEEN 2001 AND 2005;
  UPDATE public.auto_account_contact_groups SET revision = 0 WHERE id IN (600, 601);
  UPDATE public.auto_account_contact_group_dynamic_filters SET matched_count = 0, last_entered_count = 0, last_exited_count = 0 WHERE id IN (610, 611);
  UPDATE public.auto_account_contacts SET is_delete = false WHERE id BETWEEN 2001 AND 2005;
  DELETE FROM private.fixture_scope_matches WHERE filter_id IN (610, 611);
  -- Bước 1: 2001–2003 vào A, 2003 vào cả B, 2004 chưa khớp.
  INSERT INTO private.fixture_scope_matches VALUES (610, 2001, 'enter', true), (610, 2002, 'enter', true), (610, 2003, 'enter', true),
    (611, 2003, 'enter', true), (610, 2004, 'enter', false);
  INSERT INTO public.auto_account_contact_dynamic_filter_queue (contact_id, staff_id, organization_id, queued_at, last_event_at)
  SELECT id, 1, 1, clock_timestamp() - interval '1 minute', clock_timestamp() FROM unnest(ARRAY[2001, 2002, 2003, 2004, 2005]) AS id;
  v_r := public.aka_agent_process_data_group_dynamic_filters_core(1, 1, 50);
  v_results := v_results || jsonb_build_array(v_r);
  -- Bước 2: 2002 khớp luật rời, 2004 vào, 2005 bị xóa; 2001 có thêm nguồn nhập tay rồi thôi khớp (ở lại nhóm, không rời).
  SELECT id INTO v_member FROM public.auto_account_contact_group_members WHERE group_id = 600 AND contact_id = 2001;
  INSERT INTO public.auto_account_contact_group_member_origins (membership_id, kind, source_name_snapshot, is_current)
  VALUES (v_member, 'upload', 'Nhập tay', true);
  UPDATE private.fixture_scope_matches SET matches = false WHERE filter_id = 610 AND contact_id = 2001;
  INSERT INTO private.fixture_scope_matches VALUES (610, 2002, 'leave', true);
  UPDATE private.fixture_scope_matches SET matches = true WHERE filter_id = 610 AND contact_id = 2004;
  UPDATE public.auto_account_contacts SET is_delete = true WHERE id = 2005;
  INSERT INTO public.auto_account_contact_dynamic_filter_queue (contact_id, staff_id, organization_id, queued_at, last_event_at)
  SELECT id, 1, 1, clock_timestamp() - interval '1 minute', clock_timestamp() FROM unnest(ARRAY[2001, 2002, 2004, 2005]) AS id;
  v_r := public.aka_agent_process_data_group_dynamic_filters_core(1, 1, 50);
  v_results := v_results || jsonb_build_array(v_r);
