const assert = require('node:assert/strict')
const { mkdtempSync, writeFileSync, rmSync } = require('node:fs')
const { join, resolve } = require('node:path')
const { tmpdir } = require('node:os')
const { build } = require('esbuild')
const { _electron } = require('playwright')

async function main() {
  const directory = mkdtempSync(join(tmpdir(), 'akaagent-desktop-ui-'))
  let app
  let page
  try {
    await build({ entryPoints: [join(__dirname, 'desktop-ui-reads-smoke.tsx')], outdir: directory,
      bundle: true, platform: 'browser', format: 'iife', jsx: 'automatic', target: 'chrome120',
      define: { 'process.env.NODE_ENV': '"development"' }, loader: { '.png': 'dataurl', '.svg': 'dataurl' }, logLevel: 'warning',
    })
    writeFileSync(join(directory, 'index.html'), '<!doctype html><html lang="vi"><meta charset="utf-8"><link rel="stylesheet" href="desktop-ui-reads-smoke.css"><body><div id="root"></div><script src="desktop-ui-reads-smoke.js"></script></body></html>')
    writeFileSync(join(directory, 'main.cjs'), `const { app, BrowserWindow } = require('electron'); app.whenReady().then(() => {
      const win = new BrowserWindow({ show: false, width: 1600, height: 1100, webPreferences: { sandbox: true, contextIsolation: true, nodeIntegration: false } });
      win.webContents.session.webRequest.onBeforeRequest((details, callback) => callback({ cancel: /^https?:/.test(details.url) }));
      win.loadFile(${JSON.stringify(join(directory, 'index.html'))});
    });`)
    const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE
    app = await _electron.launch({ executablePath: require('electron'), args: [join(directory, 'main.cjs')], cwd: resolve(__dirname, '..'), env })
    page = await app.firstWindow()
    page.setDefaultTimeout(15000)

    await page.waitForFunction(() => window.desktopSmoke?.store.getState().campaignPage?.total === 1205)
    const store = expression => page.evaluate(expression)
    const count = method => page.evaluate(method => window.desktopSmoke.state.calls.filter(call => call.method === method).length, method)
    const settled = () => page.waitForFunction(() => {
      const s = window.desktopSmoke.store.getState()
      return !s.campaignPageDirty && s.campaignPageResultKey === JSON.stringify(s.campaignPageQuery)
    })
    await settled()
    assert.equal(await page.locator('.campaign-table-row').count(), 100)
    const beforeOpen = await count('getDesktopCampaignPage')
    await page.getByText('Campaign 1', { exact: true }).first().click()
    await settled()
    assert.equal(await count('getDesktopCampaignPage'), beforeOpen, 'opening an already loaded row must not reload page progress')
    await page.locator('.campaign-table-row').first().getByRole('checkbox').check()
    await page.getByRole('button', { name: 'Trang chiến dịch sau' }).click()
    await settled()
    await page.waitForFunction(() => window.desktopSmoke.store.getState().campaignPage.page === 2)
    assert.equal(await store(() => window.desktopSmoke.store.getState().campaignPageQuery.selectedId), 1)
    assert.equal(await store(() => window.desktopSmoke.store.getState().campaigns.length), 101)
    assert.ok((await page.locator('.campaign-list-pager').innerText()).includes('Đã chọn 1'))
    await page.getByRole('checkbox', { name: 'Chọn tất cả chiến dịch', exact: true }).check()
    await page.waitForFunction(() => document.querySelector('.campaign-list-pager').textContent.includes('Đã chọn 1205'))
    assert.equal(await count('getDesktopCampaignSelection'), 3)
    assert.equal(await count('listDesktopCampaignCatalog'), 0)
    console.log('PASS 100-row pages, pinned detail, cross-page selection of 1205, no catalog during list reads')

    await page.getByTitle('Tiếp tục các chiến dịch đang tạm dừng').click()
    await page.waitForFunction(() => window.desktopSmoke.state.calls.filter(call => call.method === 'updateCampaign').length === 1205)
    await settled()
    await page.waitForFunction(() => !document.querySelector('.campaign-list-pager').textContent.includes('Đã chọn'))
    assert.equal(await page.getByRole('checkbox', { name: 'Chọn tất cả chiến dịch', exact: true }).isChecked(), false)
    console.log('PASS bulk resume includes selected campaigns across all 13 pages and clears selection')

    await page.clock.install()
    await page.clock.pauseAt(new Date())
    const sourceTab = page.getByRole('button', { name: 'Chiến dịch tìm data (1)', exact: true })
    const initialSources = await count('getDesktopCampaignSources')
    await store(() => { window.desktopSmoke.state.sources = { 1: [999] } })
    await page.getByTitle('Làm mới', { exact: true }).click()
    await settled()
    await sourceTab.waitFor()
    assert.equal(await count('getDesktopCampaignSources'), initialSources + 1)
    // A config event for an off-page source must update the currently open target.
    await store(() => {
      window.desktopSmoke.state.sources = { 1: [] }
      for (let i = 0; i < 10; i++) window.desktopSmoke.store.getState().upsertCampaign({ id: 999, invalidateConfig: true })
    })
    await page.clock.runFor(301)
    await settled()
    await sourceTab.waitFor({ state: 'hidden' })
    assert.equal(await count('getDesktopCampaignSources'), initialSources + 2)
    await store(async () => {
      window.desktopSmoke.state.sources = { 1: [999] }
      await window.desktopSmoke.store.getState().updateCampaign(999, { extraSettings: { findDataPhoneTargetCampaignIds: [1] } })
    })
    await sourceTab.waitFor()
    assert.equal(await count('getDesktopCampaignSources'), initialSources + 3)
    // Keep one request in flight; obsolete results cannot erase a newer link set.
    await store(() => { window.desktopSmoke.state.hold = 'sources'; window.desktopSmoke.state.sources = { 1: [] } })
    await page.getByTitle('Làm mới', { exact: true }).click()
    await page.waitForFunction(() => !!window.desktopSmoke.state.release)
    await store(async () => {
      window.desktopSmoke.state.sources = { 1: [888] }
      await window.desktopSmoke.store.getState().loadCampaigns({ refreshSources: true })
      await window.desktopSmoke.store.getState().loadCampaigns({ refreshSources: true })
    })
    assert.equal(await count('getDesktopCampaignSources'), initialSources + 4)
    await store(() => { window.desktopSmoke.state.hold = null; window.desktopSmoke.state.release(); window.desktopSmoke.state.release = null })
    await page.waitForFunction(count => window.desktopSmoke.state.calls.filter(c => c.method === 'getDesktopCampaignSources').length === count, initialSources + 5)
    await sourceTab.waitFor()
    assert.equal(await count('getDesktopCampaignSources'), initialSources + 5)
    console.log('PASS sources refresh on manual reload/config changes, event bursts coalesce and pending reads serialize')

    const search = page.getByPlaceholder('Tìm tên chiến dịch...')
    const selectAll = page.getByRole('checkbox', { name: 'Chọn tất cả chiến dịch', exact: true })
    const selectionsBeforeSearch = await count('getDesktopCampaignSelection')
    await search.fill('Campaign 1205')
    assert.equal(await selectAll.isDisabled(), true, 'select all disabled before search debounce applies')
    assert.equal(await page.locator('.campaign-table-row').first().getByRole('checkbox').isDisabled(), true)
    await selectAll.dispatchEvent('click')
    assert.equal(await count('getDesktopCampaignSelection'), selectionsBeforeSearch)
    await page.clock.runFor(301)
    await settled()
    await selectAll.check()
    await page.waitForFunction(() => document.querySelector('.campaign-list-pager').textContent.includes('Đã chọn 1'))
    assert.ok(!(await page.locator('.campaign-list-pager').innerText()).includes('Đã chọn 1205'))
    await store(() => window.desktopSmoke.ui.setState({ showConfirm: message => { window.desktopSmoke.state.confirmation = message } }))
    await page.getByTitle('Xoá các chiến dịch đã chọn').click()
    await page.waitForFunction(() => !!window.desktopSmoke.state.confirmation)
    assert.equal(await store(() => window.desktopSmoke.state.confirmation), 'Xoá 1 chiến dịch đã chọn?')
    await search.fill('')
    await page.clock.runFor(301)
    await settled()
    assert.ok(!(await page.locator('.campaign-list-pager').innerText()).includes('Đã chọn'))
    await store(() => { window.desktopSmoke.state.hold = 'selection' })
    await selectAll.click()
    await page.waitForFunction(() => !!window.desktopSmoke.state.release)
    await search.fill('Campaign 1205')
    await page.clock.runFor(301)
    await settled()
    await store(() => { window.desktopSmoke.state.hold = null; window.desktopSmoke.state.release(); window.desktopSmoke.state.release = null })
    await page.clock.runFor(1)
    assert.ok(!(await page.locator('.campaign-list-pager').innerText()).includes('Đã chọn'), 'stale selection response discarded')
    await search.fill('')
    await page.clock.runFor(301)
    await settled()
    await page.getByRole('button', { name: 'Trang chiến dịch sau' }).click()
    await settled()
    console.log('PASS debounce selection guard, deletion limited to filtered selection, stale async selection discarded')

    await store(() => window.dispatchEvent(new Event('focus')))
    await settled()
    const beforeAccounts = await count('getDesktopAccountSnapshot')
    const beforeCampaigns = await count('getDesktopCampaignPage')
    const beforePeriodicSources = await count('getDesktopCampaignSources')
    await page.clock.runFor(30050)
    await settled()
    assert.equal(await count('getDesktopAccountSnapshot'), beforeAccounts + 1)
    assert.equal(await count('getDesktopCampaignPage'), beforeCampaigns + 1)
    await store(() => { window.dispatchEvent(new Event('focus')); document.dispatchEvent(new Event('visibilitychange')) })
    await page.clock.runFor(100)
    assert.equal(await count('getDesktopCampaignPage'), beforeCampaigns + 1)
    const a0 = await count('getDesktopAccountSnapshot')
    await store(() => { for (let i = 0; i < 10; i++) window.desktopSmoke.accountEvent() })
    await page.clock.runFor(299)
    assert.equal(await count('getDesktopAccountSnapshot'), a0)
    await page.clock.runFor(2)
    assert.equal(await count('getDesktopAccountSnapshot'), a0 + 1)
    assert.equal(await count('getDesktopCampaignSources'), beforePeriodicSources, 'periodic polling must not reread source links')
    console.log('PASS shared coordinator, 30s/30s defaults, fresh focus skips reads, event burst coalesced at 300ms')

    await store(() => window.desktopSmoke.polling.setState({ settings: { accounts: 45, campaigns: 60 } }))
    const a1 = await count('getDesktopAccountSnapshot'), c1 = await count('getDesktopCampaignPage')
    await page.clock.runFor(45010)
    assert.equal(await count('getDesktopAccountSnapshot'), a1 + 1)
    assert.equal(await count('getDesktopCampaignPage'), c1)
    await page.clock.runFor(15010)
    assert.equal(await count('getDesktopCampaignPage'), c1 + 1)
    await store(() => { window.desktopSmoke.state.hidden = true; document.dispatchEvent(new Event('visibilitychange')) })
    const hiddenA = await count('getDesktopAccountSnapshot'), hiddenC = await count('getDesktopCampaignPage')
    await page.clock.runFor(120000)
    assert.equal(await count('getDesktopAccountSnapshot'), hiddenA)
    assert.equal(await count('getDesktopCampaignPage'), hiddenC)
    await store(() => { window.desktopSmoke.state.hidden = false; document.dispatchEvent(new Event('visibilitychange')) })
    await page.clock.runFor(1)
    await settled()
    assert.equal(await count('getDesktopAccountSnapshot'), hiddenA + 1)
    assert.equal(await count('getDesktopCampaignPage'), hiddenC + 1)
    console.log('PASS independent intervals, hidden window pauses, visible resumes once without catch-up')

    await store(() => { window.desktopSmoke.state.hold = 'campaign'; void window.desktopSmoke.store.getState().loadCampaigns({ silent: true }) })
    await page.waitForFunction(() => !!window.desktopSmoke.state.release)
    const inflightC = await count('getDesktopCampaignPage')
    await store(() => {
      for (let i=0;i<10;i++) void window.desktopSmoke.store.getState().loadCampaigns({ silent: true, passive: true })
      window.desktopSmoke.store.getState().upsertCampaign({ id: 1, status: 'đang chạy', updatedAt: '2099-01-01T00:00:00Z' })
    })
    assert.equal(await count('getDesktopCampaignPage'), inflightC)
    await store(() => { window.desktopSmoke.state.hold = null; window.desktopSmoke.state.release(); window.desktopSmoke.state.release = null })
    await page.clock.runFor(310)
    await settled()
    assert.equal(await count('getDesktopCampaignPage'), inflightC + 1)
    assert.equal(await store(() => window.desktopSmoke.store.getState().campaigns.find(row => row.id === 1).status), 'đang chạy')
    console.log('PASS passive in-flight dedupe and state event during pending read produces one follow-up, retains newer state')

    await store(() => { window.desktopSmoke.state.hold = 'account'; void window.desktopSmoke.store.getState().loadAccounts({ silent: true, invalidate: false }) })
    await page.waitForFunction(() => !!window.desktopSmoke.state.release)
    const pendingA = await count('getDesktopAccountSnapshot')
    const beforeHeldAccountEvent = await count('getDesktopCampaignPage')
    await store(() => window.desktopSmoke.store.getState().upsertCampaign({ id: 2, status: 'hoàn thành', updatedAt: '2099-01-01T00:00:00Z' }))
    await page.clock.runFor(301)
    await settled()
    assert.equal(await count('getDesktopCampaignPage'), beforeHeldAccountEvent + 1, 'campaign event must not wait for the slow account read')
    await store(async () => {
      for (let i=0;i<5;i++) void window.desktopSmoke.store.getState().loadAccounts({ silent: true, invalidate: false })
      await window.desktopSmoke.store.getState().updateAccount(41, { name: 'Edited account' })
      window.desktopSmoke.state.hold = null; window.desktopSmoke.state.release(); window.desktopSmoke.state.release = null
    })
    await page.waitForFunction(() => window.desktopSmoke.store.getState().accounts[0]?.name === 'Edited account' && window.desktopSmoke.store.getState().accountCatalogVersion === 'b'.repeat(32))
    assert.equal(await count('getDesktopAccountSnapshot'), pendingA + 1)
    console.log('PASS account read dedupe, metadata edit during pending read is preserved')

    await store(async () => { window.desktopSmoke.state.failPage = true; await window.desktopSmoke.store.getState().loadCampaigns({ silent: true }) })
    await page.getByRole('alert').filter({ hasText: 'Fixture page error' }).waitFor()
    assert.equal(await page.locator('.campaign-table-row').count(), 0)
    await store(() => { window.desktopSmoke.state.failPage = false })
    await page.getByRole('button', { name: 'Thử lại', exact: true }).click()
    await settled()
    assert.equal(await page.locator('.campaign-table-row').count(), 100)
    assert.equal(await store(() => window.desktopSmoke.store.getState().campaignPage.page), 2)
    assert.equal(await count('getDesktopPollingSettings'), 1)
    assert.deepEqual(await store(() => window.desktopSmoke.state.errors), [])
    await page.locator('.campaign-work-area').screenshot({ path: '/tmp/aka-desktop-ui-audit/campaign-page.png' })
    console.log('PASS page error/retry preserves page/detail/filters; settings fetched once')
    const unknownBefore = await count('getDesktopCampaignPage')
    await store(() => window.desktopSmoke.store.getState().upsertCampaign({ id: 999, status: 'đang chạy', note: null, updatedAt: new Date().toISOString() }))
    await page.clock.runFor(301)
    await settled()
    await store(() => { for (let n=0;n<10;n++) window.desktopSmoke.store.getState().upsertCampaign({ id: 999, status: 'đang chạy', note: null, updatedAt: '2099-01-01T00:00:00Z' }) })
    await page.clock.runFor(301)
    assert.equal(await count('getDesktopCampaignPage'), unknownBefore + 1)
    console.log('PASS repeated off-page log/status signals do not cause repeated list reads')
  } finally { if (app) await app.close(); rmSync(directory, { recursive: true, force: true }) }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
