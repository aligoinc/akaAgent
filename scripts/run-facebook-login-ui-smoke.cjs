const {build}=require('esbuild')
const fs=require('node:fs')
const path=require('node:path')
const os=require('node:os')
const assert=require('node:assert/strict')
const {_electron}=require('playwright')
const directory=fs.mkdtempSync(path.join(os.tmpdir(),'aka-facebook-ui-'))
async function main(){
  const root=path.resolve(__dirname,'..')
  await build({entryPoints:[path.join(__dirname,'fixtures/facebook-login-ui.tsx')],outfile:path.join(directory,'ui.js'),bundle:true,platform:'browser',format:'iife',jsx:'automatic',define:{'import.meta.env.BASE_URL':'"./"'},loader:{'.woff2':'dataurl','.woff':'dataurl','.ttf':'dataurl','.png':'dataurl','.svg':'dataurl'},logLevel:'warning'})
  fs.writeFileSync(path.join(directory,'index.html'),'<!doctype html><html lang="vi"><meta charset="utf-8"><link rel="stylesheet" href="ui.css"><body class="theme-light"><div id="root"></div><script src="ui.js"></script></body></html>')
  fs.writeFileSync(path.join(directory,'main.cjs'),`const {app,BrowserWindow}=require('electron');app.setPath('userData',${JSON.stringify(path.join(directory,'profile'))});app.whenReady().then(()=>{const w=new BrowserWindow({show:false,width:1200,height:900,webPreferences:{sandbox:true}});w.loadFile(${JSON.stringify(path.join(directory,'index.html'))});});`)
  fs.copyFileSync(path.join(root,'src/renderer/public/facebook_accounts_template.xlsx'),path.join(directory,'facebook_accounts_template.xlsx'))
  const env={...process.env};delete env.ELECTRON_RUN_AS_NODE
  const app=await _electron.launch({args:[path.join(directory,'main.cjs')],env})
  try{
    const page=await app.firstWindow(),errors=[]
    page.on('pageerror',error=>errors.push(error.message))
    await page.getByRole('heading',{name:'Đăng nhập FB tự động với 2FA'}).waitFor()
    const text=page.getByLabel('Danh sách tài khoản')
    assert.equal(await page.getByRole('button',{name:'Bắt đầu đăng nhập'}).count(),0)
    assert.equal(await page.getByText('Chỉ dùng cookie:',{exact:false}).isVisible(),false)
    await page.getByText('Xem thêm định dạng nhập',{exact:true}).click()
    assert(await page.getByText('Chỉ dùng cookie:',{exact:false}).isVisible())
    await page.getByText('Xem thêm định dạng nhập',{exact:true}).click()
    await page.screenshot({path:'/tmp/akaagent-facebook-import-input.png'})
    await text.fill('100000000001111|secret-password|JBSWY3DPEHPK3PXP\n100000000002222|second-password|JBSWY3DPEHPK3PXP')
    await page.getByRole('button',{name:'Kiểm tra danh sách'}).click()
    await page.getByRole('cell',{name:'100000000001111',exact:true}).waitFor()
    assert.equal(await text.count(),0,'collapse input after preview')
    assert(!(await page.locator('body').innerText()).includes('secret-password'))
    assert.equal(await page.getByRole('button',{name:'Kiểm tra danh sách'}).count(),0)
    assert.equal(await page.locator('tbody tr').first().getByText('Sẵn sàng',{exact:true}).count(),1,'do not repeat status as the description')
    await page.screenshot({path:'/tmp/akaagent-facebook-import-preview.png'})
    await page.getByRole('button',{name:'Bắt đầu đăng nhập'}).click()
    await page.getByRole('button',{name:'Dừng',exact:true}).waitFor()
    assert.equal(await page.getByRole('button',{name:'Nhập lại danh sách'}).count(),0,'running input cannot be replaced')
    assert.equal(await page.getByRole('button',{name:'Bắt đầu đăng nhập'}).count(),0)
    await page.getByText('Đã xử lý 0/2',{exact:true}).waitFor()
    await page.evaluate(()=>window.facebookFixture.progress([
      {status:'success',name:'Tài khoản mẫu 1',message:'Thành công'},
      {status:'running',message:'Đang xác thực bằng mã 2FA…'}
    ],true))
    await page.getByText('Đã xử lý 1/2',{exact:true}).waitFor()
    assert.equal(await page.getByRole('progressbar').getAttribute('value'),'1')
    await page.getByText('Thành công 1',{exact:true}).waitFor()
    await page.evaluate(()=>window.facebookFixture.progress([
      {},{status:'failed',message:'Facebook yêu cầu xác minh thêm. Hãy đăng nhập thủ công.'}
    ],false))
    await page.getByText('Đã xử lý 2/2',{exact:true}).waitFor()
    await page.getByText('Thất bại 1',{exact:true}).waitFor()
    assert(await page.getByText('Facebook yêu cầu xác minh thêm. Hãy đăng nhập thủ công.',{exact:true}).isVisible())
    assert.equal(await page.getByRole('button',{name:'Bắt đầu đăng nhập'}).count(),0)
    await page.screenshot({path:'/tmp/akaagent-facebook-import-result.png'})
    // The requested 60% layout keeps its actions visible at the app's minimum size.
    await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(1000,700))
    const layout=await page.getByRole('dialog').evaluate(dialog=>{
      const rect=dialog.getBoundingClientRect(),footer=dialog.querySelector('footer').getBoundingClientRect()
      return {width:rect.width,viewport:innerWidth,footerBottom:footer.bottom,height:innerHeight}
    })
    assert(Math.abs(layout.width-layout.viewport*.6)<2)
    assert(layout.footerBottom<=layout.height)
    await page.screenshot({path:'/tmp/akaagent-facebook-import-minimum.png'})
    await page.evaluate(()=>document.body.classList.remove('theme-light'))
    await page.screenshot({path:'/tmp/akaagent-facebook-import-dark.png'})
    await page.evaluate(()=>document.body.classList.add('theme-light'))
    await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(1200,900))
    await page.getByRole('button',{name:'Nhập lại danh sách'}).click()
    assert.equal(await text.inputValue(),'','new input must not restore old credentials')
    await text.fill(Array.from({length:3},(_,i)=>`${100000000003333+i}|pass|JBSWY3DPEHPK3PXP`).join('\n'))
    await page.getByRole('button',{name:'Kiểm tra danh sách'}).click()
    await page.getByRole('button',{name:'Bắt đầu đăng nhập'}).click()
    await page.getByRole('button',{name:'Dừng',exact:true}).waitFor()
    await page.evaluate(()=>window.facebookFixture.progress([{status:'success',message:'Thành công'},{status:'running',message:'Đang đăng nhập…'},{}],true))
    await page.getByRole('button',{name:'Dừng',exact:true}).click()
    await page.getByText('Đã xử lý 1/3',{exact:true}).waitFor()
    await page.getByText('Đã dừng 2',{exact:true}).waitFor()
    assert.equal(await page.getByRole('progressbar').getAttribute('value'),'1','cancelled accounts are not processed')
    assert.equal(await page.locator('tbody tr').nth(1).getByText('Đã dừng',{exact:true}).count(),1)
    assert.equal(await page.locator('tbody tr').nth(1).locator('.facebook-row-message').count(),0)
    await page.getByRole('button',{name:'Nhập lại danh sách'}).click()
    await page.locator('input[type=file]').setInputFiles(path.join(directory,'facebook_accounts_template.xlsx'))
    await page.getByText('facebook_accounts_template.xlsx · 0 dòng').waitFor()
    assert(await page.getByRole('button',{name:'Kiểm tra danh sách'}).isDisabled(),'guide examples must not be imported')
    await text.fill(Array.from({length:11},(_,i)=>`${100000000001111+i}|pass|JBSWY3DPEHPK3PXP`).join('\n'))
    await page.getByRole('button',{name:'Kiểm tra danh sách'}).click()
    await page.getByText(/Vượt giới hạn/).waitFor()
    assert(await page.getByRole('button',{name:'Bắt đầu đăng nhập'}).isDisabled())
    await page.screenshot({path:'/tmp/akaagent-facebook-import-ui.png'})
    await page.evaluate(()=>window.facebookFixture.credentials(false))
    await page.getByRole('button',{name:'Đăng nhập bằng 2FA',exact:true}).waitFor()
    assert.equal(await page.getByRole('button',{name:'Lưu',exact:true}).count(),0)
    await page.getByLabel('Mật khẩu (chưa lưu)',{exact:true}).fill('fixture-password')
    await page.getByLabel('Khóa 2FA (chưa lưu)',{exact:true}).fill('JBSWY3DPEHPK3PXP')
    await page.screenshot({path:'/tmp/akaagent-facebook-existing-login.png'})
    await page.getByRole('button',{name:'Đăng nhập bằng 2FA',exact:true}).click()
    await page.getByRole('status').waitFor()
    assert(await page.getByRole('button',{name:'Hủy',exact:true}).isDisabled())
    await page.evaluate(()=>window.facebookFixture.finishLogin('Lượt đăng nhập thử thất bại'))
    await page.getByRole('alert').waitFor()
    await page.getByRole('heading',{name:'Lỗi',exact:true}).waitFor()
    await page.screenshot({path:'/tmp/akaagent-facebook-login-result-error.png'})
    await page.getByRole('button',{name:'Đóng',exact:true}).click()
    assert.equal(await page.getByLabel('Mật khẩu (chưa lưu)',{exact:true}).inputValue(),'fixture-password')
    await page.getByRole('button',{name:'Đăng nhập bằng 2FA',exact:true}).click()
    await page.getByRole('status').waitFor()
    await page.evaluate(()=>window.facebookFixture.finishLogin())
    await page.getByText('Đã đóng form',{exact:true}).waitFor()
    await page.getByRole('heading',{name:'Thành công',exact:true}).waitFor()
    await page.getByRole('button',{name:'Đóng',exact:true}).click()
    const manualCalls=await page.evaluate(()=>window.facebookFixture.credentialCalls)
    assert.equal(manualCalls.length,2);assert(manualCalls.every(c=>c.action==='login'&&c.id===40&&c.input.revision===0))
    await page.evaluate(()=>window.facebookFixture.credentials(true))
    await page.getByRole('button',{name:'Lưu',exact:true}).waitFor()
    await page.getByRole('button',{name:'Đăng nhập bằng 2FA',exact:true}).click()
    await page.getByRole('status').waitFor()
    const savedCall=await page.evaluate(()=>window.facebookFixture.credentialCalls[0])
    assert.deepEqual(savedCall.input,{uid:'100000000001111',revision:1},'blank fields reuse saved credentials')
    await page.evaluate(()=>window.facebookFixture.finishLogin())
    await page.getByText('Đã đóng form',{exact:true}).waitFor()
    await page.getByRole('heading',{name:'Thành công',exact:true}).waitFor()
    await page.getByRole('button',{name:'Đóng',exact:true}).click()
    // Closing a busy form is immediate; a late result still notifies and cannot close a new form.
    for(const error of [undefined,'Lỗi sau khi đóng form']) {
      await page.evaluate(()=>window.facebookFixture.credentials(true))
      await page.getByRole('button',{name:'Đăng nhập bằng 2FA',exact:true}).click()
      await page.getByRole('status').waitFor()
      const close=page.getByRole('button',{name:'Đóng form thông tin đăng nhập',exact:true})
      assert(await close.isEnabled())
      await close.click()
      await page.getByText('Đã đóng form',{exact:true}).waitFor()
      await page.evaluate(()=>window.facebookFixture.credentials(true,41,'Tài khoản khác'))
      await page.getByRole('heading',{name:'Thông tin đăng nhập · Tài khoản khác'}).waitFor()
      await page.evaluate(error=>window.facebookFixture.finishLogin(error),error)
      await page.getByRole('heading',{name:error?'Lỗi':'Thành công',exact:true}).waitFor()
      await page.getByRole('button',{name:'Đóng',exact:true}).click()
      assert(await page.getByRole('heading',{name:'Thông tin đăng nhập · Tài khoản khác'}).isVisible())
      assert.equal(await page.getByRole('alert').count(),0,'old failure does not change the new form')
      await page.getByRole('button',{name:'Đóng form thông tin đăng nhập',exact:true}).click()
    }
    await page.evaluate(()=>window.facebookFixture.credentials(true,42,'Đang tải thông tin',true))
    await page.getByRole('heading',{name:'Thông tin đăng nhập · Đang tải thông tin'}).waitFor()
    assert(await page.getByRole('button',{name:'Đăng nhập bằng 2FA',exact:true}).isDisabled())
    await page.getByRole('button',{name:'Đóng form thông tin đăng nhập',exact:true}).click()
    await page.getByText('Đã đóng form',{exact:true}).waitFor()
    assert.deepEqual(errors,[])
    console.log('PASS Facebook import UI and existing-account 2FA: manual/managed logged-in accounts, busy/error/retry, stored credentials, result modals, closing busy/hung forms, late responses cannot close a newer form, unchanged account ID and clean console')
  }finally{await app.close()}
}
main().catch(error=>{console.error(error);process.exitCode=1}).finally(()=>fs.rmSync(directory,{recursive:true,force:true}))
